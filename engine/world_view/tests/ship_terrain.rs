//! The bricks of a planet (a ship with terrain), made by the client from the ship's generator and its stored bricks, and drawn under the ship's pose.

use std::collections::HashMap;
use std::sync::Arc;

use block_models::BlockTable;
use terrain::TerrainGenerator;
use voxel_grid::Grid;
use voxel_meshing::PackedBrickMesh;
use voxel_space::{
    BrickBox, BrickCoordinate, FaceDirection, GridId, VoxelCoordinate, WorldPosition,
};
use world_storage::test_support::brick;
use world_view::{MeshUpdate, ShipTerrainMesher, ShipTerrainSource, ViewChannels, ViewSettings};

mod common;

use common::{LitBrick, Scene, scene};

const PLANET: GridId = GridId::new(GridId::FIRST_ALLOCATED + 2);

/// A viewer in the middle of a brick.
fn at(x: i64, y: i64, z: i64) -> WorldPosition {
    WorldPosition::new(brick(x, y, z), [16.0; 3])
}

/// Applies the updates for a ship the way a renderer would, saying so if any is not for the ship.
fn apply(live: &mut HashMap<BrickCoordinate, PackedBrickMesh>, updates: Vec<MeshUpdate>) {
    for update in updates {
        match update {
            MeshUpdate::UploadGridBrick {
                grid,
                coordinate,
                mesh,
            } => {
                assert_eq!(grid, PLANET);
                if mesh.is_empty() {
                    live.remove(&coordinate);
                } else {
                    live.insert(coordinate, mesh);
                }
            }
            MeshUpdate::RemoveGridBrick { grid, coordinate } => {
                assert_eq!(grid, PLANET);
                live.remove(&coordinate);
            }
            other => panic!("not an update of a brick of the planet: {other:?}"),
        }
    }
}

/// The generator the scene's world gives its terrain, which is what the planet is generated by too.
fn generator_of(scene: &Scene) -> Arc<dyn TerrainGenerator> {
    let terrain = &scene.world.main().terrain;
    Arc::clone(
        terrain
            .generators()
            .entry(terrain.default_generator())
            .unwrap()
            .content()
            .unwrap(),
    )
}

fn planet_mesher(scene: &Scene, radius: i64) -> ShipTerrainMesher {
    let mut opaque = vec![true; 16];
    opaque[scene.air as usize] = false;
    ShipTerrainMesher::new(
        PLANET,
        ViewSettings {
            view_radius_bricks: radius,
            worker_count: 3,
        },
        ViewChannels::new(scene.material, None, None),
        Arc::new(BlockTable::of_cubes(&opaque)),
    )
}

fn no_edits(scene: &Scene) -> Grid {
    Grid::new(Arc::clone(scene.world.main().overrides.layout()))
}

fn extent_around_the_origin(radius: u32) -> BrickBox {
    BrickBox::around(BrickCoordinate::ORIGIN, radius)
}

#[test]
fn a_planet_is_meshed_exactly_as_the_terrain_of_a_level_with_the_same_ground() {
    let mut scene = scene();
    scene.assign_around(brick(0, 0, 0), 6);
    let mut terrain_mesher = scene.mesher(3);
    let mut as_terrain: HashMap<BrickCoordinate, PackedBrickMesh> = HashMap::new();
    for update in terrain_mesher.settle(scene.world.main(), brick(0, 0, 0)) {
        if let MeshUpdate::Upload { coordinate, mesh } = update
            && !mesh.is_empty()
        {
            as_terrain.insert(coordinate, mesh);
        }
    }

    let voxels = no_edits(&scene);
    let source = ShipTerrainSource::new(
        &voxels,
        Some(generator_of(&scene)),
        extent_around_the_origin(8),
    );
    let mut mesher = planet_mesher(&scene, 3);
    let mut as_ship = HashMap::new();
    apply(&mut as_ship, mesher.settle(&source, at(0, 0, 0)));

    assert_eq!(as_ship.len(), 29);
    let mut ship_bricks: Vec<_> = as_ship.keys().copied().collect();
    let mut terrain_bricks: Vec<_> = as_terrain.keys().copied().collect();
    ship_bricks.sort();
    terrain_bricks.sort();
    assert_eq!(ship_bricks, terrain_bricks);
    for (coordinate, mesh) in &as_terrain {
        assert_eq!(&as_ship[coordinate], mesh, "{coordinate:?}");
    }
}

#[test]
fn a_stored_brick_of_a_planet_is_drawn_instead_of_the_generated_one_and_a_change_to_it_is_drawn_again()
 {
    let scene = scene();
    let mut voxels = no_edits(&scene);
    let generator = generator_of(&scene);
    let extent = extent_around_the_origin(8);
    let mut mesher = planet_mesher(&scene, 3);
    let mut live = HashMap::new();
    {
        let source = ShipTerrainSource::new(&voxels, Some(Arc::clone(&generator)), extent);
        apply(&mut live, mesher.settle(&source, at(0, 0, 0)));
    }
    let plain = live[&brick(0, 0, 0)].clone();

    // A block built on the ground: stored as the generated brick with the block in it, as the server stores it.
    let marble = scene.game.raw_block("base_blocks:stone");
    let mut stored = generator.generate_brick(voxels.layout(), brick(0, 0, 0));
    stored.set(
        scene.material,
        VoxelCoordinate::new(5, 10, 5).split().1,
        marble,
    );
    voxels
        .insert_brick(brick(0, 0, 0), Arc::new(stored))
        .unwrap();
    mesher.brick_changed(brick(0, 0, 0));
    {
        let source = ShipTerrainSource::new(&voxels, Some(Arc::clone(&generator)), extent);
        apply(&mut live, mesher.settle(&source, at(0, 0, 0)));
    }
    assert_ne!(
        live[&brick(0, 0, 0)],
        plain,
        "the block on the ground is drawn"
    );
    // The bricks beside it are meshed again too, and are as they were (the block is not at their edge).
    assert_eq!(live.len(), 29);
}

#[test]
fn beyond_the_extent_there_is_nothing_so_the_edge_of_a_planet_shows_its_side() {
    let scene = scene();
    let voxels = no_edits(&scene);
    let source = ShipTerrainSource::new(
        &voxels,
        Some(generator_of(&scene)),
        extent_around_the_origin(1),
    );
    let mut mesher = planet_mesher(&scene, 3);
    let mut live = HashMap::new();
    apply(&mut live, mesher.settle(&source, at(0, 0, 0)));

    // Only the bricks of the ground that are inside the extent are drawn: the 3 x 3 of the surface and the 3 x 3 of the stone under it (whose underside is
    // against the nothing below the extent, and so is drawn).
    let mut shown: Vec<_> = live.keys().copied().collect();
    shown.sort();
    let mut expected: Vec<_> = (-1..=1)
        .flat_map(|x| (-1..=0).flat_map(move |y| (-1..=1).map(move |z| brick(x, y, z))))
        .collect();
    expected.sort();
    assert_eq!(shown, expected);
    // The brick at the +x edge has a face against the nothing beyond it, which the one in the middle does not.
    let faces_toward = |coordinate: BrickCoordinate, direction: FaceDirection| {
        live[&coordinate]
            .quads
            .iter()
            .map(|quad| quad.unpack())
            .filter(|quad| quad.face == direction)
            .count()
    };
    assert!(faces_toward(brick(1, 0, 0), FaceDirection::PositiveX) > 0);
    assert_eq!(faces_toward(brick(0, 0, 0), FaceDirection::PositiveX), 0);
    assert!(faces_toward(brick(0, -1, 0), FaceDirection::NegativeY) > 0);
}

#[test]
fn a_planet_whose_generator_this_program_lacks_draws_nothing() {
    let scene = scene();
    let voxels = no_edits(&scene);
    let source = ShipTerrainSource::new(&voxels, None, extent_around_the_origin(8));
    let mut mesher = planet_mesher(&scene, 3);
    let mut live = HashMap::new();
    apply(&mut live, mesher.settle(&source, at(0, 0, 0)));
    assert!(live.is_empty());
}

#[test]
fn a_planet_is_drawn_again_with_the_light_a_game_gives_it_when_the_game_changes_it() {
    let scene = scene();
    let voxels = no_edits(&scene);
    let source = ShipTerrainSource::new(
        &voxels,
        Some(generator_of(&scene)),
        extent_around_the_origin(8),
    );
    let mut mesher = planet_mesher(&scene, 2);
    let mut live = HashMap::new();
    apply(&mut live, mesher.settle(&source, at(0, 0, 0)));
    let light_of_origin = |live: &HashMap<BrickCoordinate, PackedBrickMesh>| {
        live[&brick(0, 0, 0)]
            .quads
            .iter()
            .map(|quad| quad.unpack().light)
            .max()
    };
    // (A game with no light draws everything as bright as it can.)
    assert_eq!(light_of_origin(&live), Some(255));

    // A hook that lights the brick: every brick is drawn again with it, and what is on the screen stays until the new picture is ready.
    let hook = Arc::new(LitBrick {
        lit: brick(0, 0, 0),
        brightness: 100,
    });
    mesher.set_channels(scene.channels_lit_by(&hook));
    apply(&mut live, mesher.settle(&source, at(0, 0, 0)));
    assert_eq!(light_of_origin(&live), Some(100));
}

#[test]
fn resetting_the_mesher_takes_down_every_brick_it_showed() {
    let scene = scene();
    let voxels = no_edits(&scene);
    let source = ShipTerrainSource::new(
        &voxels,
        Some(generator_of(&scene)),
        extent_around_the_origin(8),
    );
    let mut mesher = planet_mesher(&scene, 3);
    let mut live = HashMap::new();
    apply(&mut live, mesher.settle(&source, at(0, 0, 0)));
    assert_eq!(live.len(), 29);
    apply(&mut live, mesher.reset());
    assert!(live.is_empty());
}
