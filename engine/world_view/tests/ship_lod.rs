const PLANET: GridId = GridId::new(GridId::FIRST_ALLOCATED + 2);

/// What the renderer holds of a terrain, as the updates say.
#[derive(Debug, Default, PartialEq)]
struct Screen {
    bricks: HashMap<BrickCoordinate, PackedBrickMesh>,
    nodes: HashMap<BrickCube, PackedBrickMesh>,
}

impl Screen {
    fn put_brick(&mut self, coordinate: BrickCoordinate, mesh: PackedBrickMesh) {
        if mesh.is_empty() {
            self.bricks.remove(&coordinate);
        } else {
            self.bricks.insert(coordinate, mesh);
        }
    }

    fn put_node(&mut self, cube: BrickCube, mesh: PackedBrickMesh) {
        if mesh.is_empty() {
            self.nodes.remove(&cube);
        } else {
            self.nodes.insert(cube, mesh);
        }
    }

    /// The updates for a level.
    fn apply_level(&mut self, updates: Vec<MeshUpdate>) {
        for update in updates {
            match update {
                MeshUpdate::Upload { coordinate, mesh } => self.put_brick(coordinate, mesh),
                MeshUpdate::Remove(coordinate) => {
                    self.bricks.remove(&coordinate);
                }
                MeshUpdate::UploadCoarse { cube, mesh } => self.put_node(cube, mesh),
                MeshUpdate::RemoveCoarse(cube) => {
                    self.nodes.remove(&cube);
                }
                other => panic!("not an update of a level: {other:?}"),
            }
        }
    }

    /// The updates for the planet, which must all say so.
    fn apply_planet(&mut self, updates: Vec<MeshUpdate>) {
        for update in updates {
            match update {
                MeshUpdate::UploadGridBrick {
                    grid,
                    coordinate,
                    mesh,
                } => {
                    assert_eq!(grid, PLANET);
                    self.put_brick(coordinate, mesh);
                }
                MeshUpdate::RemoveGridBrick { grid, coordinate } => {
                    assert_eq!(grid, PLANET);
                    self.bricks.remove(&coordinate);
                }
                MeshUpdate::UploadGridCoarse { grid, cube, mesh } => {
                    assert_eq!(grid, PLANET);
                    self.put_node(cube, mesh);
                }
                MeshUpdate::RemoveGridCoarse { grid, cube } => {
                    assert_eq!(grid, PLANET);
                    self.nodes.remove(&cube);
                }
                other => panic!("not an update of the planet's terrain: {other:?}"),
            }
        }
    }
}

fn settings() -> LodSettings {
    LodSettings {
        detail: DetailSettings {
            cell_pixels: 3.0,
            pixel_size: 2.0 * 0.700_207_538_209_062_3 / 1080.0,
        },
        zoom: None,
        maximum_distance: 1500.0,
    }
}

fn config() -> LodConfig {
    LodConfig {
        unlit: 0,
        worker_count: 3,
    }
}

fn viewer_in(at: BrickCoordinate) -> WorldPosition {
    WorldPosition::new(at, [16.0, 20.0, 16.0])
}

/// The generator the scene's world gives its terrain, which is what the planet is generated by too.
fn generator_of(scene: &Scene) -> Arc<dyn TerrainGenerator> {
    let terrain = &scene.world.main().terrain;
    Arc::clone(
        terrain
            .generators()
            .entry(terrain.default_generator())
            .unwrap()
            .content()
            .unwrap(),
    )
}

fn table_of(scene: &Scene) -> Arc<BlockTable> {
    let mut opaque = vec![true; 16];
    opaque[scene.air as usize] = false;
    Arc::new(BlockTable::of_cubes(&opaque))
}

fn view_settings() -> ViewSettings {
    ViewSettings {
        view_radius_bricks: 3,
        worker_count: 3,
    }
}

fn detailed_planet(scene: &Scene) -> ShipTerrainMesher {
    ShipTerrainMesher::with_detail(
        PLANET,
        view_settings(),
        ViewChannels::new(scene.material, None, None),
        table_of(scene),
        config(),
        settings(),
    )
}

fn no_edits(scene: &Scene) -> Grid {
    Grid::new(Arc::clone(scene.world.main().overrides.layout()))
}

/// What a level's terrain with the scene's ground shows to a viewer at the origin.
fn level_screen(scene: &mut Scene) -> Screen {
    scene.assign_around(brick(0, 0, 0), 10);
    let mut view = LodView::new(scene.mesher(3), config());
    let mut screen = Screen::default();
    screen.apply_level(view.settle(
        GridId::MAIN,
        scene.world.main(),
        viewer_in(brick(0, 0, 0)),
        &settings(),
    ));
    screen
}

/// Whether any brick of the cube is in the box.
fn meets(extent: BrickBox, cube: BrickCube) -> bool {
    let origin = cube.origin();
    let last = cube.edge_length() as i128 - 1;
    BrickBox::new(
        origin,
        BrickCoordinate::new(origin.x() + last, origin.y() + last, origin.z() + last),
    )
    .is_some_and(|whole| extent.intersection(whole).is_some())
}

#[test]
fn a_planet_is_drawn_in_detail_exactly_as_the_terrain_of_a_level_with_the_same_ground() {
    let mut scene = scene();
    let as_level = level_screen(&mut scene);
    assert!(as_level.nodes.len() > 20 && as_level.bricks.len() > 20);

    let voxels = no_edits(&scene);
    let source = ShipTerrainSource::new(
        &voxels,
        Some(generator_of(&scene)),
        BrickBox::around(BrickCoordinate::ORIGIN, 100_000),
    );
    let mut planet = detailed_planet(&scene);
    // Not settled while there is work: the first update has made nothing yet.
    let mut as_ship = Screen::default();
    as_ship.apply_planet(planet.update(&source, viewer_in(brick(0, 0, 0))));
    assert!(!planet.is_settled());
    as_ship.apply_planet(planet.settle(&source, viewer_in(brick(0, 0, 0))));

    // The same bricks and the same nodes, picture for picture.
    let mut ship_bricks: Vec<_> = as_ship.bricks.keys().copied().collect();
    let mut level_bricks: Vec<_> = as_level.bricks.keys().copied().collect();
    ship_bricks.sort();
    level_bricks.sort();
    assert_eq!(ship_bricks, level_bricks);
    assert_eq!(as_ship, as_level);
    assert!(planet.is_settled());
}

#[test]
fn what_is_drawn_of_a_planet_with_an_extent_is_what_is_drawn_of_the_ground_without_one_that_meets_the_extent()
 {
    let mut scene = scene();
    let unbounded = level_screen(&mut scene);
    let voxels = no_edits(&scene);
    let mut seen_a_cube_that_only_reaches_in_by_its_last_brick = false;
    let mut seen_a_cube_that_only_reaches_in_by_its_first_brick = false;
    // The ground goes on for ever in this world; the planet's is cut off a few bricks from the origin each way, at one place after another, so that the cubes that
    // are drawn end at it at every offset.
    for radius in 6..=21 {
        let extent = BrickBox::around(BrickCoordinate::ORIGIN, radius);
        let source = ShipTerrainSource::new(&voxels, Some(generator_of(&scene)), extent);
        let mut planet = detailed_planet(&scene);
        let mut screen = Screen::default();
        screen.apply_planet(planet.settle(&source, viewer_in(brick(0, 0, 0))));

        // The nodes: those of the ground without an extent that have a brick inside it, and no others.
        let mut expected: Vec<BrickCube> = unbounded
            .nodes
            .keys()
            .copied()
            .filter(|cube| meets(extent, *cube))
            .collect();
        let mut drawn: Vec<BrickCube> = screen.nodes.keys().copied().collect();
        expected.sort_by_key(|cube| (cube.level(), cube.origin()));
        drawn.sort_by_key(|cube| (cube.level(), cube.origin()));
        assert_eq!(drawn, expected, "radius {radius}");
        // The bricks: those with ground, inside it.
        let mut expected: Vec<BrickCoordinate> = unbounded
            .bricks
            .keys()
            .copied()
            .filter(|coordinate| extent.contains(*coordinate))
            .collect();
        let mut drawn: Vec<BrickCoordinate> = screen.bricks.keys().copied().collect();
        expected.sort();
        drawn.sort();
        assert_eq!(drawn, expected, "radius {radius}");

        for cube in screen.nodes.keys() {
            let edge = cube.edge_length() as i128;
            let origin = cube.origin();
            let last = |coordinate: i128| coordinate + edge - 1;
            let along = [
                (origin.x(), last(origin.x())),
                (origin.y(), last(origin.y())),
                (origin.z(), last(origin.z())),
            ];
            let (low, high) = (extent.min(), extent.max());
            let (low, high) = ([low.x(), low.y(), low.z()], [high.x(), high.y(), high.z()]);
            for axis in 0..3 {
                let (first, last) = along[axis];
                seen_a_cube_that_only_reaches_in_by_its_last_brick |=
                    first < low[axis] && last == low[axis];
                seen_a_cube_that_only_reaches_in_by_its_first_brick |=
                    last > high[axis] && first == high[axis];
            }
        }
    }
    // (The cases above include the ones where a cube's only brick in the extent is its first or its last along an axis: the ends of the cube are the ends of the test.)
    assert!(seen_a_cube_that_only_reaches_in_by_its_last_brick);
    assert!(seen_a_cube_that_only_reaches_in_by_its_first_brick);
}

