/// A planet's terrain that says nothing of its core, so that a view of it draws what is behind the horizon too.
struct WithoutCore<'a>(ShipTerrainSource<'a>);

impl TerrainSource for WithoutCore<'_> {
    fn known(&self, coordinate: BrickCoordinate) -> Option<Arc<Brick>> {
        self.0.known(coordinate)
    }

    fn generator_for(&self, coordinate: BrickCoordinate) -> Option<Arc<dyn TerrainGenerator>> {
        self.0.generator_for(coordinate)
    }

    fn layout(&self) -> &Arc<GridLayout> {
        self.0.layout()
    }
}

impl CoarseTerrainSource for WithoutCore<'_> {
    fn version(&self) -> u64 {
        self.0.version()
    }

    fn may_show(&self, cube: BrickCube) -> bool {
        self.0.may_show(cube)
    }

    fn coarse_generator(&self, cube: BrickCube) -> Option<Arc<dyn TerrainGenerator>> {
        self.0.coarse_generator(cube)
    }
}

/// A round planet, 600 voxels in radius, made of the scene's blocks.
fn round_planet(scene: &Scene) -> Arc<dyn TerrainGenerator> {
    let materials = SurfaceLayers {
        air: scene.air,
        deep: scene.game.raw_block("base_blocks:stone"),
        subsurface: scene.game.raw_block("base_blocks:dirt"),
        surface: scene.game.raw_block("base_blocks:grass"),
    };
    Arc::new(ball(600.0, scene.material, materials))
}

/// How far the nearest point of a node is from a place, in voxels.
fn distance_to_node(cube: BrickCube, from: [f64; 3]) -> f64 {
    let edge = cube.edge_length() as f64 * 32.0;
    let origin = cube.origin();
    let along = |first: i128, at: f64| {
        let low = first as f64 * 32.0;
        (low - at).max(at - (low + edge)).max(0.0)
    };
    let (x, y, z) = (
        along(origin.x(), from[0]),
        along(origin.y(), from[1]),
        along(origin.z(), from[2]),
    );
    (x * x + y * y + z * z).sqrt()
}

fn settle_a_view(
    scene: &Scene,
    source: &impl CoarseTerrainSource,
    viewer: WorldPosition,
    detail: &LodSettings,
) -> Screen {
    let mut view = LodView::new(scene.mesher(3), config());
    let mut screen = Screen::default();
    screen.apply_level(view.settle(PLANET, source, viewer, detail));
    screen
}

#[test]
fn from_over_a_round_planet_what_is_behind_its_horizon_is_not_made_and_what_is_before_it_is_as_it_was()
 {
    let scene = scene();
    let voxels = no_edits(&scene);
    let source = ShipTerrainSource::new(
        &voxels,
        Some(round_planet(&scene)),
        BrickBox::around(BrickCoordinate::ORIGIN, 100),
    );
    let bare = WithoutCore(source.clone());
    // Forty voxels over the top of the planet (the hills raise the ground to 616 at the most), looking over the whole of it.
    let viewer = WorldPosition::new(brick(0, 20, 0), [16.0, 0.0, 16.0]);
    let detail = LodSettings {
        maximum_distance: 5000.0,
        ..settings()
    };
    let culled = settle_a_view(&scene, &source, viewer, &detail);
    let whole = settle_a_view(&scene, &bare, viewer, &detail);

    // Nothing is drawn that was not, and what both draw is the same picture.
    assert!(!culled.nodes.is_empty());
    for (cube, mesh) in &culled.nodes {
        assert_eq!(whole.nodes.get(cube), Some(mesh), "{cube:?}");
    }
    for (coordinate, mesh) in &culled.bricks {
        assert_eq!(whole.bricks.get(coordinate), Some(mesh), "{coordinate:?}");
    }
    assert_eq!(culled.bricks.len(), whole.bricks.len());
    // A good deal less is: the far side of the planet is more than half of it.
    assert!(
        culled.nodes.len() * 4 < whole.nodes.len() * 3,
        "{} nodes, against {} without the cull",
        culled.nodes.len(),
        whole.nodes.len()
    );
    // And nothing before the horizon is: everything that the line from the viewer to the core's edge has not yet reached is kept. (The core is the radius less the
    // most the hills can raise the ground, the square root of three times 8 + 4 + 2, and a voxel, and less the margin that the view leaves for the viewer's moving within
    // its brick, which is a little under 56.)
    let viewer_at: [f64; 3] = [16.0, 640.0, 16.0];
    let from_the_centre =
        (viewer_at[0] * viewer_at[0] + viewer_at[1] * viewer_at[1] + viewer_at[2] * viewer_at[2])
            .sqrt();
    let core = 600.0 - 3.0f64.sqrt() * 14.0 - 1.0 - 55.0;
    let touching = (from_the_centre * from_the_centre - core * core).sqrt();
    let mut kept_near = 0;
    for cube in whole.nodes.keys() {
        if distance_to_node(*cube, viewer_at) <= touching {
            assert!(
                culled.nodes.contains_key(cube),
                "{cube:?} is before the horizon"
            );
            kept_near += 1;
        }
    }
    assert!(kept_near > 10, "{kept_near}");
}

#[test]
fn the_horizon_goes_with_the_viewer_what_was_hidden_is_drawn_when_the_viewer_goes_round_to_it() {
    let scene = scene();
    let voxels = no_edits(&scene);
    let source = ShipTerrainSource::new(
        &voxels,
        Some(round_planet(&scene)),
        BrickBox::around(BrickCoordinate::ORIGIN, 100),
    );
    let detail = LodSettings {
        maximum_distance: 5000.0,
        ..settings()
    };
    let top = WorldPosition::new(brick(0, 20, 0), [16.0, 0.0, 16.0]);
    let bottom = WorldPosition::new(brick(0, -21, 0), [16.0, 0.0, 16.0]);
    let from_the_top = settle_a_view(&scene, &source, top, &detail);
    let from_the_bottom = settle_a_view(&scene, &source, bottom, &detail);
    // The nodes that make the bottom of the planet are drawn from the bottom, and are not from the top.
    let at_the_bottom = |cube: &BrickCube| cube.origin().y() < -8;
    let (nearest_from_bottom, nearest_from_top) = (
        from_the_bottom
            .nodes
            .keys()
            .filter(|cube| at_the_bottom(cube))
            .count(),
        from_the_top
            .nodes
            .keys()
            .filter(|cube| at_the_bottom(cube))
            .count(),
    );
    assert!(nearest_from_bottom > 5, "{nearest_from_bottom}");
    assert!(
        nearest_from_top * 2 < nearest_from_bottom,
        "{nearest_from_top} {nearest_from_bottom}"
    );
    // And the top, from the top.
    let at_the_top = |cube: &BrickCube| cube.origin().y() >= 8;
    let (from_top, from_bottom) = (
        from_the_top
            .nodes
            .keys()
            .filter(|cube| at_the_top(cube))
            .count(),
        from_the_bottom
            .nodes
            .keys()
            .filter(|cube| at_the_top(cube))
            .count(),
    );
    assert!(from_top > 5, "{from_top}");
    assert!(from_bottom * 2 < from_top, "{from_bottom} {from_top}");
}
