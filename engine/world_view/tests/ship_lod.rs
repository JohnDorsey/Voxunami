#[test]
fn changing_the_detail_draws_the_planet_nearer_or_farther_and_the_picture_follows() {
    let scene = scene();
    let voxels = no_edits(&scene);
    let source = ShipTerrainSource::new(
        &voxels,
        Some(generator_of(&scene)),
        BrickBox::around(BrickCoordinate::ORIGIN, 100_000),
    );
    let mut planet = detailed_planet(&scene);
    let mut screen = Screen::default();
    let viewer = viewer_in(brick(0, 0, 0));
    screen.apply_planet(planet.settle(&source, viewer));
    let far_count = screen.nodes.len();

    planet.set_detail(LodSettings {
        maximum_distance: 400.0,
        ..settings()
    });
    screen.apply_planet(planet.settle(&source, viewer));
    let near_count = screen.nodes.len();
    assert!(
        near_count > 0 && near_count < far_count,
        "{near_count} {far_count}"
    );

    // And back: what was taken down is drawn again, to the picture it had.
    planet.set_detail(settings());
    screen.apply_planet(planet.settle(&source, viewer));
    assert_eq!(screen.nodes.len(), far_count);
}

#[test]
fn a_stored_brick_is_drawn_over_the_generated_one_in_detail_too() {
    let scene = scene();
    let mut voxels = no_edits(&scene);
    let generator = generator_of(&scene);
    let extent = BrickBox::around(BrickCoordinate::ORIGIN, 100_000);
    let mut planet = detailed_planet(&scene);
    let mut screen = Screen::default();
    let viewer = viewer_in(brick(0, 0, 0));
    {
        let source = ShipTerrainSource::new(&voxels, Some(Arc::clone(&generator)), extent);
        screen.apply_planet(planet.settle(&source, viewer));
    }
    let plain = screen.bricks[&brick(0, 0, 0)].clone();

    let stone = scene.game.raw_block("base_blocks:stone");
    let mut stored = generator.generate_brick(voxels.layout(), brick(0, 0, 0));
    stored.set(
        scene.material,
        VoxelCoordinate::new(5, 10, 5).split().1,
        stone,
    );
    voxels
        .insert_brick(brick(0, 0, 0), Arc::new(stored))
        .unwrap();
    planet.brick_changed(brick(0, 0, 0));
    let source = ShipTerrainSource::new(&voxels, Some(generator), extent);
    screen.apply_planet(planet.settle(&source, viewer));
    assert_ne!(screen.bricks[&brick(0, 0, 0)], plain);
}

