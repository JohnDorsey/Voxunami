//! Keeps the bricks around a viewer generated and meshed, on background threads.
//!
//! Each [`WorldMesher::update`] call collects finished work, unloads bricks that are too far away,
//! and hands out new jobs nearest-first. A brick is only meshed once it and all twenty-six of the
//! bricks that touch it (across its faces, along its edges and at its corners) are present, so no
//! mesh is ever built against a missing neighbour and no seam appears: a face looks at the brick
//! across a face of its own, and the shade of the corners of a face reads the cells beside that one,
//! which can be in a brick that touches only at an edge or a corner. A brick that changes is meshed
//! again, along with those twenty-six, whose faces or shade may have changed; the old mesh stays on
//! screen until the new one is ready.
//!
//! The viewer never generates terrain on its own thread: unedited bricks are generated by workers
//! from the generator the world assigns to their region, and edited bricks are taken as they are.

