/// Where the bricks around a viewer come from: the terrain of a level, or the terrain of a ship (a planet). A brick is either known as it is (an edited one) or
/// made by a generator, which the mesher has done on its worker threads.
pub trait TerrainSource {
    /// The brick if it needs no generating: an edited one, or for a ship the empty brick beyond what its generator makes.
    fn known(&self, coordinate: BrickCoordinate) -> Option<Arc<Brick>>;

    /// The generator that makes the brick if it is not known, if there is one in this program.
    fn generator_for(&self, coordinate: BrickCoordinate) -> Option<Arc<dyn TerrainGenerator>>;

    /// The channels the bricks have.
    fn layout(&self) -> &Arc<GridLayout>;
}

impl TerrainSource for LevelData {
    fn known(&self, coordinate: BrickCoordinate) -> Option<Arc<Brick>> {
        self.overrides.brick(coordinate).cloned()
    }

    /// The generator the level assigns to a brick's region, if the level has assigned one and this program has it.
    fn generator_for(&self, coordinate: BrickCoordinate) -> Option<Arc<dyn TerrainGenerator>> {
        let id = self.terrain.assigned_generator(coordinate)?;
        self.terrain.generators().entry(id)?.content().cloned()
    }

    fn layout(&self) -> &Arc<GridLayout> {
        self.overrides.layout()
    }
}

/// How far to keep bricks loaded around the viewer, and how much work to run at once.
#[derive(Clone, Copy, Debug, PartialEq, Eq)]
pub struct ViewSettings {
    /// Bricks within this distance (in brick units, as a sphere) are meshed.
    pub view_radius_bricks: i128,
    pub worker_count: usize,
}

/// How a game turns the channels of a brick into the brightness of each of its voxels, when what is
/// drawn is more than a light channel as it is (a light kept in cells larger than a voxel, blended with
/// the plain one). It runs on the meshing threads, once for a brick and once for each of its six
/// neighbours, so it must not wait for anything.
pub trait BrickLight: Send + Sync + std::fmt::Debug {
    /// The brightness, from 0 to 255, of every voxel of `brick`, which is at `coordinate`; or `None`
    /// to draw the plain light channel as it is.
    fn brightness(&self, brick: &Brick, coordinate: BrickCoordinate) -> Option<ChannelStorage>;
}

/// A [`BrickLight`] a view can hold. Two are equal when they are the same hook (not merely alike), so a
/// game keeps one and hands out the same until it changes, and the view is meshed again only then.
#[derive(Clone, Debug)]
pub struct BulkLight(pub Arc<dyn BrickLight>);

impl PartialEq for BulkLight {
    fn eq(&self, other: &Self) -> bool {
        Arc::ptr_eq(&self.0, &other.0)
    }
}

impl Eq for BulkLight {}

/// The channels of a world's bricks that say what to draw.
#[derive(Clone, Debug, PartialEq, Eq)]
pub struct ViewChannels {
    /// The block in each voxel.
    pub blocks: ChannelIndex,
    /// The state of each voxel's block, for games whose blocks have states.
    pub states: Option<ChannelIndex>,
    /// The orientation of each voxel, for games whose blocks can be turned.
    pub orientations: Option<ChannelIndex>,
    /// How bright each voxel is, for games with lighting.
    pub light: Option<ChannelIndex>,
    /// How the channels become the brightness drawn, when `light` is not drawn as it is.
    pub bulk_light: Option<BulkLight>,
}

impl ViewChannels {
    /// Channels for a game whose light, if it has any, is drawn as it is in `light`.
    pub fn new(
        blocks: ChannelIndex,
        states: Option<ChannelIndex>,
        light: Option<ChannelIndex>,
    ) -> Self {
        Self {
            blocks,
            states,
            orientations: None,
            light,
            bulk_light: None,
        }
    }

    /// The same, for a game whose voxels have an orientation in this channel.
    pub fn with_orientations(mut self, orientations: Option<ChannelIndex>) -> Self {
        self.orientations = orientations;
        self
    }

    /// The brightness of every voxel of a brick if the game has a bulk light hook.
    pub(crate) fn bulk_brightness(
        &self,
        brick: &Brick,
        coordinate: BrickCoordinate,
    ) -> Option<ChannelStorage> {
        self.bulk_light
            .as_ref()
            .and_then(|hook| hook.0.brightness(brick, coordinate))
    }
}

/// A change the renderer must apply.
#[derive(Clone, Debug, PartialEq, Eq)]
pub enum MeshUpdate {
    /// Replaces the brick's mesh; an empty mesh removes it.
    Upload {
        coordinate: BrickCoordinate,
        mesh: PackedBrickMesh,
    },
    Remove(BrickCoordinate),
    /// Replaces the mesh of a brick of a ship, in the ship's own coordinates.
    UploadGridBrick {
        grid: GridId,
        coordinate: BrickCoordinate,
        mesh: PackedBrickMesh,
    },
    RemoveGridBrick {
        grid: GridId,
        coordinate: BrickCoordinate,
    },
    /// Says where a ship is and how it is turned.
    GridPose {
        grid: GridId,
        pose: GridPose,
    },
    /// Says that a grid is the ground of a planet (a ship with terrain), told once when it is first seen. What the renderer does with it is its own (`set_grid_is_ground`).
    GridIsGround(GridId),
    /// A ship is gone, with all its bricks.
    RemoveGrid(GridId),
    /// Replaces the picture of a coarse node of the terrain (a cube of bricks of detail level 1 or more, see `coarse_cells`).
    UploadCoarse {
        cube: BrickCube,
        mesh: PackedBrickMesh,
    },
    RemoveCoarse(BrickCube),
    /// Replaces the picture of a coarse node of a planet, in the planet's own coordinates (see [`MeshUpdate::UploadCoarse`]).
    UploadGridCoarse {
        grid: GridId,
        cube: BrickCube,
        mesh: PackedBrickMesh,
    },
    RemoveGridCoarse {
        grid: GridId,
        cube: BrickCube,
    },
    /// Takes the picture of a coarse node of the terrain out of what is drawn and keeps it on the graphics card (`renderer::VoxelRenderer::hide_mesh`): the view holds it
    /// so that the node can be shown again without making it again ([`crate::LodView::hold_hidden_pictures`]). A later [`MeshUpdate::ShowCoarse`] shows it, and a
    /// [`MeshUpdate::RemoveCoarse`] lets go of it.
    HideCoarse(BrickCube),
    /// Shows the picture of a coarse node that was hidden.
    ShowCoarse(BrickCube),
    /// Gives the renderer the picture of a coarse node of the terrain that is **not** to be drawn: it holds it hidden (`renderer::VoxelRenderer::upload_hidden_mesh`), made for a
    /// viewpoint that is kept warm ([`crate::LodView::set_warm_viewpoint`]). A later [`MeshUpdate::ShowCoarse`] shows it. A mesh that is drawn is replaced where it is.
    UploadHiddenCoarse {
        cube: BrickCube,
        mesh: PackedBrickMesh,
    },
    /// [`MeshUpdate::UploadHiddenCoarse`] for a node of a planet.
    UploadHiddenGridCoarse {
        grid: GridId,
        cube: BrickCube,
        mesh: PackedBrickMesh,
    },
    /// [`MeshUpdate::HideCoarse`] for a node of a planet.
    HideGridCoarse {
        grid: GridId,
        cube: BrickCube,
    },
    /// [`MeshUpdate::ShowCoarse`] for a node of a planet.
    ShowGridCoarse {
        grid: GridId,
        cube: BrickCube,
    },
    /// Takes the picture of a brick of the terrain out of what is drawn and keeps it on the graphics card, as [`MeshUpdate::HideCoarse`] does for a node: the mesher holds
    /// it ([`WorldMesher::hold_hidden_pictures`]). A later [`MeshUpdate::ShowBrick`] shows it, and a [`MeshUpdate::Remove`] lets go of it.
    HideBrick(BrickCoordinate),
    /// Shows the picture of a brick that was hidden.
    ShowBrick(BrickCoordinate),
    /// Gives the renderer the picture of a brick of the terrain that is **not** to be drawn: it holds it hidden, made for a viewpoint that is kept warm
    /// ([`crate::LodView::set_warm_viewpoint`]), as [`MeshUpdate::UploadHiddenCoarse`] does for a node. A later [`MeshUpdate::ShowBrick`] shows it.
    UploadHiddenBrick {
        coordinate: BrickCoordinate,
        mesh: PackedBrickMesh,
    },
    /// [`MeshUpdate::UploadHiddenBrick`] for a brick of a planet.
    UploadHiddenGridBrick {
        grid: GridId,
        coordinate: BrickCoordinate,
        mesh: PackedBrickMesh,
    },
    /// [`MeshUpdate::HideBrick`] for a brick of a planet.
    HideGridBrick {
        grid: GridId,
        coordinate: BrickCoordinate,
    },
    /// [`MeshUpdate::ShowBrick`] for a brick of a planet.
    ShowGridBrick {
        grid: GridId,
        coordinate: BrickCoordinate,
    },
}

struct NeighbourhoodSnapshot {
    center: Arc<Brick>,
    /// Indexed by [`FaceDirection::index`].
    neighbours: [Arc<Brick>; 6],
}

enum Job {
    Generate {
        epoch: u64,
        coordinate: BrickCoordinate,
        generator: Arc<dyn TerrainGenerator>,
        layout: Arc<GridLayout>,
    },
    Mesh {
        epoch: u64,
        coordinate: BrickCoordinate,
        version: u64,
        snapshot: Box<NeighbourhoodSnapshot>,
        /// What to draw from, as it is when the job is made: a game can change it (see
        /// [`WorldMesher::set_channels`]).
        channels: ViewChannels,
        /// Whether to say which voxels of the brick block the sun as well (see [`WorldMesher::enable_occupancy`]).
        want_occupancy: bool,
    },
}

enum JobResult {
    Generated {
        epoch: u64,
        coordinate: BrickCoordinate,
        brick: Arc<Brick>,
    },
    Meshed {
        epoch: u64,
        coordinate: BrickCoordinate,
        version: u64,
        mesh: PackedBrickMesh,
        occupancy: Option<BrickOccupancy>,
    },
    /// The job panicked, with this payload.
    Panicked(Box<dyn Any + Send>),
}

/// The channels of a brick that meshing looks at.
pub(crate) fn brick_channels<'a>(
    brick: &'a Brick,
    combined_light: Option<&'a ChannelStorage>,
    channels: &ViewChannels,
) -> BrickChannels<'a> {
    BrickChannels {
        blocks: brick.channel(channels.blocks),
        states: channels.states.map(|states| brick.channel(states)),
        orientations: channels
            .orientations
            .map(|orientations| brick.channel(orientations)),
        light: combined_light.or_else(|| channels.light.map(|light| brick.channel(light))),
    }
}

/// Integer offsets within `radius` of the origin, nearest first.
fn offsets_within(radius: i128) -> Vec<[i128; 3]> {
    let mut offsets = Vec::new();
    for x in -radius..=radius {
        for y in -radius..=radius {
            for z in -radius..=radius {
                if x * x + y * y + z * z <= radius * radius {
                    offsets.push([x, y, z]);
                }
            }
        }
    }
    offsets.sort_by_key(|[x, y, z]| (x * x + y * y + z * z, *x, *y, *z));
    offsets
}

/// Whether `a` is farther from `b` than `radius` bricks (a ball, not a box). Bricks are as far apart as the range of coordinates (2^116), so the squares of the
/// distances would not fit: a distance beyond the radius along one axis is farther whatever the others are, which is checked first, and after it each is at most
/// the radius.
fn is_farther_than(a: BrickCoordinate, b: BrickCoordinate, radius: i128) -> bool {
    let radius = radius.unsigned_abs();
    let distances = [
        a.x().abs_diff(b.x()),
        a.y().abs_diff(b.y()),
        a.z().abs_diff(b.z()),
    ];
    distances.iter().any(|&distance| distance > radius)
        || distances
            .iter()
            .map(|&distance| distance * distance)
            .sum::<u128>()
            > radius * radius
}

pub struct WorldMesher {
    settings: ViewSettings,
    channels: ViewChannels,
    table: Arc<BlockTable>,
    /// What is known of each brick near the viewer: its voxels (edited or generated here), whether a job is making them or its picture, the picture if it is
    /// held back, and whether it is shown (see [`BrickStates`]).
    states: BrickStates,
    /// Bumped when a brick or a neighbour of it changes; results from older versions are stale.
    versions: HashMap<BrickCoordinate, u64>,
    /// Offsets of bricks to load: the view sphere plus a one-brick shell for neighbours.
    load_offsets: Vec<[i128; 3]>,
    /// Whether the pictures are kept until they are asked for (see [`WorldMesher::with_held_back_display`]).
    held_back: bool,
    /// Counts the pictures that have become ready, so that a coordinator can tell that there is something new.
    ready_serial: u64,
    jobs: Option<mpsc::Sender<Job>>,
    results: mpsc::Receiver<JobResult>,
    workers: Vec<JoinHandle<()>>,
    scheduled_last_update: usize,
    /// Counts the times the mesher was reset; work and results from an earlier count are ignored.
    epoch: u64,
    /// Which voxels of the bricks block the sun, as far as the renderer has been told (off until asked for).
    occupancy: OccupancyLog<BrickCoordinate>,
    /// The bricks whose pictures were held, whose hidden meshes the renderer is to take down: their pictures went out of date (an edit, a change of what is drawn from)
    /// since the last update, which says so.
    pending_removals: Vec<BrickCoordinate>,
    /// The centre of a second ball of bricks that is made and kept as well as the one round the viewer ([`WorldMesher::set_warm_centre`]).
    warm_centre: Option<BrickCoordinate>,
    /// The bricks of that ball whose pictures are made and waiting: held, hidden, once nothing wants them drawn ([`WorldMesher::park_ready`]).
    warm_waiting: HashSet<BrickCoordinate>,
}

impl std::fmt::Debug for WorldMesher {
    fn fmt(&self, formatter: &mut std::fmt::Formatter<'_>) -> std::fmt::Result {
        formatter
            .debug_struct("WorldMesher")
            .field("settings", &self.settings)
            .field("loaded", &self.states.loaded_count())
            .field("meshed", &self.states.meshed_count())
            .finish_non_exhaustive()
    }
}

impl WorldMesher {
    /// `table` says what each block and state of the channels is: which faces it hides, and how it
    /// fills its cell.
    pub fn new(settings: ViewSettings, channels: ViewChannels, table: Arc<BlockTable>) -> Self {
        let (job_sender, job_receiver) = mpsc::channel::<Job>();
        let (result_sender, results) = mpsc::channel::<JobResult>();
        let job_receiver = Arc::new(Mutex::new(job_receiver));
        let workers = (0..settings.worker_count.max(1))
            .map(|_| {
                let job_receiver = Arc::clone(&job_receiver);
                let result_sender = result_sender.clone();
                let table = Arc::clone(&table);
                std::thread::spawn(move || {
                    loop {
                        // Hold the lock only while waiting for the next job, not while running it.
                        let job = job_receiver.lock().expect("job queue lock").recv();
                        let Ok(job) = job else { return };
                        // A generator with a bug panics here, on a thread nobody is watching: it is caught, and said to the one who updates the mesher, who panics with it. (A thread
                        // that dies with its job leaves the job pending for ever and the view waiting for it, with nothing to say why.)
                        let result = catch_unwind(AssertUnwindSafe(|| match job {
                            Job::Generate {
                                epoch,
                                coordinate,
                                generator,
                                layout,
                            } => JobResult::Generated {
                                epoch,
                                coordinate,
                                brick: Arc::new(generator.generate_brick(&layout, coordinate)),
                            },
                            Job::Mesh {
                                epoch,
                                coordinate,
                                version,
                                snapshot,
                                channels,
                                want_occupancy,
                            } => {
                                // A game with a bulk light hook says how bright each voxel is.
                                let center_light =
                                    channels.bulk_brightness(&snapshot.center, coordinate);
                                let neighbour_light: [Option<ChannelStorage>; 6] =
                                    std::array::from_fn(|face| {
                                        let neighbour =
                                            coordinate.neighbour(FaceDirection::ALL[face]);
                                        neighbour.and_then(|neighbour| {
                                            channels.bulk_brightness(
                                                &snapshot.neighbours[face],
                                                neighbour,
                                            )
                                        })
                                    });
                                let neighbourhood = BrickNeighbourhood {
                                    center: brick_channels(
                                        &snapshot.center,
                                        center_light.as_ref(),
                                        &channels,
                                    ),
                                    neighbours: std::array::from_fn(|face| {
                                        Some(brick_channels(
                                            &snapshot.neighbours[face],
                                            neighbour_light[face].as_ref(),
                                            &channels,
                                        ))
                                    }),
                                };
                                JobResult::Meshed {
                                    epoch,
                                    coordinate,
                                    version,
                                    mesh: mesh_brick(&neighbourhood, &table).pack(),
                                    occupancy: want_occupancy
                                        .then(|| BrickOccupancy::of(&neighbourhood.center, &table)),
                                }
                            }
                        }))
                        .unwrap_or_else(JobResult::Panicked);
                        if result_sender.send(result).is_err() {
                            return;
                        }
                    }
                })
            })
            .collect();
        Self {
            settings,
            channels,
            table,
            states: BrickStates::new(),
            versions: HashMap::new(),
            load_offsets: offsets_within(settings.view_radius_bricks + 1),
            held_back: false,
            ready_serial: 0,
            jobs: Some(job_sender),
            results,
            workers,
            scheduled_last_update: 0,
            epoch: 0,
            occupancy: OccupancyLog::new(),
            pending_removals: Vec::new(),
            warm_centre: None,
            warm_waiting: HashSet::new(),
        }
    }

    /// Makes the mesher say which voxels of each brick it meshes block the sun, for every brick (the buried ones and the ones of sky, which have no mesh, too): see
    /// [`WorldMesher::take_occupancy_updates`]. Call it before the first update; bricks meshed before are not said again.
    pub fn enable_occupancy(&mut self) {
        self.occupancy.enable();
    }

    /// What has changed in the occupancy of the bricks since the last call, in order (nothing unless [`WorldMesher::enable_occupancy`] was called). A brick is told of
    /// when its mesh is made, whether or not it has anything to draw, and again only when its occupancy changes; it is cleared when it goes out of range or the mesher is
    /// reset.
    pub fn take_occupancy_updates(&mut self) -> Vec<(BrickCoordinate, OccupancyChange)> {
        self.occupancy.take()
    }

    /// How many of the bricks that were told of are empty, full and mixed.
    pub fn occupancy_statistics(&self) -> OccupancyStatistics {
        self.occupancy.statistics()
    }

    /// Makes the mesher keep the pictures it makes instead of reporting them, for a view that swaps bricks and coarse nodes for each other
    /// (`docs/specs/lod-spec.md`, 3.6) and so decides when a picture goes up: [`WorldMesher::is_ready`] says that one is waiting, [`WorldMesher::show`] hands it out
    /// and [`WorldMesher::hide`] takes it down. The bricks it makes pictures of are the ones the view radius (as a [`FineRegion`]) says are drawn as bricks:
    /// those in a cube of two bricks that touches the ball. A brick that is shown and changes is reported again as it is made, since it is on the screen
    /// already. Bricks that go out of range are not hidden, that is for the caller to do.
    pub fn with_held_back_display(mut self) -> Self {
        self.held_back = true;
        // The wanted bricks reach less than two bricks past the ball, and their neighbours one more.
        self.load_offsets = offsets_within(self.settings.view_radius_bricks + 3);
        self
    }

    /// Keeps the pictures of the bricks that are taken down ([`WorldMesher::hide`]), up to `budget_bytes` of them: the renderer is to **hide** the mesh
    /// ([`MeshUpdate::HideBrick`]) and not take it down, and showing the brick again ([`WorldMesher::show`]) is a move ([`MeshUpdate::ShowBrick`]) and makes nothing, even
    /// after the brick went out of range and its voxels were let go of. What the sun is told of the brick is kept with it, and told again then. A picture goes out of
    /// date with an edit ([`WorldMesher::brick_changed`]) or a change of what is drawn from, and is let go of ([`MeshUpdate::Remove`], at the next update). 0, the default,
    /// keeps nothing. Only for a mesher that holds its pictures back ([`WorldMesher::with_held_back_display`]); the oldest are let go of by [`WorldMesher::evict_held`].
    pub fn hold_hidden_pictures(&mut self, budget_bytes: usize) {
        self.states.set_budget(budget_bytes);
    }

    /// What is held now ([`WorldMesher::hold_hidden_pictures`]).
    pub fn held_pictures(&self) -> HeldBricks {
        self.states.held_pictures()
    }

    /// Whether the picture of the brick is held: it is not shown, and is shown again without making anything.
    pub fn is_held(&self, coordinate: BrickCoordinate) -> bool {
        self.states.is_held(coordinate)
    }

    /// Lets go of held pictures, the oldest first, until what is held is within the budget, except those of the bricks `keep` says are kept (the ones that are wanted: they
    /// are about to be shown, so what is held may pass the budget by them). Returns what the renderer is to do.
    pub fn evict_held(&mut self, keep: impl Fn(BrickCoordinate) -> bool) -> Vec<MeshUpdate> {
        self.states
            .evict_over_budget(keep)
            .into_iter()
            .map(MeshUpdate::Remove)
            .collect()
    }

    /// Makes and keeps the bricks of a second ball, round `centre`, as well as those round the viewer (`None`, the default, none): what is made for the viewer comes first, and
    /// a picture made for the second ball alone is not told to the sun, and is held hidden by [`WorldMesher::park_ready`]. Needs pictures to be held
    /// ([`WorldMesher::hold_hidden_pictures`]).
    pub fn set_warm_centre(&mut self, centre: Option<BrickCoordinate>) {
        if self.warm_centre != centre {
            self.warm_centre = centre;
            self.warm_waiting.clear();
        }
    }

    /// Holds the pictures of the second ball that are made and waiting: returns what the renderer is to be given, each mesh hidden. (One of them that the viewer comes to draw is
    /// shown by a move, as any held picture is.)
    pub fn park_ready(&mut self) -> Vec<MeshUpdate> {
        let mut candidates: Vec<BrickCoordinate> = self.warm_waiting.drain().collect();
        candidates.sort();
        let mut updates = Vec::new();
        for coordinate in candidates {
            // (One that is not waiting any more was shown, or its picture went: it is not the second ball's to hold.)
            if let Some(mesh) = self.states.park(coordinate)
                && !mesh.is_empty()
            {
                updates.push(MeshUpdate::UploadHiddenBrick { coordinate, mesh });
            }
        }
        updates
    }

    /// How many pictures have become ready since the mesher was made (when held back).
    pub fn ready_serial(&self) -> u64 {
        self.ready_serial
    }

    /// The radius of the ball of bricks that are drawn as bricks.
    pub fn view_radius_bricks(&self) -> i128 {
        self.settings.view_radius_bricks
    }

    /// Whether a picture of the brick is waiting to be shown, or is held, so that it is shown without making anything (when held back).
    pub fn is_ready(&self, coordinate: BrickCoordinate) -> bool {
        self.states.is_ready(coordinate)
    }

    /// Whether the brick has been asked to be shown and not hidden since (when held back).
    pub fn is_shown(&self, coordinate: BrickCoordinate) -> bool {
        self.states.is_shown(coordinate)
    }

    /// The bricks that have been asked to be shown and not hidden since (when held back), in no order.
    pub(crate) fn shown_coordinates(&self) -> impl Iterator<Item = BrickCoordinate> + '_ {
        self.states.shown_coordinates()
    }

    /// Why a picture of the brick is not waiting to be shown, in words, for the report of a view that has stopped; `None` if one is. A brick wanted by a viewer is
    /// made unless something is wrong, so what this says when nothing is being done for it is what to look at.
    pub fn why_not_ready(
        &self,
        source: &impl TerrainSource,
        coordinate: BrickCoordinate,
    ) -> Option<String> {
        if self.states.is_ready(coordinate) {
            return None;
        }
        let made_by_nothing = |coordinate: BrickCoordinate| {
            source.known(coordinate).is_none() && source.generator_for(coordinate).is_none()
        };
        let state = self.states.get(coordinate);
        Some(if state.is_some_and(BrickState::is_generating) {
            "it is being generated".to_string()
        } else if state.is_some_and(BrickState::is_meshing) {
            "it is being meshed".to_string()
        } else if state.is_some_and(BrickState::is_shown) {
            "it is shown already".to_string()
        } else if state.is_some_and(BrickState::is_meshed) {
            "it is meshed and its picture is gone (it would never be meshed again)".to_string()
        } else if self.states.data(coordinate).is_none() {
            if made_by_nothing(coordinate) {
                "nothing here can make it: it is not known and no generator has it".to_string()
            } else {
                "it is not loaded".to_string()
            }
        } else if let Some(missing) = FaceDirection::ALL
            .iter()
            .filter_map(|&face| coordinate.neighbour(face))
            .find(|&neighbour| self.states.data(neighbour).is_none())
        {
            let reason = if made_by_nothing(missing) {
                ", and nothing here can make it"
            } else {
                ""
            };
            format!("its neighbour {missing:?} is not loaded{reason}")
        } else {
            "it is loaded with its neighbours and nothing is meshing it".to_string()
        })
    }

    /// Shows the picture of a brick that [`WorldMesher::is_ready`]: returns what the renderer must be given for it, which is nothing if there is nothing to see
    /// (the brick is shown all the same), or the order to show the mesh it holds hidden if the picture was held. Nothing happens, and nothing is returned, for a brick that
    /// is not ready.
    pub fn show(&mut self, coordinate: BrickCoordinate) -> Option<MeshUpdate> {
        if let Some(displayed) = self.states.reveal(coordinate) {
            // The sun is told again what it was told of the brick: the renderer was told to forget it if the brick went out of range, and nothing is sent if it did not.
            if self.occupancy.is_enabled()
                && let Some(occupancy) = self.states.occupancy(coordinate).cloned()
            {
                self.occupancy.set(coordinate, occupancy);
            }
            return displayed.then_some(MeshUpdate::ShowBrick(coordinate));
        }
        let mesh = self.states.hand_out(coordinate)?;
        // (A picture made for the second ball alone was not told to the sun: it is now, and nothing is sent if it was.)
        if self.occupancy.is_enabled()
            && let Some(occupancy) = self.states.occupancy(coordinate).cloned()
        {
            self.occupancy.set(coordinate, occupancy);
        }
        if mesh.is_empty() {
            return None;
        }
        self.states.set_displayed(coordinate, true);
        Some(MeshUpdate::Upload { coordinate, mesh })
    }

    /// Takes a shown brick down: returns what the renderer must do, which is nothing if it had nothing on the screen. The picture is gone with it (it was handed
    /// out by [`WorldMesher::show`]), so the brick has none, and is made again if it is wanted again; unless pictures are held ([`WorldMesher::hold_hidden_pictures`]),
    /// and then the renderer is to hide the mesh and not take it down, and the brick is ready.
    pub fn hide(&mut self, coordinate: BrickCoordinate) -> Option<MeshUpdate> {
        match self.states.hold_down(coordinate)? {
            Taken::Nothing => None,
            Taken::Removed => Some(MeshUpdate::Remove(coordinate)),
            Taken::Hidden => Some(MeshUpdate::HideBrick(coordinate)),
        }
    }

    /// Jobs handed to workers and not yet finished.
    pub fn pending_jobs(&self) -> usize {
        self.states.jobs_in_flight()
    }

    /// Whether the mesher has nothing more to do until something changes: no job is in flight, and the last update started none and loaded no brick (a brick that
    /// is loaded may complete its neighbours, which the next update looks at). What a viewer waits for when it wants everything that is wanted to be made.
    pub fn is_settled(&self) -> bool {
        self.pending_jobs() == 0 && self.scheduled_last_update == 0
    }

    /// Checks what the records of the bricks cannot make impossible by their shape, and says what is wrong if it is not so (the first thing found): a brick
    /// whose picture was given out and that is not shown is never meshed again, and a view that waits for it waits for ever. Cheap enough to call at every
    /// update of a test.
    pub fn check_consistency(&self) -> Result<(), String> {
        self.states.check_consistency(self.held_back)
    }

    /// Bricks currently held in memory (whether or not drawn).
    pub fn loaded_brick_count(&self) -> usize {
        self.states.loaded_count()
    }

    /// The block in a voxel, if its brick is loaded.
    pub fn material_at(&self, coordinate: VoxelCoordinate) -> Option<u32> {
        let (brick, local) = coordinate.split();
        self.states
            .data(brick)
            .map(|loaded| loaded.get(self.channels.blocks, local))
    }

    /// The state of the block in a voxel (0 where the game has no states), if its brick is loaded.
    pub fn state_at(&self, coordinate: VoxelCoordinate) -> Option<u32> {
        let (brick, local) = coordinate.split();
        self.states.data(brick).map(|loaded| {
            self.channels
                .states
                .map_or(0, |states| loaded.get(states, local))
        })
    }

    /// The orientation of the block in a voxel (0 where the game has none), if its brick is loaded.
    pub fn orientation_at(&self, coordinate: VoxelCoordinate) -> Option<u32> {
        let (brick, local) = coordinate.split();
        self.states.data(brick).map(|loaded| {
            self.channels
                .orientations
                .map_or(0, |orientations| loaded.get(orientations, local))
        })
    }

    /// Whether a voxel holds something that fills any part of it (anything but air), if its brick is
    /// loaded. This is what a crosshair can point at.
    pub fn is_solid_at(&self, coordinate: VoxelCoordinate) -> Option<bool> {
        let model = self.table.model_of(
            self.material_at(coordinate)?,
            self.state_at(coordinate)?,
            self.orientation_at(coordinate)?,
        );
        Some(self.table.is_solid(model))
    }

    /// Whether a voxel holds a whole cube that hides what is behind it, if its brick is loaded.
    pub fn is_opaque_at(&self, coordinate: VoxelCoordinate) -> Option<bool> {
        let model = self.table.model_of(
            self.material_at(coordinate)?,
            self.state_at(coordinate)?,
            self.orientation_at(coordinate)?,
        );
        Some(self.table.is_opaque_cube(model))
    }

    /// Tells the mesher a brick's edited contents changed, so it and its neighbours are meshed
    /// again from the new contents.
    pub fn brick_changed(&mut self, coordinate: BrickCoordinate) {
        self.states.forget_data(coordinate);
        for affected in std::iter::once(coordinate).chain(
            FaceDirection::ALL
                .iter()
                .filter_map(|&f| coordinate.neighbour(f)),
        ) {
            *self.versions.entry(affected).or_insert(0) += 1;
            if self.states.drop_picture(affected) {
                self.pending_removals.push(affected);
            }
        }
    }

    /// Changes what is drawn from (as when a game changes the scales of its light): every brick is
    /// meshed again, and what is on the screen stays until its new mesh is ready.
    pub fn set_channels(&mut self, channels: ViewChannels) {
        if channels == self.channels {
            return;
        }
        self.channels = channels;
        for coordinate in self.states.loaded_coordinates() {
            *self.versions.entry(coordinate).or_insert(0) += 1;
        }
        let held = self.states.drop_all_pictures();
        self.pending_removals.extend(held);
    }

    /// Forgets every brick and all work in progress, as when the viewer moves to another level whose
    /// bricks have nothing to do with the old ones. Returns the removal of every mesh displayed.
    pub fn reset(&mut self) -> Vec<MeshUpdate> {
        self.epoch += 1;
        let mut displayed = self.states.clear();
        // (The renderer still holds the hidden meshes of the pictures that went out of date, and nothing else of them.)
        displayed.append(&mut self.pending_removals);
        displayed.sort();
        displayed.dedup();
        self.versions.clear();
        self.scheduled_last_update = 0;
        self.warm_waiting.clear();
        self.occupancy.clear_all();
        displayed.into_iter().map(MeshUpdate::Remove).collect()
    }

    fn version_of(&self, coordinate: BrickCoordinate) -> u64 {
        self.versions.get(&coordinate).copied().unwrap_or(0)
    }

    /// Collects finished jobs, unloads far bricks and schedules nearby work around `center`, reading
    /// from `source` (a level's terrain, or a ship's). Returns what the renderer should change.
    pub fn update(
        &mut self,
        source: &impl TerrainSource,
        center: BrickCoordinate,
    ) -> Vec<MeshUpdate> {
        // What went out of date since the last update is taken down first: a picture made for the brick comes after it.
        let mut updates: Vec<MeshUpdate> = self
            .pending_removals
            .drain(..)
            .map(MeshUpdate::Remove)
            .collect();
        let view_radius = self.settings.view_radius_bricks;
        let keep_radius = view_radius + if self.held_back { 4 } else { 2 };
        let fine_region = FineRegion::new(center, u32::try_from(view_radius).unwrap_or(0));
        let warm_region = self
            .warm_centre
            .filter(|_| self.held_back && self.states.holds_pictures())
            .map(|warm| FineRegion::new(warm, u32::try_from(view_radius).unwrap_or(0)));

        while let Ok(result) = self.results.try_recv() {
            match result {
                // As if the work had been done here: a bug in a generator is a panic of whoever asked for the brick.
                JobResult::Panicked(payload) => resume_unwind(payload),
                JobResult::Generated {
                    epoch,
                    coordinate,
                    brick,
                } => {
                    if epoch == self.epoch {
                        self.states.finish_generating(coordinate, brick);
                    }
                }
                JobResult::Meshed {
                    epoch,
                    coordinate,
                    version,
                    mesh,
                    occupancy,
                } => {
                    if epoch != self.epoch
                        || !self.states.finish_meshing(coordinate)
                        || version != self.version_of(coordinate)
                    {
                        continue; // unloaded, or changed since: the brick will be meshed again
                    }
                    // (A copy is kept with the picture when pictures are held, to tell the sun again when the brick is shown from hold.)
                    let to_keep = if self.states.holds_pictures() {
                        occupancy.clone()
                    } else {
                        None
                    };
                    // A brick that is in the second ball and not the first is made to be held: the sun is told of it when it is drawn (the renderer's tables of the sun are
                    // for what is near the camera, and a brick far from it would take the place of one that is near).
                    let for_the_warm_ball_alone = self.held_back
                        && !fine_region.wants_brick(coordinate)
                        && warm_region
                            .as_ref()
                            .is_some_and(|region| region.wants_brick(coordinate));
                    if !for_the_warm_ball_alone && let Some(occupancy) = occupancy {
                        self.occupancy.set(coordinate, occupancy);
                    }
                    if self.held_back && !self.states.is_shown(coordinate) {
                        self.states.hold(coordinate, mesh);
                        if let Some(occupancy) = to_keep {
                            self.states.keep_occupancy(coordinate, occupancy);
                        }
                        if for_the_warm_ball_alone {
                            self.warm_waiting.insert(coordinate);
                        }
                        self.ready_serial += 1;
                        continue;
                    }
                    self.states.deliver(coordinate, mesh.byte_size());
                    if let Some(occupancy) = to_keep {
                        self.states.keep_occupancy(coordinate, occupancy);
                    }
                    if mesh.is_empty() && !self.states.is_displayed(coordinate) {
                        continue;
                    }
                    self.states.set_displayed(coordinate, !mesh.is_empty());
                    updates.push(MeshUpdate::Upload { coordinate, mesh });
                }
            }
        }

        // Unload what is out of range. A removal is reported for every displayed brick.
        let too_far: Vec<BrickCoordinate> = self
            .states
            .loaded_coordinates()
            .filter(|&coordinate| is_farther_than(coordinate, center, keep_radius))
            .filter(|&coordinate| {
                warm_region.is_none()
                    || self
                        .warm_centre
                        .is_none_or(|warm| is_farther_than(coordinate, warm, keep_radius))
            })
            .collect();
        for coordinate in too_far {
            self.states.unload(coordinate);
            self.occupancy.clear(coordinate);
            if !self.held_back && self.states.is_displayed(coordinate) {
                self.states.set_displayed(coordinate, false);
                updates.push(MeshUpdate::Remove(coordinate));
            }
        }

        let mut scheduled = self.schedule_around(source, center, &fine_region);
        // (A second ball round the same centre is the first.)
        if let Some(region) = &warm_region
            && let Some(warm) = self.warm_centre.filter(|&warm| warm != center)
        {
            // (What is made for the viewer comes first: the limit on jobs is the same.)
            scheduled += self.schedule_around(source, warm, region);
        }
        self.scheduled_last_update = scheduled;
        updates
    }

    /// Loads the bricks round `center` that are not, starts the jobs that generate the voxels of those that are not known, and the jobs that mesh the bricks of `fine_region`
    /// whose neighbours are loaded; at most as many as the limit on jobs in flight. Returns how many things it started or loaded.
    fn schedule_around(
        &mut self,
        source: &impl TerrainSource,
        center: BrickCoordinate,
        fine_region: &FineRegion,
    ) -> usize {
        let view_radius = self.settings.view_radius_bricks;
        let maximum_in_flight = self.workers.len() * 4;
        let mut scheduled = 0;
        for &[dx, dy, dz] in &self.load_offsets {
            if self.states.jobs_in_flight() >= maximum_in_flight {
                break;
            }
            let Some(coordinate) = center.checked_offset(dx, dy, dz) else {
                continue;
            };
            let mut state = self.states.get(coordinate);
            if state.and_then(BrickState::data).is_none() {
                if let Some(known) = source.known(coordinate) {
                    self.states.load(coordinate, known);
                    // No job, and yet the bricks beside it may be whole now, and are looked at again by the next update.
                    scheduled += 1;
                    state = self.states.get(coordinate);
                } else if !state.is_some_and(BrickState::is_generating)
                    && let Some(generator) = source.generator_for(coordinate)
                {
                    self.states.start_generating(coordinate);
                    self.jobs
                        .as_ref()
                        .expect("workers run until the mesher is dropped")
                        .send(Job::Generate {
                            epoch: self.epoch,
                            coordinate,
                            generator,
                            layout: Arc::clone(source.layout()),
                        })
                        .expect("workers are running");
                    scheduled += 1;
                    continue;
                }
            }
            let within_view = if self.held_back {
                fine_region.wants_brick(coordinate)
            } else {
                dx * dx + dy * dy + dz * dz <= view_radius * view_radius
            };
            if !within_view || !state.is_some_and(BrickState::needs_meshing) {
                continue;
            }
            if let Some(snapshot) = self.snapshot_of(coordinate) {
                let version = self.version_of(coordinate);
                self.states.start_meshing(coordinate);
                self.jobs
                    .as_ref()
                    .expect("workers run until the mesher is dropped")
                    .send(Job::Mesh {
                        epoch: self.epoch,
                        coordinate,
                        version,
                        snapshot: Box::new(snapshot),
                        channels: self.channels.clone(),
                        want_occupancy: self.occupancy.is_enabled(),
                    })
                    .expect("workers are running");
                scheduled += 1;
            }
        }
        scheduled
    }

    /// The brick and its six neighbours, if all of them are loaded.
    fn snapshot_of(&self, coordinate: BrickCoordinate) -> Option<NeighbourhoodSnapshot> {
        let center = Arc::clone(self.states.data(coordinate)?);
        let mut neighbours = Vec::with_capacity(6);
        for face in FaceDirection::ALL {
            let neighbour = coordinate.neighbour(face)?;
            neighbours.push(Arc::clone(self.states.data(neighbour)?));
        }
        Some(NeighbourhoodSnapshot {
            center,
            neighbours: neighbours.try_into().expect("exactly six faces"),
        })
    }

    /// Updates until no work is pending or schedulable, returning every change. For headless
    /// rendering and tests; an interactive viewer calls [`WorldMesher::update`] once per frame.
    pub fn settle(
        &mut self,
        source: &impl TerrainSource,
        center: BrickCoordinate,
    ) -> Vec<MeshUpdate> {
        let mut updates = Vec::new();
        loop {
            updates.extend(self.update(source, center));
            if self.is_settled() {
                return updates;
            }
            std::thread::sleep(std::time::Duration::from_micros(200));
        }
    }
}

impl Drop for WorldMesher {
    fn drop(&mut self) {
        // Closing the job queue ends each worker's loop.
        self.jobs = None;
        for worker in self.workers.drain(..) {
            let _ = worker.join();
        }
    }
}

#[cfg(test)]
mod tests {
    use voxel_space::{BRICK_COORDINATE_MAXIMUM, BRICK_COORDINATE_MINIMUM};

    use super::*;

    fn brick(x: i128, y: i128, z: i128) -> BrickCoordinate {
        BrickCoordinate::new(x, y, z)
    }

    #[test]
    fn a_brick_is_farther_than_a_radius_when_the_squares_of_its_distances_add_to_more_than_the_square_of_it()
     {
        let centre = brick(10, -4, 7);
        assert!(!is_farther_than(centre, centre, 0));
        // 3, 4, 0 is exactly 5, and not farther than 5; 3, 4, 1 is.
        assert!(!is_farther_than(brick(13, -8, 7), centre, 5));
        assert!(is_farther_than(brick(13, -8, 8), centre, 5));
        assert!(!is_farther_than(brick(15, -4, 7), centre, 5));
        assert!(is_farther_than(brick(16, -4, 7), centre, 5));
        assert!(is_farther_than(brick(4, -4, 7), centre, 5));
        assert!(!is_farther_than(brick(5, -4, 7), centre, 5));
    }

    #[test]
    fn bricks_at_opposite_ends_of_the_range_are_far_apart_and_nothing_overflows() {
        // The squares of these distances (2^116) would not fit in 128 bits.
        let (low, high) = (BRICK_COORDINATE_MINIMUM, BRICK_COORDINATE_MAXIMUM);
        assert!(is_farther_than(
            brick(low, low, low),
            brick(high, high, high),
            10
        ));
        assert!(is_farther_than(
            brick(low, 0, 0),
            brick(high, 0, 0),
            i128::from(u32::MAX)
        ));
        assert!(!is_farther_than(
            brick(high, low, 0),
            brick(high, low, 0),
            0
        ));
        assert!(!is_farther_than(
            brick(high - 3, low + 4, 0),
            brick(high, low, 0),
            5
        ));
        assert!(is_farther_than(
            brick(high - 3, low + 4, 1),
            brick(high, low, 0),
            5
        ));
    }
}
