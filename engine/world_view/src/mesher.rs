//! Keeps the bricks around a viewer generated and meshed, on background threads.
//!
//! Each [`WorldMesher::update`] call collects finished work, unloads bricks that are too far away,
//! and hands out new jobs nearest-first. A brick is only meshed once it and all six of its
//! neighbours are present, so no mesh is ever built against a missing neighbour and no seam
//! appears. A brick that changes is meshed again, along with its neighbours, whose faces against it
//! may have changed; the old mesh stays on screen until the new one is ready.
//!
//! The viewer never generates terrain on its own thread: unedited bricks are generated by workers
//! from the generator the world assigns to their region, and edited bricks are taken as they are.

use std::collections::hash_map::Entry;
use std::collections::{HashMap, HashSet};
use std::sync::{Arc, Mutex, mpsc};
use std::thread::JoinHandle;

use block_models::BlockTable;
use terrain::TerrainGenerator;
use voxel_grid::{Brick, ChannelIndex, ChannelStorage, GridLayout};
use voxel_meshing::{BrickChannels, BrickNeighbourhood, PackedBrickMesh, mesh_brick};
use voxel_space::{BrickCoordinate, FaceDirection, GridId, GridPose, VoxelCoordinate};
use world_storage::LevelData;

/// How far to keep bricks loaded around the viewer, and how much work to run at once.
#[derive(Clone, Copy, Debug, PartialEq, Eq)]
pub struct ViewSettings {
    /// Bricks within this distance (in brick units, as a sphere) are meshed.
    pub view_radius_bricks: i64,
    pub worker_count: usize,
}

/// How a game turns the channels of a brick into the brightness of each of its voxels, when what is
/// drawn is more than a light channel as it is (a light kept in cells larger than a voxel, blended with
/// the plain one). It runs on the meshing threads, once for a brick and once for each of its six
/// neighbours, so it must not wait for anything.
pub trait BrickLight: Send + Sync + std::fmt::Debug {
    /// The brightness, from 0 to 255, of every voxel of `brick`, which is at `coordinate`; or `None`
    /// to draw the plain light channel as it is.
    fn brightness(&self, brick: &Brick, coordinate: BrickCoordinate) -> Option<ChannelStorage>;
}

/// A [`BrickLight`] a view can hold. Two are equal when they are the same hook (not merely alike), so a
/// game keeps one and hands out the same until it changes, and the view is meshed again only then.
#[derive(Clone, Debug)]
pub struct BulkLight(pub Arc<dyn BrickLight>);

impl PartialEq for BulkLight {
    fn eq(&self, other: &Self) -> bool {
        Arc::ptr_eq(&self.0, &other.0)
    }
}

impl Eq for BulkLight {}

/// The channels of a world's bricks that say what to draw.
#[derive(Clone, Debug, PartialEq, Eq)]
pub struct ViewChannels {
    /// The block in each voxel.
    pub blocks: ChannelIndex,
    /// The state of each voxel's block, for games whose blocks have states.
    pub states: Option<ChannelIndex>,
    /// The orientation of each voxel, for games whose blocks can be turned.
    pub orientations: Option<ChannelIndex>,
    /// How bright each voxel is, for games with lighting.
    pub light: Option<ChannelIndex>,
    /// How the channels become the brightness drawn, when `light` is not drawn as it is.
    pub bulk_light: Option<BulkLight>,
}

impl ViewChannels {
    /// Channels for a game whose light, if it has any, is drawn as it is in `light`.
    pub fn new(
        blocks: ChannelIndex,
        states: Option<ChannelIndex>,
        light: Option<ChannelIndex>,
    ) -> Self {
        Self {
            blocks,
            states,
            orientations: None,
            light,
            bulk_light: None,
        }
    }

    /// The same, for a game whose voxels have an orientation in this channel.
    pub fn with_orientations(mut self, orientations: Option<ChannelIndex>) -> Self {
        self.orientations = orientations;
        self
    }

    /// The brightness of every voxel of a brick if the game has a bulk light hook.
    pub(crate) fn bulk_brightness(
        &self,
        brick: &Brick,
        coordinate: BrickCoordinate,
    ) -> Option<ChannelStorage> {
        self.bulk_light
            .as_ref()
            .and_then(|hook| hook.0.brightness(brick, coordinate))
    }
}

/// A change the renderer must apply.
#[derive(Clone, Debug, PartialEq, Eq)]
pub enum MeshUpdate {
    /// Replaces the brick's mesh; an empty mesh removes it.
    Upload {
        coordinate: BrickCoordinate,
        mesh: PackedBrickMesh,
    },
    Remove(BrickCoordinate),
    /// Replaces the mesh of a brick of a ship, in the ship's own coordinates.
    UploadGridBrick {
        grid: GridId,
        coordinate: BrickCoordinate,
        mesh: PackedBrickMesh,
    },
    RemoveGridBrick {
        grid: GridId,
        coordinate: BrickCoordinate,
    },
    /// Says where a ship is and how it is turned.
    GridPose {
        grid: GridId,
        pose: GridPose,
    },
    /// A ship is gone, with all its bricks.
    RemoveGrid(GridId),
}

struct NeighbourhoodSnapshot {
    center: Arc<Brick>,
    /// Indexed by [`FaceDirection::index`].
    neighbours: [Arc<Brick>; 6],
}

enum Job {
    Generate {
        epoch: u64,
        coordinate: BrickCoordinate,
        generator: Arc<dyn TerrainGenerator>,
        layout: Arc<GridLayout>,
    },
    Mesh {
        epoch: u64,
        coordinate: BrickCoordinate,
        version: u64,
        snapshot: Box<NeighbourhoodSnapshot>,
        /// What to draw from, as it is when the job is made: a game can change it (see
        /// [`WorldMesher::set_channels`]).
        channels: ViewChannels,
    },
}

enum JobResult {
    Generated {
        epoch: u64,
        coordinate: BrickCoordinate,
        brick: Arc<Brick>,
    },
    Meshed {
        epoch: u64,
        coordinate: BrickCoordinate,
        version: u64,
        mesh: PackedBrickMesh,
    },
}

/// The channels of a brick that meshing looks at.
pub(crate) fn brick_channels<'a>(
    brick: &'a Brick,
    combined_light: Option<&'a ChannelStorage>,
    channels: &ViewChannels,
) -> BrickChannels<'a> {
    BrickChannels {
        blocks: brick.channel(channels.blocks),
        states: channels.states.map(|states| brick.channel(states)),
        orientations: channels
            .orientations
            .map(|orientations| brick.channel(orientations)),
        light: combined_light.or_else(|| channels.light.map(|light| brick.channel(light))),
    }
}

/// Integer offsets within `radius` of the origin, nearest first.
fn offsets_within(radius: i64) -> Vec<[i64; 3]> {
    let mut offsets = Vec::new();
    for x in -radius..=radius {
        for y in -radius..=radius {
            for z in -radius..=radius {
                if x * x + y * y + z * z <= radius * radius {
                    offsets.push([x, y, z]);
                }
            }
        }
    }
    offsets.sort_by_key(|[x, y, z]| (x * x + y * y + z * z, *x, *y, *z));
    offsets
}

fn distance_squared(a: BrickCoordinate, b: BrickCoordinate) -> i128 {
    let component = |p: i64, q: i64| i128::from(p) - i128::from(q);
    let (dx, dy, dz) = (
        component(a.x(), b.x()),
        component(a.y(), b.y()),
        component(a.z(), b.z()),
    );
    dx * dx + dy * dy + dz * dz
}

pub struct WorldMesher {
    settings: ViewSettings,
    channels: ViewChannels,
    table: Arc<BlockTable>,
    /// The bricks near the viewer, whether edited or generated here.
    bricks: HashMap<BrickCoordinate, Arc<Brick>>,
    generating: HashSet<BrickCoordinate>,
    /// Bricks being meshed, with the version of the world they were meshed from.
    meshing: HashMap<BrickCoordinate, u64>,
    /// Bricks whose current mesh is up to date.
    meshed: HashSet<BrickCoordinate>,
    /// Bricks the renderer currently holds a mesh for.
    displayed: HashSet<BrickCoordinate>,
    /// Bumped when a brick or a neighbour of it changes; results from older versions are stale.
    versions: HashMap<BrickCoordinate, u64>,
    /// Offsets of bricks to load: the view sphere plus a one-brick shell for neighbours.
    load_offsets: Vec<[i64; 3]>,
    jobs: Option<mpsc::Sender<Job>>,
    results: mpsc::Receiver<JobResult>,
    workers: Vec<JoinHandle<()>>,
    scheduled_last_update: usize,
    /// Counts the times the mesher was reset; work and results from an earlier count are ignored.
    epoch: u64,
}

impl std::fmt::Debug for WorldMesher {
    fn fmt(&self, formatter: &mut std::fmt::Formatter<'_>) -> std::fmt::Result {
        formatter
            .debug_struct("WorldMesher")
            .field("settings", &self.settings)
            .field("loaded", &self.bricks.len())
            .field("meshed", &self.meshed.len())
            .finish_non_exhaustive()
    }
}

impl WorldMesher {
    /// `table` says what each block and state of the channels is: which faces it hides, and how it
    /// fills its cell.
    pub fn new(settings: ViewSettings, channels: ViewChannels, table: Arc<BlockTable>) -> Self {
        let (job_sender, job_receiver) = mpsc::channel::<Job>();
        let (result_sender, results) = mpsc::channel::<JobResult>();
        let job_receiver = Arc::new(Mutex::new(job_receiver));
        let workers = (0..settings.worker_count.max(1))
            .map(|_| {
                let job_receiver = Arc::clone(&job_receiver);
                let result_sender = result_sender.clone();
                let table = Arc::clone(&table);
                std::thread::spawn(move || {
                    loop {
                        // Hold the lock only while waiting for the next job, not while running it.
                        let job = job_receiver.lock().expect("job queue lock").recv();
                        let Ok(job) = job else { return };
                        let result = match job {
                            Job::Generate {
                                epoch,
                                coordinate,
                                generator,
                                layout,
                            } => JobResult::Generated {
                                epoch,
                                coordinate,
                                brick: Arc::new(generator.generate_brick(&layout, coordinate)),
                            },
                            Job::Mesh {
                                epoch,
                                coordinate,
                                version,
                                snapshot,
                                channels,
                            } => {
                                // A game with a bulk light hook says how bright each voxel is.
                                let center_light =
                                    channels.bulk_brightness(&snapshot.center, coordinate);
                                let neighbour_light: [Option<ChannelStorage>; 6] =
                                    std::array::from_fn(|face| {
                                        let neighbour =
                                            coordinate.neighbour(FaceDirection::ALL[face]);
                                        neighbour.and_then(|neighbour| {
                                            channels.bulk_brightness(
                                                &snapshot.neighbours[face],
                                                neighbour,
                                            )
                                        })
                                    });
                                let neighbourhood = BrickNeighbourhood {
                                    center: brick_channels(
                                        &snapshot.center,
                                        center_light.as_ref(),
                                        &channels,
                                    ),
                                    neighbours: std::array::from_fn(|face| {
                                        Some(brick_channels(
                                            &snapshot.neighbours[face],
                                            neighbour_light[face].as_ref(),
                                            &channels,
                                        ))
                                    }),
                                };
                                JobResult::Meshed {
                                    epoch,
                                    coordinate,
                                    version,
                                    mesh: mesh_brick(&neighbourhood, &table).pack(),
                                }
                            }
                        };
                        if result_sender.send(result).is_err() {
                            return;
                        }
                    }
                })
            })
            .collect();
        Self {
            settings,
            channels,
            table,
            bricks: HashMap::new(),
            generating: HashSet::new(),
            meshing: HashMap::new(),
            meshed: HashSet::new(),
            displayed: HashSet::new(),
            versions: HashMap::new(),
            load_offsets: offsets_within(settings.view_radius_bricks + 1),
            jobs: Some(job_sender),
            results,
            workers,
            scheduled_last_update: 0,
            epoch: 0,
        }
    }

    /// Jobs handed to workers and not yet finished.
    pub fn pending_jobs(&self) -> usize {
        self.generating.len() + self.meshing.len()
    }

    /// Bricks currently held in memory (whether or not drawn).
    pub fn loaded_brick_count(&self) -> usize {
        self.bricks.len()
    }

    /// The block in a voxel, if its brick is loaded.
    pub fn material_at(&self, coordinate: VoxelCoordinate) -> Option<u32> {
        let (brick, local) = coordinate.split();
        self.bricks
            .get(&brick)
            .map(|loaded| loaded.get(self.channels.blocks, local))
    }

    /// The state of the block in a voxel (0 where the game has no states), if its brick is loaded.
    pub fn state_at(&self, coordinate: VoxelCoordinate) -> Option<u32> {
        let (brick, local) = coordinate.split();
        self.bricks.get(&brick).map(|loaded| {
            self.channels
                .states
                .map_or(0, |states| loaded.get(states, local))
        })
    }

    /// The orientation of the block in a voxel (0 where the game has none), if its brick is loaded.
    pub fn orientation_at(&self, coordinate: VoxelCoordinate) -> Option<u32> {
        let (brick, local) = coordinate.split();
        self.bricks.get(&brick).map(|loaded| {
            self.channels
                .orientations
                .map_or(0, |orientations| loaded.get(orientations, local))
        })
    }

    /// Whether a voxel holds something that fills any part of it (anything but air), if its brick is
    /// loaded. This is what a crosshair can point at.
    pub fn is_solid_at(&self, coordinate: VoxelCoordinate) -> Option<bool> {
        let model = self.table.model_of(
            self.material_at(coordinate)?,
            self.state_at(coordinate)?,
            self.orientation_at(coordinate)?,
        );
        Some(self.table.is_solid(model))
    }

    /// Whether a voxel holds a whole cube that hides what is behind it, if its brick is loaded.
    pub fn is_opaque_at(&self, coordinate: VoxelCoordinate) -> Option<bool> {
        let model = self.table.model_of(
            self.material_at(coordinate)?,
            self.state_at(coordinate)?,
            self.orientation_at(coordinate)?,
        );
        Some(self.table.is_opaque_cube(model))
    }

    /// Tells the mesher a brick's edited contents changed, so it and its neighbours are meshed
    /// again from the new contents.
    pub fn brick_changed(&mut self, coordinate: BrickCoordinate) {
        self.bricks.remove(&coordinate);
        self.generating.remove(&coordinate);
        for affected in std::iter::once(coordinate).chain(
            FaceDirection::ALL
                .iter()
                .filter_map(|&f| coordinate.neighbour(f)),
        ) {
            *self.versions.entry(affected).or_insert(0) += 1;
            self.meshed.remove(&affected);
        }
    }

    /// Changes what is drawn from (as when a game changes the scales of its light): every brick is
    /// meshed again, and what is on the screen stays until its new mesh is ready.
    pub fn set_channels(&mut self, channels: ViewChannels) {
        if channels == self.channels {
            return;
        }
        self.channels = channels;
        let loaded: Vec<BrickCoordinate> = self.bricks.keys().copied().collect();
        for coordinate in loaded {
            *self.versions.entry(coordinate).or_insert(0) += 1;
        }
        self.meshed.clear();
        self.meshing.clear();
    }

    /// Forgets every brick and all work in progress, as when the viewer moves to another level whose
    /// bricks have nothing to do with the old ones. Returns the removal of every mesh displayed.
    pub fn reset(&mut self) -> Vec<MeshUpdate> {
        self.epoch += 1;
        self.bricks.clear();
        self.generating.clear();
        self.meshing.clear();
        self.meshed.clear();
        self.versions.clear();
        self.scheduled_last_update = 0;
        let mut displayed: Vec<BrickCoordinate> = self.displayed.drain().collect();
        displayed.sort();
        displayed.into_iter().map(MeshUpdate::Remove).collect()
    }

    fn version_of(&self, coordinate: BrickCoordinate) -> u64 {
        self.versions.get(&coordinate).copied().unwrap_or(0)
    }

    /// Collects finished jobs, unloads far bricks and schedules nearby work around `center`, reading
    /// from `level`. Returns what the renderer should change.
    pub fn update(&mut self, level: &LevelData, center: BrickCoordinate) -> Vec<MeshUpdate> {
        let mut updates = Vec::new();
        let view_radius = self.settings.view_radius_bricks;
        let keep_radius_squared = i128::from((view_radius + 2) * (view_radius + 2));

        while let Ok(result) = self.results.try_recv() {
            match result {
                JobResult::Generated {
                    epoch,
                    coordinate,
                    brick,
                } => {
                    if epoch == self.epoch && self.generating.remove(&coordinate) {
                        self.bricks.entry(coordinate).or_insert(brick);
                    }
                }
                JobResult::Meshed {
                    epoch,
                    coordinate,
                    version,
                    mesh,
                } => {
                    if epoch != self.epoch
                        || self.meshing.remove(&coordinate).is_none()
                        || version != self.version_of(coordinate)
                    {
                        continue; // unloaded, or changed since: the brick will be meshed again
                    }
                    self.meshed.insert(coordinate);
                    if mesh.is_empty() && !self.displayed.contains(&coordinate) {
                        continue;
                    }
                    if mesh.is_empty() {
                        self.displayed.remove(&coordinate);
                    } else {
                        self.displayed.insert(coordinate);
                    }
                    updates.push(MeshUpdate::Upload { coordinate, mesh });
                }
            }
        }

        // Unload what is out of range. A removal is reported for every displayed brick.
        let too_far: Vec<BrickCoordinate> = self
            .bricks
            .keys()
            .copied()
            .filter(|&coordinate| distance_squared(coordinate, center) > keep_radius_squared)
            .collect();
        for coordinate in too_far {
            self.bricks.remove(&coordinate);
            self.meshed.remove(&coordinate);
            self.meshing.remove(&coordinate);
            if self.displayed.remove(&coordinate) {
                updates.push(MeshUpdate::Remove(coordinate));
            }
        }

        let maximum_in_flight = self.workers.len() * 4;
        let mut scheduled = 0;
        for &[dx, dy, dz] in &self.load_offsets {
            if self.generating.len() + self.meshing.len() >= maximum_in_flight {
                break;
            }
            let Some(coordinate) = center.checked_offset(dx, dy, dz) else {
                continue;
            };
            if let Entry::Vacant(slot) = self.bricks.entry(coordinate) {
                if let Some(edited) = level.overrides.brick(coordinate) {
                    slot.insert(Arc::clone(edited));
                } else if !self.generating.contains(&coordinate)
                    && let Some(generator) = Self::generator_for(level, coordinate)
                {
                    self.generating.insert(coordinate);
                    self.jobs
                        .as_ref()
                        .expect("workers run until the mesher is dropped")
                        .send(Job::Generate {
                            epoch: self.epoch,
                            coordinate,
                            generator,
                            layout: Arc::clone(level.overrides.layout()),
                        })
                        .expect("workers are running");
                    scheduled += 1;
                    continue;
                }
            }
            let within_view = dx * dx + dy * dy + dz * dz <= view_radius * view_radius;
            if !within_view
                || self.meshed.contains(&coordinate)
                || self.meshing.contains_key(&coordinate)
            {
                continue;
            }
            if let Some(snapshot) = self.snapshot_of(coordinate) {
                let version = self.version_of(coordinate);
                self.meshing.insert(coordinate, version);
                self.jobs
                    .as_ref()
                    .expect("workers run until the mesher is dropped")
                    .send(Job::Mesh {
                        epoch: self.epoch,
                        coordinate,
                        version,
                        snapshot: Box::new(snapshot),
                        channels: self.channels.clone(),
                    })
                    .expect("workers are running");
                scheduled += 1;
            }
        }
        self.scheduled_last_update = scheduled;
        updates
    }

    /// The generator the level assigns to a brick's region, if the level has assigned one and this
    /// program has it.
    fn generator_for(
        level: &LevelData,
        coordinate: BrickCoordinate,
    ) -> Option<Arc<dyn TerrainGenerator>> {
        let id = level.terrain.assigned_generator(coordinate)?;
        level.terrain.generators().entry(id)?.content().cloned()
    }

    /// The brick and its six neighbours, if all of them are loaded.
    fn snapshot_of(&self, coordinate: BrickCoordinate) -> Option<NeighbourhoodSnapshot> {
        let center = Arc::clone(self.bricks.get(&coordinate)?);
        let mut neighbours = Vec::with_capacity(6);
        for face in FaceDirection::ALL {
            let neighbour = coordinate.neighbour(face)?;
            neighbours.push(Arc::clone(self.bricks.get(&neighbour)?));
        }
        Some(NeighbourhoodSnapshot {
            center,
            neighbours: neighbours.try_into().expect("exactly six faces"),
        })
    }

    /// Updates until no work is pending or schedulable, returning every change. For headless
    /// rendering and tests; an interactive viewer calls [`WorldMesher::update`] once per frame.
    pub fn settle(&mut self, level: &LevelData, center: BrickCoordinate) -> Vec<MeshUpdate> {
        let mut updates = Vec::new();
        loop {
            updates.extend(self.update(level, center));
            if self.pending_jobs() == 0 && self.scheduled_last_update == 0 {
                return updates;
            }
            std::thread::sleep(std::time::Duration::from_micros(200));
        }
    }
}

impl Drop for WorldMesher {
    fn drop(&mut self) {
        // Closing the job queue ends each worker's loop.
        self.jobs = None;
        for worker in self.workers.drain(..) {
            let _ = worker.join();
        }
    }
}
