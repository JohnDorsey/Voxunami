/// One level of a world: the terrain recipe and the player-made changes to it.
///
/// Terrain is *regenerated* from `terrain` wherever `overrides` has no brick; a brick in `overrides`
/// replaces the generated one entirely.
#[derive(Debug)]
pub struct LevelData {
    pub terrain: WorldTerrain,
    pub overrides: Grid,
    /// The default generator the level asked for, which may be unavailable right now.
    preferred_default_generator: NamespacedId,
}

/// Everything about a world that is saved: its levels, and the sections of plugins that are not
/// loaded.
///
/// Every level has its own terrain assignments and edited bricks. All levels share the world's
/// content (the channels, the registries) and its terrain generator versions, which levels differ
/// in by which of them they use.
#[derive(Debug)]
pub struct WorldData {
    pub world_seed: u64,
    /// Never empty. The first is the main level.
    levels: Vec<(NamespacedId, LevelData)>,
    /// Registry tables of kinds nobody supplied a registry for; kept so their ids stay meaningful.
    unknown_registry_tables: BTreeMap<NamespacedId, Vec<NamespacedId>>,
    opaque_sections: Vec<Section>,
    entities: EntityStore,
    /// The ships: in memory, or in files of their own that the world file lists.
    grids: GridStore,
}

/// Where the voxels of a brick come from.
#[derive(Debug, PartialEq, Eq)]
pub enum BrickSource {
    /// Changed since generation; stored in the world file.
    Edited(Arc<Brick>),
    Generated(Brick),
    /// No generator version has been assigned to this region yet.
    Unassigned,
    /// Generated by a plugin that is not loaded, so the terrain cannot be reproduced.
    MissingGenerator(NamespacedId),
}

#[derive(Debug, thiserror::Error)]
pub enum SaveError {
    #[error("channel {channel} holds ids from the registry {registry}, which has no table to save")]
    MissingRegistry {
        channel: NamespacedId,
        registry: NamespacedId,
    },
    #[error(
        "{0} ships are in memory, and a world file does not hold their voxels: save the world with the files of its ships"
    )]
    ShipsInMemory(usize),
    #[error("{grid} cannot be made into a file: {source}")]
    Ship { grid: GridId, source: ShipFileError },
}

/// Why a parked ship could not be brought back into memory.
#[derive(Debug, thiserror::Error)]
pub enum ShipLoadError {
    #[error("{0} is not a ship that is in a file")]
    NotParked(GridId),
    #[error("the file {file} of {grid} cannot be read: {source}")]
    Unreadable {
        grid: GridId,
        file: ShipFileName,
        source: io::Error,
    },
    #[error(
        "the file {file} of {grid} is not the file the world saved: its checksum is {found:#010x}, not {expected:#010x}"
    )]
    WrongFile {
        grid: GridId,
        file: ShipFileName,
        expected: u32,
        found: u32,
    },
    #[error("the file {file} of {grid} is damaged: {source}")]
    Damaged {
        grid: GridId,
        file: ShipFileName,
        source: ShipFileError,
    },
}

/// Why a ship could not be put into a file.
#[derive(Debug, thiserror::Error)]
pub enum ShipParkError {
    #[error("{0} is not a ship that is in memory")]
    NotLoaded(GridId),
    #[error("{grid} cannot be made into a file: {source}")]
    Encoding { grid: GridId, source: ShipFileError },
    #[error("the file of {grid} cannot be written: {source}")]
    Writing { grid: GridId, source: io::Error },
}

/// A world ready to be written to disk: the world file, and the files of the ships that were in memory. The files of ships that were already in
/// files are on disk and are only named.
///
/// The set is written in an order that leaves a world that can be read whatever happens: the files of the ships first, then the world file,
/// then the removal of the ship files the world file does not name. A save that stops before the world file is written leaves the
/// previous world file with every file it names; one that stops after it leaves the new one with every file it names.
#[derive(Debug)]
pub struct WorldSave {
    /// The world file.
    pub world: Vec<u8>,
    /// The files of the ships that were in memory, to write before the world file.
    pub new_ship_files: Vec<(ShipFileName, Vec<u8>)>,
    /// Every ship file the world file names: those, and those of the ships that were parked.
    pub named_ship_files: BTreeSet<ShipFileName>,
}

impl WorldSave {
    /// Writes the set: the ship files into `files`, then the world file by `write_world`, then removes from `files` what the world file
    /// does not name (the files of earlier saves, and what saves that did not finish left). An error before the world file is in place
    /// leaves the previous set as it was, apart from files nobody names; the removals cannot fail the save, since the new set is
    /// complete when they are made, and are made again by the next one.
    pub fn write_with(
        &self,
        files: &mut dyn ShipFiles,
        write_world: impl FnOnce(&[u8]) -> io::Result<()>,
    ) -> io::Result<()> {
        for (name, bytes) in &self.new_ship_files {
            files.write(name, bytes)?;
        }
        write_world(&self.world)?;
        if let Ok(names) = files.names() {
            for name in names {
                if !self.named_ship_files.contains(&name) {
                    let _ = files.remove(&name);
                }
            }
        }
        Ok(())
    }

    /// Writes the set with the world file at `path` (replaced all or nothing) and the ship files in `files`.
    pub fn write(&self, path: &std::path::Path, files: &mut dyn ShipFiles) -> io::Result<()> {
        self.write_with(files, |bytes| crate::file::write_atomically(path, bytes))
    }
}

/// Why a level cannot be added to a world.
#[derive(Clone, Debug, PartialEq, Eq, thiserror::Error)]
pub enum LevelError {
    #[error("the world already has a level {0}")]
    Duplicate(NamespacedId),
    #[error("level {0} uses different terrain generator versions than the world's other levels")]
    DifferentGenerators(NamespacedId),
    #[error("level {0} has different channels than the world's other levels")]
    DifferentChannels(NamespacedId),
}

fn generator_table(terrain: &WorldTerrain) -> Vec<NamespacedId> {
    table_of(terrain.generators())
}

fn table_of(registry: &dyn IdentifierRegistry) -> Vec<NamespacedId> {
    (0..registry.entry_count() as u32)
        .map(|raw| {
            registry
                .identifier_of_raw(raw)
                .expect("registry ids are dense")
                .clone()
        })
        .collect()
}

impl LevelData {
    pub fn new(terrain: WorldTerrain, overrides: Grid) -> Self {
        let preferred_default_generator = terrain
            .generators()
            .entry(terrain.default_generator())
            .expect("the default generator is in its own registry")
            .identifier()
            .clone();
        Self {
            terrain,
            overrides,
            preferred_default_generator,
        }
    }

    pub fn preferred_default_generator(&self) -> &NamespacedId {
        &self.preferred_default_generator
    }

    /// Chooses the generator for regions generated from now on, and remembers the choice in the file.
    pub fn set_default_generator(
        &mut self,
        generator: GeneratorId,
    ) -> Result<(), WorldTerrainError> {
        self.terrain.set_default_generator(generator)?;
        self.preferred_default_generator = self
            .terrain
            .generators()
            .entry(generator)
            .expect("set_default_generator accepted it")
            .identifier()
            .clone();
        Ok(())
    }

    /// The brick as the game should see it: the edited one if there is one, else the generated one.
    pub fn effective_brick(&self, coordinate: BrickCoordinate) -> BrickSource {
        if let Some(edited) = self.overrides.brick(coordinate) {
            return BrickSource::Edited(Arc::clone(edited));
        }
        match self.terrain.generate(self.overrides.layout(), coordinate) {
            GenerationOutcome::Generated(brick) => BrickSource::Generated(brick),
            GenerationOutcome::Unassigned => BrickSource::Unassigned,
            GenerationOutcome::MissingGenerator(identifier) => {
                BrickSource::MissingGenerator(identifier)
            }
        }
    }

    /// Drops edited bricks that are identical to what the generator produces, so the file only
    /// holds real changes. Bricks whose generator is unassigned or unavailable are kept, since they
    /// cannot be compared. Returns how many were dropped.
    pub fn prune_unmodified_overrides(&mut self) -> usize {
        let unchanged: Vec<BrickCoordinate> = self
            .overrides
            .bricks()
            .filter(|(coordinate, edited)| {
                matches!(
                    self.terrain.generate(self.overrides.layout(), *coordinate),
                    GenerationOutcome::Generated(generated) if generated == ***edited
                )
            })
            .map(|(coordinate, _)| coordinate)
            .collect();
        for coordinate in &unchanged {
            self.overrides.remove_brick(*coordinate);
        }
        unchanged.len()
    }
}

impl WorldData {
    /// A world with one level, its main level, named `main_level`.
    pub fn new(world_seed: u64, main_level: NamespacedId, level: LevelData) -> Self {
        Self {
            world_seed,
            levels: vec![(main_level, level)],
            unknown_registry_tables: BTreeMap::new(),
            opaque_sections: Vec::new(),
            entities: EntityStore::new(),
            grids: GridStore::new(),
        }
    }

    /// Adds a level after the existing ones. It must use the same channels and terrain generator
    /// versions as they do, and its generators must have been built from this world's seed: clients
    /// regenerate terrain from the seed they are told, so a level made with another seed shows them
    /// other terrain than the server has. Nothing here can check that.
    pub fn add_level(
        &mut self,
        id: NamespacedId,
        level: LevelData,
    ) -> Result<LevelIndex, LevelError> {
        if self.level_index(&id).is_some() {
            return Err(LevelError::Duplicate(id));
        }
        let main = self.main();
        if main.overrides.layout() != level.overrides.layout() {
            return Err(LevelError::DifferentChannels(id));
        }
        if generator_table(&main.terrain) != generator_table(&level.terrain) {
            return Err(LevelError::DifferentGenerators(id));
        }
        let index = LevelIndex::new(u32::try_from(self.levels.len()).expect("few levels"));
        self.levels.push((id, level));
        Ok(index)
    }

    pub fn level_count(&self) -> usize {
        self.levels.len()
    }

    /// Every level with its identifier, in index order.
    pub fn levels(&self) -> impl ExactSizeIterator<Item = (LevelIndex, &NamespacedId, &LevelData)> {
        self.levels
            .iter()
            .enumerate()
            .map(|(index, (id, level))| (LevelIndex::new(index as u32), id, level))
    }

    pub fn level(&self, index: LevelIndex) -> Option<&LevelData> {
        self.levels
            .get(index.get() as usize)
            .map(|(_, level)| level)
    }

    pub fn level_mut(&mut self, index: LevelIndex) -> Option<&mut LevelData> {
        self.levels
            .get_mut(index.get() as usize)
            .map(|(_, level)| level)
    }

    pub fn level_id(&self, index: LevelIndex) -> Option<&NamespacedId> {
        self.levels.get(index.get() as usize).map(|(id, _)| id)
    }

    pub fn level_index(&self, id: &NamespacedId) -> Option<LevelIndex> {
        self.levels
            .iter()
            .position(|(level_id, _)| level_id == id)
            .map(|position| LevelIndex::new(position as u32))
    }

    /// The level where players start.
    pub fn main(&self) -> &LevelData {
        &self.levels[0].1
    }

    pub fn main_mut(&mut self) -> &mut LevelData {
        &mut self.levels[0].1
    }

    /// The main level's data, dropping the rest of the world. How a game makes a level of its own
    /// kind to add to another world: build a new world and take its main level.
    pub fn into_main(mut self) -> LevelData {
        self.levels.swap_remove(0).1
    }

    /// Prunes every level; see [`LevelData::prune_unmodified_overrides`].
    pub fn prune_unmodified_overrides(&mut self) -> usize {
        self.levels
            .iter_mut()
            .map(|(_, level)| level.prune_unmodified_overrides())
            .sum()
    }

    /// The entities of the world.
    pub fn entities(&self) -> &EntityStore {
        &self.entities
    }

    pub fn entities_mut(&mut self) -> &mut EntityStore {
        &mut self.entities
    }

    /// The grids that are not the terrain of a level.
    pub fn grids(&self) -> &GridStore {
        &self.grids
    }

    pub fn grids_mut(&mut self) -> &mut GridStore {
        &mut self.grids
    }

    /// Where an entity in the frame of a ship is in the world, as a pose in the root grid of the ship's level: the place it is put at if its
    /// ship is lost. `None` for an entity that is not in a ship's frame, or in the frame of one the world does not know, or at a place
    /// the world cannot hold.
    fn place_in_the_world(&self, entity: &Entity) -> Option<EntityPose> {
        entity.pose.grid.root_level().is_none().then_some(())?;
        let (level, pose) = self.grids.frame_of(entity.pose.grid)?;
        let (position, orientation) =
            pose.place_in_world(entity.pose.position, entity.pose.orientation)?;
        Some(EntityPose::new(GridId::root(level), position, orientation))
    }

    /// Sections of plugins, in file order. Never interpreted here.
    pub fn opaque_sections(&self) -> &[Section] {
        &self.opaque_sections
    }

    /// Adds a plugin's section, or replaces its existing one of the same identifier.
    pub fn set_opaque_section(&mut self, section: Section) {
        match self
            .opaque_sections
            .iter_mut()
            .find(|existing| existing.identifier == section.identifier)
        {
            Some(existing) => *existing = section,
            None => self.opaque_sections.push(section),
        }
    }

    /// Serializes the world as a world file. `registries` supplies, per registry kind, the table translating raw ids
    /// to identifiers; it must include every kind a content channel uses (unless the kind came from
    /// a file whose plugin is missing, in which case the table is kept from loading).
    ///
    /// For a world in which no ship is in memory (a world of terrain, or one whose ships are all in files, which the world file names).
    /// A world with a ship in memory is saved with [`WorldData::save_with_ships`], which makes the file of the ship as well.
    pub fn save(
        &self,
        registries: &[(NamespacedId, &dyn IdentifierRegistry)],
    ) -> Result<Vec<u8>, SaveError> {
        if !self.grids.is_empty() {
            return Err(SaveError::ShipsInMemory(self.grids.len()));
        }
        let records = self.grid_records(&[]);
        let mut all = self.engine_sections(registries, Some(&records))?;
        all.extend(self.opaque_sections.iter().cloned());
        Ok(write_container(&all))
    }

    /// Serializes the world as a world file and a file for each ship that is in memory, as they stand. The files are named with numbers the
    /// world has not used before, so none is the name of a file that the world file on the disk still names. The ships that are in files
    /// are named by the world file as they are.
    pub fn save_with_ships(
        &mut self,
        registries: &[(NamespacedId, &dyn IdentifierRegistry)],
    ) -> Result<WorldSave, SaveError> {
        let format = self.ship_format(registries)?;
        let mut new_ship_files = Vec::with_capacity(self.grids.len());
        let mut loaded = Vec::with_capacity(self.grids.len());
        // (The files are all made before any number is taken, so a save that cannot be made does not use any up.)
        let mut made = Vec::with_capacity(self.grids.len());
        for (id, ship) in self.grids.iter() {
            let level = self
                .level_id(ship.level)
                .expect("a ship is in a level the world has");
            let bytes = format
                .encode(ship, level)
                .map_err(|source| SaveError::Ship { grid: id, source })?;
            made.push((
                id,
                level.clone(),
                ship.pose,
                ship.world_brick_bounds(),
                bytes,
            ));
        }
        for (id, level, pose, bounds, bytes) in made {
            let serial = self.grids.take_serial();
            loaded.push(GridRecord {
                id,
                level,
                pose,
                bounds,
                serial,
                checksum: crc32fast::hash(&bytes),
                waits_for_those_aboard: false,
            });
            new_ship_files.push((ShipFileName::new(id, serial), bytes));
        }
        let records = self.grid_records(&loaded);
        let mut named_ship_files: BTreeSet<ShipFileName> =
            new_ship_files.iter().map(|(name, _)| *name).collect();
        named_ship_files.extend(self.grids.parked().map(|(_, parked)| parked.file));
        let mut all = self.engine_sections(registries, Some(&records))?;
        all.extend(self.opaque_sections.iter().cloned());
        Ok(WorldSave {
            world: write_container(&all),
            new_ship_files,
            named_ship_files,
        })
    }

    /// The ships a world file lists: those that are in memory (as `loaded` records them, in order of id) and those that are in files, in
    /// order of id.
    fn grid_records(&self, loaded: &[GridRecord]) -> GridsRecord {
        let mut ships: Vec<GridRecord> = loaded.to_vec();
        ships.extend(self.grids.parked().map(|(id, parked)| {
            GridRecord {
                id,
                level: self
                    .level_id(parked.level)
                    .expect("a ship is in a level the world has")
                    .clone(),
                pose: parked.pose,
                bounds: parked.bounds,
                serial: parked.file.serial,
                checksum: parked.checksum,
                waits_for_those_aboard: parked.waits_for_those_aboard,
            }
        }));
        ships.sort_by_key(|ship| ship.id);
        GridsRecord {
            next: self.grids.next_id(),
            next_serial: self.grids.next_serial(),
            ships,
            tombstones: self
                .grids
                .tombstones()
                .map(|(id, successors)| (id, successors.to_vec()))
                .collect(),
        }
    }

    /// Puts a ship that is in a file into memory, where it was and moving as it was. Nothing changes if the file cannot be read, is not
    /// the one the world saved, or is damaged.
    pub fn load_ship(
        &mut self,
        id: GridId,
        files: &dyn ShipFiles,
        format: &ShipFormat,
    ) -> Result<(), ShipLoadError> {
        let ship = self.read_ship(id, files, format)?;
        self.admit_ship(id, ship)
    }

    /// The ship that is in a file, as it would be if it were brought in, without bringing it in: for whoever wants to see where it would
    /// land, and perhaps change it, before it does. Nothing changes in the world.
    pub fn read_ship(
        &self,
        id: GridId,
        files: &dyn ShipFiles,
        format: &ShipFormat,
    ) -> Result<MovingGrid, ShipLoadError> {
        let parked = self
            .grids
            .get_parked(id)
            .ok_or(ShipLoadError::NotParked(id))?
            .clone();
        let bytes = files
            .read(&parked.file)
            .map_err(|source| ShipLoadError::Unreadable {
                grid: id,
                file: parked.file,
                source,
            })?;
        let found = crc32fast::hash(&bytes);
        if found != parked.checksum {
            return Err(ShipLoadError::WrongFile {
                grid: id,
                file: parked.file,
                expected: parked.checksum,
                found,
            });
        }
        let contents = format
            .decode(&bytes)
            .map_err(|source| ShipLoadError::Damaged {
                grid: id,
                file: parked.file,
                source,
            })?;
        // The world file says where the ship is; the file says how it moved (a file that was shared may not say).
        let flight = contents.flight;
        Ok(MovingGrid {
            level: parked.level,
            pose: flight.map_or(parked.pose, |flight| flight.pose),
            linear_velocity: flight.map_or([0.0; 3], |flight| flight.linear_velocity),
            angular_velocity: flight.map_or([0.0; 3], |flight| flight.angular_velocity),
            mass: 0.0,
            centre_of_mass: [0.0; 3],
            held: flight.is_some_and(|flight| flight.held),
            frozen: false,
            on_pilot_logout: flight.map_or(Default::default(), |flight| flight.on_pilot_logout),
            voxels: contents.voxels,
            sections: contents.sections,
        })
    }

    /// Brings a ship that is in a file into memory as this ship (the one that [`WorldData::read_ship`] gave, changed or not). The ship
    /// that was in the file is gone from the world's list of ships in files, and the ship in memory is the one given.
    pub fn admit_ship(&mut self, id: GridId, ship: MovingGrid) -> Result<(), ShipLoadError> {
        self.grids
            .unpark(id, ship)
            .map(|_| ())
            .ok_or(ShipLoadError::NotParked(id))
    }

    /// Puts a ship that is in memory into a file, and out of memory. What is aboard it stays where it is, in the ship's frame. Nothing
    /// changes if the file cannot be written.
    pub fn park_ship(
        &mut self,
        id: GridId,
        waits_for_those_aboard: bool,
        files: &mut dyn ShipFiles,
        format: &ShipFormat,
    ) -> Result<(), ShipParkError> {
        let ship = self.grids.get(id).ok_or(ShipParkError::NotLoaded(id))?;
        let level = self
            .level_id(ship.level)
            .expect("a ship is in a level the world has");
        let bytes = format
            .encode(ship, level)
            .map_err(|source| ShipParkError::Encoding { grid: id, source })?;
        let file = ShipFileName::new(id, self.grids.take_serial());
        files
            .write(&file, &bytes)
            .map_err(|source| ShipParkError::Writing { grid: id, source })?;
        let ship = self
            .grids
            .get(id)
            .expect("the ship was in memory a moment ago");
        let level = ship.level;
        let parked = ParkedGrid {
            level,
            pose: ship.pose,
            bounds: ship.world_brick_bounds(),
            file,
            checksum: crc32fast::hash(&bytes),
            waits_for_those_aboard,
        };
        self.grids
            .park(id, parked)
            .expect("the ship was in memory a moment ago");
        Ok(())
    }

    /// The world's shape without its contents, as a small world file: seed, registry tables, channel
    /// layout, and each level's name and generator setup, but no generator assignments, edited
    /// bricks or plugin sections. A server sends this to a joining client, which loads it like a
    /// save and then learns the assignments and bricks it needs as they come into view.
    pub fn describe(
        &self,
        registries: &[(NamespacedId, &dyn IdentifierRegistry)],
    ) -> Result<Vec<u8>, SaveError> {
        Ok(write_container(&self.engine_sections(registries, None)?))
    }

    /// The identifiers of the entries of each registry, in order of their numbers: those the registries give, and the tables the file had of
    /// registries nobody supplied one for this time.
    fn registry_tables(
        &self,
        registries: &[(NamespacedId, &dyn IdentifierRegistry)],
    ) -> BTreeMap<NamespacedId, Vec<NamespacedId>> {
        let mut tables = self.unknown_registry_tables.clone();
        for (kind, registry) in registries {
            tables.insert(kind.clone(), table_of(*registry));
        }
        tables
    }

    /// What it takes to write the files of this world's ships and to read them again.
    pub fn ship_format(
        &self,
        registries: &[(NamespacedId, &dyn IdentifierRegistry)],
    ) -> Result<ShipFormat, SaveError> {
        ShipFormat::new(
            self.world_seed,
            &self.registry_tables(registries),
            Arc::clone(self.main().overrides.layout()),
        )
    }

    fn section(identifier: NamespacedId, payload: Vec<u8>) -> Section {
        Section {
            identifier,
            version: sections::SUPPORTED_VERSION,
            payload,
        }
    }

    /// Header, registries, channels and levels, with the levels' assignments and bricks, and the entities and the ships `grids` lists,
    /// if there is a list of ships (a world's description has none, and has none of the contents).
    fn engine_sections(
        &self,
        registries: &[(NamespacedId, &dyn IdentifierRegistry)],
        grids: Option<&GridsRecord>,
    ) -> Result<Vec<Section>, SaveError> {
        let with_contents = grids.is_some();
        let main = self.main();
        let mut tables = self.registry_tables(registries);
        tables.insert(
            sections::terrain_generator_registry_kind(),
            generator_table(&main.terrain),
        );

        let layout = main.overrides.layout();
        let channel_records: Vec<ChannelRecord> = layout
            .channels()
            .iter()
            .map(|channel| ChannelRecord {
                identifier: channel.identifier.clone(),
                default_value: channel.default_value,
                value_kind: channel.value_kind.clone(),
            })
            .collect();
        for channel in &channel_records {
            if let ChannelValueKind::Content { registry } = &channel.value_kind
                && !tables.contains_key(registry)
            {
                return Err(SaveError::MissingRegistry {
                    channel: channel.identifier.clone(),
                    registry: registry.clone(),
                });
            }
        }

        let sorted_bricks: Vec<Vec<BrickCoordinate>> = self
            .levels
            .iter()
            .map(|(_, level)| {
                if with_contents {
                    level.overrides.sorted_brick_coordinates()
                } else {
                    Vec::new()
                }
            })
            .collect();
        let to_write: Vec<LevelToWrite<'_>> = self
            .levels
            .iter()
            .zip(&sorted_bricks)
            .map(|((id, level), coordinates)| LevelToWrite {
                id,
                generators: GeneratorsRecord {
                    default_generator: level.preferred_default_generator.clone(),
                    assignment_cube_level: level.terrain.assignment_cube_level(),
                    leaves: if with_contents {
                        level
                            .terrain
                            .assignments()
                            .leaves()
                            .into_iter()
                            .map(|(cube, generator)| (cube, generator.map(|id| id.raw())))
                            .collect()
                    } else {
                        Vec::new()
                    },
                },
                bricks: coordinates
                    .iter()
                    .map(|&coordinate| {
                        (
                            coordinate,
                            &**level
                                .overrides
                                .brick(coordinate)
                                .expect("listed brick exists"),
                        )
                    })
                    .collect(),
            })
            .collect();
        let mut written = vec![
            Self::section(
                sections::header_id(),
                sections::encode_header(&Header {
                    world_seed: self.world_seed,
                    engine_version: env!("CARGO_PKG_VERSION").to_owned(),
                }),
            ),
            Self::section(
                sections::registries_id(),
                sections::encode_registries(
                    &tables
                        .into_iter()
                        .map(|(kind, entries)| RegistryTable { kind, entries })
                        .collect::<Vec<_>>(),
                ),
            ),
            Self::section(
                sections::channels_id(),
                sections::encode_channels(&channel_records),
            ),
            Self::section(sections::levels_id(), sections::encode_levels(&to_write)),
        ];
        // Entities are contents: a description does not have them, and a world that never had any does not
        // write the section, so it saves as it did before entities existed.
        if with_contents && sections::entities_are_saved(&self.entities) {
            written.push(Self::section(
                sections::entities_id(),
                sections::encode_entities_with(&self.entities, |entity| {
                    self.place_in_the_world(entity)
                }),
            ));
        }
        // Ships are contents as well, and a world that never had one does not write the section.
        if let Some(record) = grids
            && self.grids.is_worth_saving()
        {
            written.push(Self::section(
                sections::grids_id(),
                sections::encode_grids(record),
            ));
        }
        Ok(written)
    }
}

#[derive(Debug, thiserror::Error)]
pub enum LoadError {
    #[error(transparent)]
    Container(#[from] ContainerError),
    #[error("section {section} is malformed: {source}")]
    Section {
        section: NamespacedId,
        source: DecodeError,
    },
    #[error("the world file has no header")]
    MissingHeader,
    #[error(
        "section {section} is version {version}, newer than this program understands; loading would lose data"
    )]
    UnsupportedEngineSection { section: NamespacedId, version: u32 },
    #[error(
        "the world file has both a list of levels and the generator or brick sections of a file with one level"
    )]
    LevelsAndLegacySections,
    #[error("registry {0} is listed twice")]
    DuplicateRegistry(NamespacedId),
    #[error("registry {registry} lists {entry} twice")]
    DuplicateRegistryEntry {
        registry: NamespacedId,
        entry: NamespacedId,
    },
    #[error("channel {0} is listed twice")]
    DuplicateChannel(NamespacedId),
    #[error(
        "channel {channel} is defined by the game with different value meaning than the file records"
    )]
    ChannelKindMismatch { channel: NamespacedId },
    #[error(
        "the game defines channel {channel} using registry {registry}, but supplied no such registry"
    )]
    RegistryNotSupplied {
        channel: NamespacedId,
        registry: NamespacedId,
    },
    #[error("the file's tables do not account for its contents: {0}")]
    Translation(#[from] TranslationError),
    #[error("the world's channels do not form a valid layout: {0}")]
    Layout(#[from] GridLayoutError),
    #[error("the terrain could not be set up: {0}")]
    Terrain(#[from] WorldTerrainError),
    #[error("{ship} is listed in level {level}, which the world does not have")]
    ShipInUnknownLevel { ship: GridId, level: NamespacedId },
}

/// What the game supplies so a world file can be turned into runtime data.
pub struct LoadContext<'a> {
    /// The game's own channels, in its order. They keep their indices in the loaded grid; channels
    /// found only in the file are appended after them.
    pub channels: Vec<ChannelDefinition>,
    /// The content registries, by kind. Ids in the file are translated into these; identifiers the
    /// registry does not know become placeholders.
    pub registries: Vec<(NamespacedId, &'a mut dyn IdentifierRegistry)>,
    /// The terrain generator versions currently available.
    pub generators: Registry<Arc<dyn TerrainGenerator>>,
    /// Used as the default generator when the one a level asked for is unavailable.
    pub fallback_default_generator: NamespacedId,
    /// Used when the file has no generator section.
    pub assignment_cube_level: u8,
    /// The name of the one level of a file written before worlds had levels, which does not name it.
    pub legacy_level: NamespacedId,
}

impl std::fmt::Debug for LoadContext<'_> {
    fn fmt(&self, formatter: &mut std::fmt::Formatter<'_>) -> std::fmt::Result {
        formatter
            .debug_struct("LoadContext")
            .field("channels", &self.channels.len())
            .field(
                "registries",
                &self
                    .registries
                    .iter()
                    .map(|(kind, _)| kind.as_str())
                    .collect::<Vec<_>>(),
            )
            .field("generators", &self.generators.len())
            .field(
                "fallback_default_generator",
                &self.fallback_default_generator,
            )
            .finish()
    }
}

/// What was not as the game expected while loading. None of it is an error: the data is kept.
#[derive(Clone, Debug, Default, PartialEq, Eq)]
pub struct LoadReport {
    /// Content named in the file that no loaded plugin provides, as (registry kind, identifier).
    pub missing_content: Vec<(NamespacedId, NamespacedId)>,
    /// Channels in the file that the game does not define; their data is kept.
    pub extra_channels: Vec<NamespacedId>,
    /// Channels whose default value in the file differs from the game's; the game's is used.
    pub changed_channel_defaults: Vec<NamespacedId>,
    /// Plugin sections kept without being interpreted.
    pub opaque_sections: Vec<NamespacedId>,
    /// Registry kinds in the file that the game supplied no registry for.
    pub unknown_registry_kinds: Vec<NamespacedId>,
    /// Levels whose preferred default generator is unavailable, as (level, the generator it asked for).
    pub unavailable_default_generators: Vec<(NamespacedId, NamespacedId)>,
}

impl LoadReport {
    /// The plugins (namespaces) whose content is missing.
    pub fn missing_namespaces(&self) -> BTreeSet<String> {
        self.missing_content
            .iter()
            .map(|(_, identifier)| identifier.namespace().to_owned())
            .collect()
    }
}

/// The levels of a file, as they were written.
#[derive(Debug)]
enum ParsedLevels {
    Listed(Vec<LevelRecord>),
    /// A file written before worlds had levels: one level, with its generators and bricks in
    /// sections of their own.
    Legacy {
        generators: Option<GeneratorsRecord>,
        bricks: Vec<(BrickCoordinate, Brick)>,
    },
}

/// A level read from a file, before it is turned into runtime data. A file written before worlds had
/// levels may have no generator setup.
struct LevelToLoad {
    id: NamespacedId,
    generators: Option<GeneratorsRecord>,
    bricks: Vec<(BrickCoordinate, Brick)>,
}

/// A world file that has been read and checked but not yet turned into runtime data. This split lets
/// a game read the seed first and build its terrain generators from it.
#[derive(Debug)]
pub struct ParsedWorld {
    header: Header,
    registries: Vec<RegistryTable>,
    channels: Vec<ChannelRecord>,
    levels: ParsedLevels,
    entities: EntityStore,
    /// Where the entities in the frames of ships fall back to if their ships are lost.
    entity_fallbacks: BTreeMap<EntityId, EntityPose>,
    grids: Option<GridsRecord>,
    opaque_sections: Vec<Section>,
}

impl ParsedWorld {
    pub fn parse(bytes: &[u8]) -> Result<Self, LoadError> {
        let mut header = None;
        let mut registries = Vec::new();
        let mut channels = Vec::new();
        let mut listed_levels = None;
        let mut legacy_generators = None;
        let mut legacy_bricks = None;
        let mut entities = EntityStore::new();
        let mut entity_fallbacks = BTreeMap::new();
        let mut grids = None;
        let mut opaque_sections = Vec::new();
        for section in read_container(bytes)? {
            let known = [
                sections::header_id(),
                sections::registries_id(),
                sections::channels_id(),
                sections::levels_id(),
                sections::generators_id(),
                sections::override_bricks_id(),
                sections::entities_id(),
                sections::grids_id(),
            ]
            .contains(&section.identifier);
            if !known {
                opaque_sections.push(section);
                continue;
            }
            let readable = if section.identifier == sections::generators_id() {
                sections::reads_generators_version(section.version)
            } else {
                section.version == sections::SUPPORTED_VERSION
            };
            if !readable {
                return Err(LoadError::UnsupportedEngineSection {
                    section: section.identifier,
                    version: section.version,
                });
            }
            let wrap = |source| LoadError::Section {
                section: section.identifier.clone(),
                source,
            };
            let payload = &section.payload[..];
            if section.identifier == sections::header_id() {
                header = Some(sections::decode_header(payload).map_err(wrap)?);
            } else if section.identifier == sections::registries_id() {
                registries = sections::decode_registries(payload).map_err(wrap)?;
            } else if section.identifier == sections::channels_id() {
                channels = sections::decode_channels(payload).map_err(wrap)?;
            } else if section.identifier == sections::levels_id() {
                listed_levels = Some(sections::decode_levels(payload).map_err(wrap)?);
            } else if section.identifier == sections::entities_id() {
                (entities, entity_fallbacks) =
                    sections::decode_entities_with_fallbacks(payload).map_err(wrap)?;
            } else if section.identifier == sections::grids_id() {
                grids = Some(sections::decode_grids(payload).map_err(wrap)?);
            } else if section.identifier == sections::generators_id() {
                legacy_generators =
                    Some(sections::decode_generators(payload, section.version).map_err(wrap)?);
            } else {
                legacy_bricks = Some(sections::decode_override_bricks(payload).map_err(wrap)?);
            }
        }
        let levels = match listed_levels {
            Some(levels) => {
                if legacy_generators.is_some() || legacy_bricks.is_some() {
                    return Err(LoadError::LevelsAndLegacySections);
                }
                ParsedLevels::Listed(levels)
            }
            None => ParsedLevels::Legacy {
                generators: legacy_generators,
                bricks: legacy_bricks.unwrap_or_default(),
            },
        };
        Ok(Self {
            header: header.ok_or(LoadError::MissingHeader)?,
            registries,
            channels,
            levels,
            entities,
            entity_fallbacks,
            grids,
            opaque_sections,
        })
    }

    pub fn world_seed(&self) -> u64 {
        self.header.world_seed
    }

    /// Turns the file into runtime data, translating ids and keeping everything the game cannot
    /// interpret.
    pub fn load(self, context: LoadContext<'_>) -> Result<(WorldData, LoadReport), LoadError> {
        self.load_with_translator(context)
            .map(|(world, report, _)| (world, report))
    }

    /// Like [`ParsedWorld::load`], and also returns the translator for what the source supplies
    /// later. A client that learns a world from a server (which sends this same description, then
    /// bricks as they come into view) needs it to understand those bricks.
    pub fn load_with_translator(
        self,
        context: LoadContext<'_>,
    ) -> Result<(WorldData, LoadReport, SourceTranslator), LoadError> {
        let LoadContext {
            channels: game_channels,
            mut registries,
            generators: mut generator_registry,
            fallback_default_generator,
            assignment_cube_level,
            legacy_level,
        } = context;
        let mut report = LoadReport::default();

        // Registry tables: file id -> runtime id, per kind.
        let mut file_tables: HashMap<&NamespacedId, &Vec<NamespacedId>> = HashMap::new();
        for table in &self.registries {
            if file_tables.insert(&table.kind, &table.entries).is_some() {
                return Err(LoadError::DuplicateRegistry(table.kind.clone()));
            }
            let mut seen = BTreeSet::new();
            for entry in &table.entries {
                if !seen.insert(entry) {
                    return Err(LoadError::DuplicateRegistryEntry {
                        registry: table.kind.clone(),
                        entry: entry.clone(),
                    });
                }
            }
        }
        let generator_kind = sections::terrain_generator_registry_kind();
        let mut mappings: HashMap<NamespacedId, Vec<u32>> = HashMap::new();
        let mut unknown_registry_tables = BTreeMap::new();
        for table in &self.registries {
            if table.kind == generator_kind {
                continue;
            }
            match registries.iter_mut().find(|(kind, _)| *kind == table.kind) {
                Some((_, registry)) => {
                    let mapping = table
                        .entries
                        .iter()
                        .map(|identifier| match registry.raw_id_of(identifier) {
                            Some(raw) => raw,
                            None => {
                                report
                                    .missing_content
                                    .push((table.kind.clone(), identifier.clone()));
                                registry.register_missing_raw(identifier.clone())
                            }
                        })
                        .collect();
                    mappings.insert(table.kind.clone(), mapping);
                }
                None => {
                    report.unknown_registry_kinds.push(table.kind.clone());
                    unknown_registry_tables.insert(table.kind.clone(), table.entries.clone());
                }
            }
        }

        // Terrain generators, shared by every level.
        let generator_file_entries: &[NamespacedId] = file_tables
            .get(&generator_kind)
            .map_or(&[][..], |entries| &entries[..]);
        let generator_mapping: Vec<GeneratorId> = generator_file_entries
            .iter()
            .map(
                |identifier| match generator_registry.runtime_id(identifier) {
                    Some(id) => id,
                    None => {
                        report
                            .missing_content
                            .push((generator_kind.clone(), identifier.clone()));
                        generator_registry.register_missing(identifier.clone())
                    }
                },
            )
            .collect();
        let available = |identifier: &NamespacedId,
                         registry: &Registry<Arc<dyn TerrainGenerator>>| {
            registry
                .runtime_id(identifier)
                .filter(|id| registry.entry(*id).is_some_and(|entry| !entry.is_missing()))
        };

        // Each level's terrain; its bricks wait until the channels are known.
        let level_records: Vec<LevelToLoad> = match self.levels {
            ParsedLevels::Listed(records) => records
                .into_iter()
                .map(|record| LevelToLoad {
                    id: record.id,
                    generators: Some(record.generators),
                    bricks: record.bricks,
                })
                .collect(),
            ParsedLevels::Legacy { generators, bricks } => vec![LevelToLoad {
                id: legacy_level,
                generators,
                bricks,
            }],
        };

        let mut levels = Vec::with_capacity(level_records.len());
        for LevelToLoad {
            id,
            generators,
            bricks,
        } in level_records
        {
            let preferred_default = generators.as_ref().map_or_else(
                || fallback_default_generator.clone(),
                |record| record.default_generator.clone(),
            );
            let default_generator = match available(&preferred_default, &generator_registry) {
                Some(generator) => generator,
                None => {
                    report
                        .unavailable_default_generators
                        .push((id.clone(), preferred_default.clone()));
                    available(&fallback_default_generator, &generator_registry).ok_or_else(
                        || {
                            WorldTerrainError::GeneratorUnavailable(
                                fallback_default_generator.clone(),
                            )
                        },
                    )?
                }
            };
            let cube_level = generators
                .as_ref()
                .map_or(assignment_cube_level, |record| record.assignment_cube_level);
            let mut terrain =
                WorldTerrain::new(generator_registry.clone(), default_generator, cube_level)?;
            if let Some(record) = &generators {
                for (cube, file_id) in &record.leaves {
                    let generator = match file_id {
                        None => None,
                        Some(file_id) => Some(
                            *generator_mapping
                                .get(*file_id as usize)
                                .ok_or(TranslationError::GeneratorOutsideTable(*file_id))?,
                        ),
                    };
                    terrain.set_assignment(*cube, generator);
                }
            }
            levels.push((id, terrain, preferred_default, bricks));
        }

        // Channels: the game's first, then any only the file knows.
        for channel in &game_channels {
            if let ChannelValueKind::Content { registry } = &channel.value_kind
                && !registries.iter().any(|(kind, _)| kind == registry)
            {
                return Err(LoadError::RegistryNotSupplied {
                    channel: channel.identifier.clone(),
                    registry: registry.clone(),
                });
            }
        }
        let mut file_channel_index: HashMap<&NamespacedId, usize> = HashMap::new();
        for (index, record) in self.channels.iter().enumerate() {
            if file_channel_index
                .insert(&record.identifier, index)
                .is_some()
            {
                return Err(LoadError::DuplicateChannel(record.identifier.clone()));
            }
        }
        let translate_default = |record: &ChannelRecord| -> Result<u32, LoadError> {
            let ChannelValueKind::Content { registry } = &record.value_kind else {
                return Ok(record.default_value);
            };
            let table = file_tables.get(registry).ok_or_else(|| {
                TranslationError::ChannelRegistryNotInSource {
                    channel: record.identifier.clone(),
                    registry: registry.clone(),
                }
            })?;
            match mappings.get(registry) {
                Some(mapping) => mapping
                    .get(record.default_value as usize)
                    .copied()
                    .ok_or_else(|| {
                        TranslationError::ValueOutsideRegistry {
                            channel: record.identifier.clone(),
                            registry: registry.clone(),
                            value: record.default_value,
                            entries: table.len(),
                        }
                        .into()
                    }),
                None => Ok(record.default_value),
            }
        };
        let mut definitions = game_channels.clone();
        for definition in &game_channels {
            if let Some(&index) = file_channel_index.get(&definition.identifier) {
                let record = &self.channels[index];
                if record.value_kind != definition.value_kind {
                    return Err(LoadError::ChannelKindMismatch {
                        channel: definition.identifier.clone(),
                    });
                }
                if translate_default(record)? != definition.default_value {
                    report
                        .changed_channel_defaults
                        .push(definition.identifier.clone());
                }
            }
        }
        for record in &self.channels {
            if !game_channels
                .iter()
                .any(|channel| channel.identifier == record.identifier)
            {
                report.extra_channels.push(record.identifier.clone());
                definitions.push(ChannelDefinition {
                    identifier: record.identifier.clone(),
                    default_value: translate_default(record)?,
                    value_kind: record.value_kind.clone(),
                });
            }
        }
        let layout = Arc::new(GridLayout::new(definitions)?);
        let table_lengths: HashMap<&NamespacedId, usize> = file_tables
            .iter()
            .map(|(kind, entries)| (*kind, entries.len()))
            .collect();
        let translator = SourceTranslator::new(
            Arc::clone(&layout),
            &self.channels,
            &table_lengths,
            mappings,
            generator_mapping,
        )?;

        let levels = levels
            .into_iter()
            .map(|(id, terrain, preferred_default_generator, bricks)| {
                let mut overrides = Grid::new(Arc::clone(&layout));
                for (coordinate, brick) in bricks {
                    overrides
                        .insert_brick(coordinate, Arc::new(translator.translate_brick(brick)?))
                        .expect("the translated brick has one storage per layout channel");
                }
                Ok((
                    id,
                    LevelData {
                        terrain,
                        overrides,
                        preferred_default_generator,
                    },
                ))
            })
            .collect::<Result<Vec<_>, LoadError>>()?;

        // Every ship the file lists starts in its file: the server brings in those that are wanted.
        let level_index = |name: &NamespacedId| {
            levels
                .iter()
                .position(|(id, _)| id == name)
                .map(|position| LevelIndex::new(position as u32))
        };
        let grids = match self.grids {
            None => GridStore::new(),
            Some(record) => {
                let mut parked = Vec::with_capacity(record.ships.len());
                for ship in record.ships {
                    let level =
                        level_index(&ship.level).ok_or_else(|| LoadError::ShipInUnknownLevel {
                            ship: ship.id,
                            level: ship.level.clone(),
                        })?;
                    parked.push((
                        ship.id,
                        ParkedGrid {
                            level,
                            pose: ship.pose,
                            bounds: ship.bounds,
                            file: ShipFileName::new(ship.id, ship.serial),
                            checksum: ship.checksum,
                            waits_for_those_aboard: ship.waits_for_those_aboard,
                        },
                    ));
                }
                GridStore::from_saved(record.next, record.next_serial, parked, record.tombstones)
            }
        };
        // What the file puts in the frame of a ship it does not list is put where it was in the world: not in a frame that is not there.
        let mut entities = self.entities;
        let stranded: Vec<(EntityId, EntityPose)> = entities
            .iter()
            .filter(|entity| {
                entity.pose.grid.root_level().is_none() && !grids.knows(entity.pose.grid)
            })
            .map(|entity| {
                let place =
                    self.entity_fallbacks
                        .get(&entity.id)
                        .copied()
                        .unwrap_or(EntityPose::new(
                            GridId::MAIN,
                            entity.pose.position,
                            entity.pose.orientation,
                        ));
                (entity.id, place)
            })
            .collect();
        for (id, place) in stranded {
            entities
                .set_pose(id, place)
                .expect("an entity that is in the store can be moved in it");
        }
        // (That is a change to the entities that nobody was told of.)
        let _ = entities.take_changed();

        report.opaque_sections = self
            .opaque_sections
            .iter()
            .map(|s| s.identifier.clone())
            .collect();
        let world = WorldData {
            world_seed: self.header.world_seed,
            levels,
            unknown_registry_tables,
            opaque_sections: self.opaque_sections,
            entities,
            grids,
        };
        Ok((world, report, translator))
    }
}
