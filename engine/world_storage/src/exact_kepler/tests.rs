/// Mean anomalies and ratios at random: the ratio is a fraction of a power of two from 1 down to 2^-60.
fn any_ratio() -> impl Strategy<Value = f64> {
    (0..60i32, 0.5f64..1.0).prop_map(|(power, fraction)| libm::scalbn(fraction, -power).min(1.0))
}

proptest! {
    #[test]
    fn the_equation_holds_to_a_few_units_whatever_the_ratio_and_the_mean_anomaly(ratio in any_ratio(), mean in any::<u128>()) {
        let ellipse = Ellipse::new(ratio);
        let found = ellipse.anomaly(mean);
        // E - e / (2 pi) sin E = M, in turns, worked out again from the sine and cosine of the anomaly found (the reflected half turn for a mean anomaly past it).
        let reflected = mean > HALF_TURN;
        let (eccentric, mean) = if reflected { (found.turns.wrapping_neg(), mean.wrapping_neg()) } else { (found.turns, mean) };
        let (sine, _) = sine_and_cosine(eccentric);
        let sine_part = multiplied(ellipse.eccentricity_in_turns, sine, 126) << 2;
        let residual = (eccentric as i128) - sine_part - (mean as i128);
        prop_assert!(residual.abs() <= RESIDUAL, "residual {residual} of {RESIDUAL} allowed");
    }
}
