#[test]
fn the_minor_axis_is_the_root_of_one_less_the_square_of_the_eccentricity_rounded_down() {
    for ratio in [
        1.0,
        0.99,
        0.5,
        0.1,
        1.0e-3,
        1.0e-9,
        1.0e-12,
        1.0e-18,
        SMALLEST_RATIO,
    ] {
        let minor = Ellipse::new(ratio).minor as u128;
        // minor^2 <= ratio (2 - ratio) < (minor + 1)^2, all with 252 bits after the point
        let ratio_fixed = Ellipse::new(ratio).ratio as u128;
        let target = Wide::of_product(ratio_fixed, (2 * ONE as u128) - ratio_fixed);
        assert!(
            target.is_at_least(Wide::of_product(minor, minor)),
            "{ratio}"
        );
        assert!(
            !target.is_at_least(Wide::of_product(minor + 1, minor + 1)),
            "{ratio}"
        );
    }
}

