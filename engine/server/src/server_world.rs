    /// Queues text for one client as the answer to a command, delivered at the end of this tick.
    /// Text longer than [`MAXIMUM_COMMAND_LENGTH`] bytes is cut short.
    pub fn reply(&mut self, client: ClientId, text: &str) {
        let mut end = text.len().min(MAXIMUM_COMMAND_LENGTH);
        while !text.is_char_boundary(end) {
            end -= 1;
        }
        self.replies.push((client, text[..end].to_owned()));
    }

    /// The generated terrain of a brick, assigning a generator to its region first if it has none.
    /// Recently generated bricks are remembered.
    fn generated_brick(
        &mut self,
        level: LevelIndex,
        coordinate: BrickCoordinate,
    ) -> Result<Arc<Brick>, AccessError> {
        if let Some(remembered) = self
            .generated
            .borrow()
            .get((GridId::root(level), coordinate))
        {
            return Ok(Arc::clone(remembered));
        }
        let data = self
            .data
            .level_mut(level)
            .ok_or(AccessError::NoSuchLevel(level))?;
        data.terrain.assign_unassigned(coordinate);
        // (What the generator makes, whether or not the brick has been edited: the edits are not asked about here.)
        match data.terrain.generate(data.overrides.layout(), coordinate) {
            GenerationOutcome::Generated(brick) => {
                self.generations.set(self.generations.get() + 1);
                let brick = Arc::new(brick);
                self.generated
                    .borrow_mut()
                    .insert((GridId::root(level), coordinate), Arc::clone(&brick));
                Ok(brick)
            }
            GenerationOutcome::MissingGenerator(generator) => {
                Err(AccessError::TerrainUnavailable { generator })
            }
            GenerationOutcome::Unassigned => {
                unreachable!("the brick was just assigned a generator")
            }
        }
    }

    /// The brick the terrain of a ship makes at `coordinate`, in the ship's own coordinates: what its generator makes, if the brick is in the ship's extent, and
    /// the default brick if it is not or the ship has no terrain. Recently made bricks are remembered, with those of the terrain of the levels.
    fn generated_ship_brick(
        &self,
        grid: GridId,
        coordinate: BrickCoordinate,
    ) -> Result<Arc<Brick>, AccessError> {
        let ship = self
            .data
            .grids()
            .get(grid)
            .ok_or(AccessError::NoSuchGrid(grid))?;
        let layout = Arc::clone(ship.voxels.layout());
        let Some(terrain) = ship
            .terrain
            .filter(|terrain| terrain.extent.contains(coordinate))
        else {
            return Ok(Arc::new(Brick::new(&layout)));
        };
        if let Some(remembered) = self.generated.borrow().get((grid, coordinate)) {
            return Ok(Arc::clone(remembered));
        }
        // (The generators are the world's, one table for all its levels.)
        let entry = self
            .data
            .main()
            .terrain
            .generators()
            .entry(terrain.generator)
            .ok_or_else(|| AccessError::TerrainUnavailable {
                generator: "unknown:generator"
                    .parse()
                    .expect("constant identifier is valid"),
            })?;
        let generator = entry
            .content()
            .ok_or_else(|| AccessError::TerrainUnavailable {
                generator: entry.identifier().clone(),
            })?;
        let brick = Arc::new(generator.generate_brick(&layout, coordinate));
        self.generations.set(self.generations.get() + 1);
        self.generated
            .borrow_mut()
            .insert((grid, coordinate), Arc::clone(&brick));
        Ok(brick)
    }
