use std::collections::{BTreeMap, BTreeSet};
use std::sync::Arc;

use namespaced_id::NamespacedId;
use protocol::{ClientId, MAXIMUM_COMMAND_LENGTH, Tick, VoxelChange};
use voxel_grid::{Brick, ChannelIndex};
use voxel_space::{BrickCoordinate, GridId, LevelIndex, VoxelCoordinate};
use world_storage::{BrickSource, WorldData};

use crate::generated_cache::GeneratedBrickCache;

/// Who receives a game message.
#[derive(Clone, Copy, Debug, PartialEq, Eq)]
pub enum Audience {
    /// Every client that has joined.
    Everyone,
    /// One client. Dropped if that client has left.
    Client(ClientId),
    /// Every client whose watched region contains the brick of the level.
    Watching(LevelIndex, BrickCoordinate),
}

/// Why a voxel of the world cannot be read or changed.
#[derive(Clone, Debug, PartialEq, Eq, thiserror::Error)]
pub enum AccessError {
    /// The region has terrain this server cannot reproduce, because the plugin of its generator is
    /// not loaded. The world is intact, but this program cannot read or change that terrain.
    #[error("the terrain here was generated by {generator}, which is not loaded")]
    TerrainUnavailable { generator: NamespacedId },
    #[error("the world has no {0}")]
    NoSuchLevel(LevelIndex),
    #[error("the world has no {0}")]
    NoSuchGrid(GridId),
}

/// A voxel whose value in a watched channel changed (see [`ServerWorld::watch_channels`]).
#[derive(Clone, Copy, Debug, PartialEq, Eq)]
pub struct ChannelChange {
    pub grid: GridId,
    pub channel: ChannelIndex,
    pub voxel: VoxelCoordinate,
}

/// What happened to one brick during the current tick.
#[derive(Debug)]
pub(crate) struct BrickEdits {
    /// The brick had never been edited before this tick, so clients cannot apply `changes` to what
    /// they generate themselves: they are sent the whole brick instead.
    pub created: bool,
    pub changes: Vec<VoxelChange>,
}

#[derive(Debug)]
pub(crate) struct OutgoingGameMessage {
    pub audience: Audience,
    pub kind: NamespacedId,
    pub payload: Vec<u8>,
}

/// The world as game logic sees it during a tick: the terrain and edits of every level, and the way to
/// change them and to talk to clients. Everything done here is replicated to the clients that watch it.
#[derive(Debug)]
pub struct ServerWorld {
    data: WorldData,
    tick: Tick,
    clients: BTreeSet<ClientId>,
    generated: GeneratedBrickCache,
    pub(crate) edits: BTreeMap<(LevelIndex, BrickCoordinate), BrickEdits>,
    pub(crate) outgoing: Vec<OutgoingGameMessage>,
    pub(crate) replies: Vec<(ClientId, String)>,
    /// The channels whose changes are logged for whoever asks (see [`ServerWorld::take_changes`]).
    watched: BTreeSet<ChannelIndex>,
    changes: Vec<ChannelChange>,
}

impl ServerWorld {
    pub(crate) fn new(data: WorldData) -> Self {
        Self {
            data,
            tick: Tick::ZERO,
            clients: BTreeSet::new(),
            generated: GeneratedBrickCache::default(),
            edits: BTreeMap::new(),
            outgoing: Vec::new(),
            replies: Vec::new(),
            watched: BTreeSet::new(),
            changes: Vec::new(),
        }
    }

    /// Says which channels to log changes of, in the order they happen. Nothing is logged for any
    /// other channel, so a channel nobody asked about costs nothing. Replaces the earlier choice.
    pub fn watch_channels(&mut self, channels: BTreeSet<ChannelIndex>) {
        self.watched = channels;
        self.changes.clear();
    }

    /// The changes made to watched channels since the last call, in order. Only changes that altered
    /// a voxel are in it (setting a voxel to the value it has is not a change).
    pub fn take_changes(&mut self) -> Vec<ChannelChange> {
        std::mem::take(&mut self.changes)
    }

    pub fn data(&self) -> &WorldData {
        &self.data
    }

    pub(crate) fn data_mut(&mut self) -> &mut WorldData {
        &mut self.data
    }

    pub(crate) fn into_data(self) -> WorldData {
        self.data
    }

    /// The level with this identifier, if the world has one.
    pub fn level_index(&self, id: &NamespacedId) -> Option<LevelIndex> {
        self.data.level_index(id)
    }

    /// The tick being processed, or the last one completed between ticks.
    pub fn tick(&self) -> Tick {
        self.tick
    }

    pub(crate) fn set_tick(&mut self, tick: Tick) {
        self.tick = tick;
    }

    /// The clients that have joined, in the order they did.
    pub fn clients(&self) -> impl Iterator<Item = ClientId> + '_ {
        self.clients.iter().copied()
    }

    pub(crate) fn add_client(&mut self, client: ClientId) {
        self.clients.insert(client);
    }

    pub(crate) fn remove_client(&mut self, client: ClientId) {
        self.clients.remove(&client);
    }

    /// The value of a voxel, from the edited brick if there is one, else from the terrain generator.
    pub fn voxel(
        &mut self,
        level: LevelIndex,
        channel: ChannelIndex,
        at: VoxelCoordinate,
    ) -> Result<u32, AccessError> {
        let (coordinate, local) = at.split();
        let data = self
            .data
            .level(level)
            .ok_or(AccessError::NoSuchLevel(level))?;
        if let Some(edited) = data.overrides.brick(coordinate) {
            return Ok(edited.get(channel, local));
        }
        Ok(self.generated_brick(level, coordinate)?.get(channel, local))
    }

    /// The value that every voxel of a brick has in a channel, if they all have the same one: a way
    /// to know what a brick holds without looking at its voxels.
    pub fn uniform_value(
        &mut self,
        level: LevelIndex,
        channel: ChannelIndex,
        brick: BrickCoordinate,
    ) -> Result<Option<u32>, AccessError> {
        let data = self
            .data
            .level(level)
            .ok_or(AccessError::NoSuchLevel(level))?;
        if let Some(edited) = data.overrides.brick(brick) {
            return Ok(edited.channel(channel).uniform_value());
        }
        Ok(self
            .generated_brick(level, brick)?
            .channel(channel)
            .uniform_value())
    }

    /// Sets a voxel and replicates the change to the clients watching its brick. Returns whether
    /// the voxel changed; setting it to the value it has changes and sends nothing.
    pub fn set_voxel(
        &mut self,
        level: LevelIndex,
        channel: ChannelIndex,
        at: VoxelCoordinate,
        value: u32,
    ) -> Result<bool, AccessError> {
        let (coordinate, local) = at.split();
        let created = self
            .data
            .level(level)
            .ok_or(AccessError::NoSuchLevel(level))?
            .overrides
            .brick(coordinate)
            .is_none();
        if created {
            let mut generated = Brick::clone(&*self.generated_brick(level, coordinate)?);
            if !generated.set(channel, local, value) {
                return Ok(false);
            }
            self.data
                .level_mut(level)
                .expect("the level exists")
                .overrides
                .insert_brick(coordinate, Arc::new(generated))
                .expect("the generated brick has the grid's channels");
        } else if !self
            .data
            .level_mut(level)
            .expect("the level exists")
            .overrides
            .brick_mut(coordinate)
            .expect("the brick exists")
            .set(channel, local, value)
        {
            return Ok(false);
        }
        let entry = self.edits.entry((level, coordinate)).or_insert(BrickEdits {
            created,
            changes: Vec::new(),
        });
        entry.changes.push(VoxelChange {
            voxel: local,
            channel: u16::try_from(channel.get()).expect("channel positions fit in 16 bits"),
            value,
        });
        if self.watched.contains(&channel) {
            self.changes.push(ChannelChange {
                grid: GridId::root(level),
                channel,
                voxel: at,
            });
        }
        Ok(true)
    }

    /// Queues a message from the game for clients, delivered at the end of this tick.
    pub fn send(&mut self, audience: Audience, kind: NamespacedId, payload: Vec<u8>) {
        self.outgoing.push(OutgoingGameMessage {
            audience,
            kind,
            payload,
        });
    }

    /// Queues text for one client as the answer to a command, delivered at the end of this tick.
    /// Text longer than [`MAXIMUM_COMMAND_LENGTH`] bytes is cut short.
    pub fn reply(&mut self, client: ClientId, text: &str) {
        let mut end = text.len().min(MAXIMUM_COMMAND_LENGTH);
        while !text.is_char_boundary(end) {
            end -= 1;
        }
        self.replies.push((client, text[..end].to_owned()));
    }

    /// The generated terrain of a brick, assigning a generator to its region first if it has none.
    /// Recently generated bricks are remembered.
    fn generated_brick(
        &mut self,
        level: LevelIndex,
        coordinate: BrickCoordinate,
    ) -> Result<Arc<Brick>, AccessError> {
        if let Some(remembered) = self.generated.get((level, coordinate)) {
            return Ok(Arc::clone(remembered));
        }
        let data = self
            .data
            .level_mut(level)
            .ok_or(AccessError::NoSuchLevel(level))?;
        data.terrain.assign_unassigned(coordinate);
        match data.effective_brick(coordinate) {
            BrickSource::Generated(brick) => {
                let brick = Arc::new(brick);
                self.generated
                    .insert((level, coordinate), Arc::clone(&brick));
                Ok(brick)
            }
            BrickSource::MissingGenerator(generator) => {
                Err(AccessError::TerrainUnavailable { generator })
            }
            BrickSource::Edited(_) | BrickSource::Unassigned => {
                unreachable!("the brick has no edits and was just assigned a generator")
            }
        }
    }
}

#[cfg(test)]
mod tests {
    use std::sync::atomic::{AtomicUsize, Ordering};

    use terrain::{TerrainGenerator, WorldTerrain};
    use voxel_grid::{Grid, GridLayout};
    use world_storage::LevelData;
    use world_storage::test_support::{Game, Plugin, id, main_level_id};

    use super::*;

    /// A generator that counts how many bricks it is asked for.
    #[derive(Debug)]
    struct Counting {
        inner: Arc<dyn TerrainGenerator>,
        calls: Arc<AtomicUsize>,
    }

    impl TerrainGenerator for Counting {
        fn generate_brick(&self, layout: &GridLayout, coordinate: BrickCoordinate) -> Brick {
            self.calls.fetch_add(1, Ordering::Relaxed);
            self.inner.generate_brick(layout, coordinate)
        }
    }

    /// A level of flat ground whose generator counts its calls.
    fn counting_level(game: &Game, calls: &Arc<AtomicUsize>) -> LevelData {
        let flat = game.generator_registry();
        let inner = Arc::clone(
            flat.entry(flat.runtime_id(&id("base_terrain:flat_v1")).unwrap())
                .unwrap()
                .content()
                .unwrap(),
        );
        let counting: Arc<dyn TerrainGenerator> = Arc::new(Counting {
            inner,
            calls: Arc::clone(calls),
        });
        let mut generators = content_registry::Registry::new();
        let default = generators
            .register(id("base_terrain:flat_v1"), counting)
            .unwrap();
        let terrain = WorldTerrain::new(generators, default, 3).unwrap();
        let layout = Arc::new(GridLayout::new(game.channel_definitions()).unwrap());
        LevelData::new(terrain, Grid::new(layout))
    }

    fn block_channel(level: &LevelData) -> ChannelIndex {
        level
            .overrides
            .layout()
            .channel_index(&id("core:block"))
            .unwrap()
    }

    fn counting_world() -> (ServerWorld, ChannelIndex, Arc<AtomicUsize>) {
        let game = Game::new(&[Plugin::BaseBlocks]);
        let calls = Arc::new(AtomicUsize::new(0));
        let level = counting_level(&game, &calls);
        let channel = block_channel(&level);
        let data = WorldData::new(1, main_level_id(), level);
        (ServerWorld::new(data), channel, calls)
    }

    #[test]
    fn reading_terrain_nobody_has_edited_generates_each_brick_once() {
        let (mut world, channel, calls) = counting_world();
        for x in 0..32 {
            world
                .voxel(LevelIndex::MAIN, channel, VoxelCoordinate::new(x, 2, 3))
                .unwrap();
        }
        assert_eq!(calls.load(Ordering::Relaxed), 1);
        world
            .voxel(LevelIndex::MAIN, channel, VoxelCoordinate::new(40, 2, 3))
            .unwrap();
        assert_eq!(calls.load(Ordering::Relaxed), 2);
    }

    #[test]
    fn editing_after_reading_uses_the_remembered_brick_and_changes_only_what_was_set() {
        let (mut world, channel, calls) = counting_world();
        let level = LevelIndex::MAIN;
        let at = VoxelCoordinate::new(5, 5, 5);
        let neighbour = VoxelCoordinate::new(6, 5, 5);
        let before = world.voxel(level, channel, neighbour).unwrap();
        let original = world.voxel(level, channel, at).unwrap();
        assert!(world.set_voxel(level, channel, at, original + 1).unwrap());
        assert_eq!(calls.load(Ordering::Relaxed), 1);
        assert_eq!(world.voxel(level, channel, at).unwrap(), original + 1);
        assert_eq!(world.voxel(level, channel, neighbour).unwrap(), before);
        // The remembered brick is not changed by the edit: setting the original value back is
        // a change again only if the edit really happened.
        assert!(world.set_voxel(level, channel, at, original).unwrap());
    }

    #[test]
    fn levels_are_separate_worlds_with_their_own_terrain_and_edits_and_unknown_ones_are_errors() {
        let game = Game::new(&[Plugin::BaseBlocks]);
        let first_calls = Arc::new(AtomicUsize::new(0));
        let second_calls = Arc::new(AtomicUsize::new(0));
        let level = counting_level(&game, &first_calls);
        let channel = block_channel(&level);
        let mut data = WorldData::new(1, main_level_id(), level);
        let nether_id = id("test_content:nether");
        let nether = data
            .add_level(nether_id.clone(), counting_level(&game, &second_calls))
            .unwrap();
        let mut world = ServerWorld::new(data);
        assert_eq!(world.level_index(&nether_id), Some(nether));
        assert_eq!(world.level_index(&id("test_content:nowhere")), None);

        let at = VoxelCoordinate::new(1, 1, 1);
        let ground = world.voxel(LevelIndex::MAIN, channel, at).unwrap();
        // Editing one level leaves the other as it was, and each remembers its own bricks.
        assert!(world.set_voxel(nether, channel, at, ground + 1).unwrap());
        assert_eq!(world.voxel(nether, channel, at).unwrap(), ground + 1);
        assert_eq!(world.voxel(LevelIndex::MAIN, channel, at).unwrap(), ground);
        assert_eq!(world.data().main().overrides.brick_count(), 0);
        assert_eq!(
            world.data().level(nether).unwrap().overrides.brick_count(),
            1
        );
        assert_eq!(
            world.edits.keys().copied().collect::<Vec<_>>(),
            [(nether, at.split().0)]
        );
        assert_eq!(
            (
                first_calls.load(Ordering::Relaxed),
                second_calls.load(Ordering::Relaxed)
            ),
            (1, 1)
        );

        let nowhere = LevelIndex::new(9);
        assert_eq!(
            world.voxel(nowhere, channel, at),
            Err(AccessError::NoSuchLevel(nowhere))
        );
        assert_eq!(
            world.set_voxel(nowhere, channel, at, 1),
            Err(AccessError::NoSuchLevel(nowhere))
        );
    }

    #[test]
    fn replies_are_cut_to_the_longest_a_message_may_be_without_splitting_a_character() {
        let (mut world, _, _) = counting_world();
        let client = ClientId::new(1);
        world.reply(client, "short");
        let long = "é".repeat(MAXIMUM_COMMAND_LENGTH); // two bytes each
        world.reply(client, &long);
        assert_eq!(world.replies[0], (client, "short".to_owned()));
        assert_eq!(world.replies[1].1.len(), MAXIMUM_COMMAND_LENGTH);
        assert!(world.replies[1].1.chars().all(|character| character == 'é'));
        let odd = format!("{}é", "a".repeat(MAXIMUM_COMMAND_LENGTH - 1));
        world.reply(client, &odd);
        assert_eq!(world.replies[2].1, "a".repeat(MAXIMUM_COMMAND_LENGTH - 1));
    }
}
