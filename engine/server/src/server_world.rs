/// Who receives a game message.
#[derive(Clone, Copy, Debug, PartialEq, Eq)]
pub enum Audience {
    /// Every client that has joined.
    Everyone,
    /// One client. Dropped if that client has left.
    Client(ClientId),
    /// Every client whose watched region contains the brick of the level.
    Watching(LevelIndex, BrickCoordinate),
}

/// Why a voxel of the world cannot be read or changed.
#[derive(Clone, Debug, PartialEq, Eq, thiserror::Error)]
pub enum AccessError {
    /// The region has terrain this server cannot reproduce, because the plugin of its generator is
    /// not loaded. The world is intact, but this program cannot read or change that terrain.
    #[error("the terrain here was generated by {generator}, which is not loaded")]
    TerrainUnavailable { generator: NamespacedId },
    #[error("the world has no {0}")]
    NoSuchLevel(LevelIndex),
    #[error("the world has no {0}")]
    NoSuchGrid(GridId),
}

/// Why a ship could not be made or removed.
#[derive(Clone, Debug, PartialEq, Eq, thiserror::Error)]
pub enum DetachError {
    #[error("there are no voxels to make a ship of")]
    NoVoxels,
    #[error("the place the new ship would be in is outside what the world can hold")]
    OutOfRange,
    #[error(transparent)]
    Access(#[from] AccessError),
}

/// One piece of a ship that is being cut apart: the voxels it keeps, in the ship's own coordinates, and where its centre of mass is.
#[derive(Clone, Debug, PartialEq)]
pub struct SplitPart {
    pub voxels: BTreeSet<VoxelCoordinate>,
    pub centre_of_mass: [f32; 3],
}

/// Why a ship could not be split.
#[derive(Clone, Debug, PartialEq, Eq, thiserror::Error)]
pub enum SplitError {
    #[error(transparent)]
    Access(#[from] AccessError),
    #[error("a ship is split into at least two parts, each with a voxel")]
    NotTwoParts,
    #[error("a voxel is in two of the parts")]
    Overlap,
    #[error(
        "a ship with terrain, a planet, is not cut into parts: its blocks are mostly not stored, and a part would have none of its ground"
    )]
    HasTerrain,
}

/// Why a ship could not be put into a file or brought out of one.
