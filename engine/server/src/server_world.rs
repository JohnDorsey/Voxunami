    pub fn player_key(&self, client: ClientId) -> Option<PlayerKey> {
        self.clients.get(&client).copied()
    }

    /// The value of a voxel of a level's terrain, from the edited brick if there is one, else from the terrain generator. (Rules and games read voxels
    /// through [`GridView`](crate::GridView), which is this for the terrain of a level and the ship's own bricks for a ship.)
    pub(crate) fn root_voxel(
        &mut self,
        level: LevelIndex,
        channel: ChannelIndex,
        at: VoxelCoordinate,
    ) -> Result<u32, AccessError> {
        let (coordinate, local) = at.split();
        let data = self
            .data
            .level(level)
            .ok_or(AccessError::NoSuchLevel(level))?;
        if let Some(edited) = data.overrides.brick(coordinate) {
            return Ok(edited.get(channel, local));
        }
        Ok(self.generated_brick(level, coordinate)?.get(channel, local))
    }

    /// The value a voxel has in the terrain the generator makes, whatever has been built there since: a way to tell what a player
    /// built from the ground it stands on.
    pub(crate) fn root_generated_voxel(
        &mut self,
        level: LevelIndex,
        channel: ChannelIndex,
        at: VoxelCoordinate,
    ) -> Result<u32, AccessError> {
        let (coordinate, local) = at.split();
        self.data
            .level(level)
            .ok_or(AccessError::NoSuchLevel(level))?;
        Ok(self.generated_brick(level, coordinate)?.get(channel, local))
    }

    /// How many times the terrain generator has made a brick since the world was made: what reading terrain nobody has edited costs
    /// (ten milliseconds or more a brick for natural terrain), for whoever wants to know what a rule or a body asks of it.
    pub fn bricks_generated(&self) -> u64 {
        self.generations.get()
    }

    /// How many bricks the worker of [`ServerWorld::prefetch_ship_bricks`] has made and the world has taken in (the reads that found one made are not in
    /// [`ServerWorld::bricks_generated`]).
    pub fn bricks_prefetched(&self) -> u64 {
        self.take_prefetched();
        self.prefetched.get()
    }

    /// Asks a worker thread to make these bricks of a ship with terrain (a planet) before they are read: the bricks of its extent that are not remembered and
    /// not already asked for. What the world reads is the same whether a brick was made by the worker or where it was read (a generator makes the same
    /// brick every time), so asking changes no result, only whether a tick has to wait for the generator; and the worker's bricks are taken into the
    /// cache the next time the world reads a brick of a ship or [`ServerWorld::take_prefetched`] is called.
    pub fn prefetch_ship_bricks(
        &self,
        grid: GridId,
        bricks: impl IntoIterator<Item = BrickCoordinate>,
    ) {
        self.take_prefetched();
        let Some(ship) = self.data.grids().get(grid) else {
            return;
        };
        let Some(terrain) = ship.terrain else {
            return;
        };
        let Some(generator) = self
            .data
            .main()
            .terrain
            .generators()
            .entry(terrain.generator)
            .and_then(|entry| entry.content())
        else {
            return;
        };
        let layout = Arc::clone(ship.voxels.layout());
        let mut prefetcher = self.prefetcher.borrow_mut();
        for coordinate in bricks {
            if !terrain.extent.contains(coordinate)
                || self.generated.borrow().get((grid, coordinate)).is_some()
            {
                continue;
            }
            prefetcher.ask((grid, coordinate), generator, &layout);
        }
    }

    /// The same for the terrain of a level: asks the worker for these bricks, giving a region that has no generator the one it would be given when a brick of it
    /// is first read (as that read would, so it is a matter of when and not of what). The bricks are taken into the cache as those of ships are.
    pub fn prefetch_level_bricks(
        &mut self,
        level: LevelIndex,
        bricks: impl IntoIterator<Item = BrickCoordinate>,
    ) {
        self.take_prefetched();
        let grid = GridId::root(level);
        let Some(data) = self.data.level_mut(level) else {
            return;
        };
        let layout = Arc::clone(data.overrides.layout());
        let mut prefetcher = self.prefetcher.borrow_mut();
        for coordinate in bricks {
            if self.generated.borrow().get((grid, coordinate)).is_some() {
                continue;
            }
            let generator = data.terrain.assign_unassigned(coordinate);
            let Some(generator) = data
                .terrain
                .generators()
                .entry(generator)
                .and_then(|entry| entry.content())
            else {
                continue;
            };
            prefetcher.ask((grid, coordinate), generator, &layout);
        }
    }

    /// Takes the bricks the worker has finished into the cache.
    pub fn take_prefetched(&self) {
        let made = self.prefetcher.borrow_mut().finished();
        if made.is_empty() {
            return;
        }
        let mut cache = self.generated.borrow_mut();
        for (key, brick) in made {
            if cache.get(key).is_none() {
                cache.insert(key, Arc::new(brick));
                self.prefetched.set(self.prefetched.get() + 1);
            }
        }
    }

    /// The value that every voxel of a brick has in a channel, if they all have the same one: a way
    /// to know what a brick holds without looking at its voxels.
    pub(crate) fn root_uniform_value(
        &mut self,
        level: LevelIndex,
        channel: ChannelIndex,
        brick: BrickCoordinate,
    ) -> Result<Option<u32>, AccessError> {
        let data = self
            .data
            .level(level)
            .ok_or(AccessError::NoSuchLevel(level))?;
        if let Some(edited) = data.overrides.brick(brick) {
            return Ok(edited.channel(channel).uniform_value());
        }
        Ok(self
            .generated_brick(level, brick)?
            .channel(channel)
            .uniform_value())
    }

    /// Sets a voxel and replicates the change to the clients watching its brick. Returns whether
    /// the voxel changed; setting it to the value it has changes and sends nothing.
    pub(crate) fn set_root_voxel(
        &mut self,
        level: LevelIndex,
        channel: ChannelIndex,
        at: VoxelCoordinate,
        value: u32,
    ) -> Result<bool, AccessError> {
        let (coordinate, local) = at.split();
        let created = self
            .data
            .level(level)
            .ok_or(AccessError::NoSuchLevel(level))?
            .overrides
            .brick(coordinate)
            .is_none();
        if created {
            let mut generated = Brick::clone(&*self.generated_brick(level, coordinate)?);
            if !generated.set(channel, local, value) {
                return Ok(false);
            }
            self.data
                .level_mut(level)
                .expect("the level exists")
                .overrides
                .insert_brick(coordinate, Arc::new(generated))
                .expect("the generated brick has the grid's channels");
        } else if !self
            .data
            .level_mut(level)
            .expect("the level exists")
            .overrides
            .brick_mut(coordinate)
            .expect("the brick exists")
            .set(channel, local, value)
        {
            return Ok(false);
        }
        self.record_edit(GridId::root(level), created, channel, at, value);
        Ok(true)
    }

    /// Notes that a voxel changed, for the clients that watch its brick and for whoever asked for the changes of its channel.
    fn record_edit(
        &mut self,
        grid: GridId,
        brick_created: bool,
        channel: ChannelIndex,
        at: VoxelCoordinate,
        value: u32,
    ) {
        let (coordinate, local) = at.split();
        let entry = self.edits.entry((grid, coordinate)).or_insert(BrickEdits {
            created: brick_created,
            changes: Vec::new(),
        });
        entry.changes.push(VoxelChange {
            voxel: local,
            channel: u16::try_from(channel.get()).expect("channel positions fit in 16 bits"),
            value,
        });
        if self.watched.contains(&channel) {
            self.changes.push(ChannelChange {
                grid,
                channel,
                voxel: at,
            });
        }
    }

    /// The value of a voxel of a grid that is not the terrain of a level, in the grid's own coordinates: from the stored brick if there is one, else from the
    /// generator of the ship's terrain (if it has any, and the brick is in its extent), else the channel's default. Needs only a shared borrow of the world, so that
    /// a body can meet several ships at once (the bricks a generator makes are remembered behind a cell).
    pub fn moving_voxel(
        &self,
        grid: GridId,
        channel: ChannelIndex,
        at: VoxelCoordinate,
    ) -> Result<u32, AccessError> {
        let (coordinate, local) = at.split();
        let moving = self
            .data
            .grids()
            .get(grid)
            .ok_or(AccessError::NoSuchGrid(grid))?;
        if let Some(stored) = moving.voxels.brick(coordinate) {
            return Ok(stored.get(channel, local));
        }
        if moving.terrain.is_none() {
            return Ok(moving.voxels.layout().default_value(channel));
        }
        Ok(self
            .generated_ship_brick(grid, coordinate)?
            .get(channel, local))
    }

