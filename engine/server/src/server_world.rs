    /// Puts every ship that is on a rail where its rail says at the time of the world: `ticks_per_second` of the world's clock make a second (see
    /// [`WorldData::put_ships_on_their_rails`]). Its place is the same bits on every machine: the time is the tick itself, not a number of seconds, and the rest is the
    /// arithmetic of [`world_storage::rail`]. A ship the world cannot place is left where it is.
    ///
    /// What is in a level near a planet on a rail goes with the planet: a player or an item (in the level's own coordinates) and a ship, whether it is free or
    /// held, are moved by the planet's displacement, so that each stays where it is from the planet, and a player there falls to it and stands on it however
    /// fast the planet goes. (A ship's body is the plugin's: it simulates the ships a planet carries in a frame that goes with the planet, and puts them where
    /// they are against it. What this does for them is that they are with the planet in every tick before the bodies move, and not a tick behind it.) A ship's
    /// velocity and an entity's are left as they are; they are against the planet. See [`ServerWorld::planet_carrying`].
    pub(crate) fn apply_rails(&mut self, ticks_per_second: u32) {
        let time = RailTime::of_tick(self.data.clock(), ticks_per_second);
        self.carried_entities.clear();
        if !self
            .data
            .grids()
            .iter()
            .any(|(_, ship)| ship.rail.is_some())
        {
            self.carried_by.clear();
            self.carried_ships.clear();
            return;
        }
        // Who is carried by which planet, by where the planets are before they move.
        let carriers = self.carriers();
        let mut carried_entities: Vec<(EntityId, GridId)> = Vec::new();
        let mut now_carried: BTreeMap<EntityId, GridId> = BTreeMap::new();
        for entity in self.data.entities().iter() {
            let Some(level) = entity.pose.grid.root_level() else {
                continue;
            };
            if let Some(planet) = pick_carrier(
                &carriers,
                level,
                entity.pose.position,
                self.carried_by.get(&entity.id).copied(),
            ) {
                carried_entities.push((entity.id, planet));
                now_carried.insert(entity.id, planet);
            }
        }
        self.carried_by = now_carried;
        let mut carried_ships: Vec<(GridId, GridId)> = Vec::new();
        for (id, ship) in self.data.grids().iter() {
            if ship.terrain.is_some() || ship.rail.is_some() {
                continue;
            }
            if let Some(planet) = pick_carrier(
                &carriers,
                ship.level,
                ship.pose.position,
                self.carried_ships.get(&id).copied(),
            ) {
                carried_ships.push((id, planet));
            }
        }
        self.carried_ships = carried_ships.iter().copied().collect();
        let _ = self.data.put_ships_on_their_rails(time);
        let displacement_of = |world: &Self, planet: GridId| {
            let from = carriers
                .iter()
                .find(|carrier| carrier.id == planet)?
                .position;
            let to = world.data.grids().get(planet)?.pose.position;
            Some(from.displacement_to(to))
                .filter(|displacement| *displacement != Displacement::NONE)
        };
        for (entity, planet) in carried_entities {
            let Some(displacement) = displacement_of(self, planet) else {
                continue;
            };
            let Some(mut pose) = self.data.entities().get(entity).map(|entity| entity.pose) else {
                continue;
            };
            if let Some(position) = pose.position.displaced(displacement) {
                pose.position = position;
                if self.data.entities_mut().set_pose(entity, pose).is_ok() {
                    self.carried_entities.insert(entity, displacement);
                }
            }
        }
        for (ship, planet) in carried_ships {
            let Some(displacement) = displacement_of(self, planet) else {
                continue;
            };
            let Some(grid) = self.data.grids_mut().get_mut(ship) else {
                continue;
            };
            if let Some(position) = grid.pose.position.displaced(displacement) {
                grid.pose.position = position;
            }
        }
    }

    /// The planet that carried a ship in the last tick, if one did: the planet on a rail whose sphere of influence the ship was in (see
    /// [`ServerWorld::planet_carrying`]; a planet and a ship on a rail are carried by none). The bodies of a ship it carries are simulated in a frame that goes
    /// with it.
    pub fn carrier_of(&self, ship: GridId) -> Option<GridId> {
        self.carried_ships.get(&ship).copied()
    }

    /// How far the world moved an entity in this tick by carrying it with a planet on a rail (see [`ServerWorld::planet_carrying`]), if it did; the same displacement
    /// that it was moved by. A system that keeps a state of its own for an entity, as the body of a player is, moves that state by the same, so that it goes with the
    /// entity. It is told in the tick that the world carried the entity, to whatever runs after (the rules and the bodies), and is gone in the next call; and it is
    /// forgotten when the entity is put somewhere ([`ServerWorld::set_entity_pose`]): a pose put on it after is not carried.
    pub fn carried_by_rails(&self, entity: EntityId) -> Option<Displacement> {
        self.carried_entities.get(&entity).copied()
    }

    /// The planets on a rail, with where each is and how far it carries.
    fn carriers(&self) -> Vec<Carrier> {
        self.data
            .grids()
            .iter()
            .filter_map(|(id, ship)| {
                Some(Carrier {
                    id,
                    level: ship.level,
                    position: ship.pose.position,
                    radius: self.influence_radius(id)?,
                })
            })
            .collect()
    }

    /// How far from the middle of a planet on a rail it carries what is near it, in voxels: one and a half times the reach of its ground (the farthest brick
    /// its terrain makes, from the middle), and no more than the bodies of ships are exact in (`f32` is exact to a hundredth within 131 km). `None` for a ship that
    /// is not a planet or is not on a rail: it carries nothing.
    pub fn influence_radius(&self, planet: GridId) -> Option<f64> {
        let ship = self.data.grids().get(planet)?;
        ship.rail?;
        let extent = ship.terrain?.extent;
        let reach_in_bricks = [extent.min(), extent.max()]
            .into_iter()
            .flat_map(|corner| [corner.x(), corner.y(), corner.z()])
            .map(i128::abs)
            .max()
            .unwrap_or(0);
        let edge = voxel_space::BRICK_EDGE_LENGTH as f64;
        Some((reach_in_bricks as f64 * edge * INFLUENCE_PER_REACH).min(GREATEST_INFLUENCE))
    }

    /// The planet on a rail in a level that carries a place: the one whose sphere of influence ([`ServerWorld::influence_radius`]) it is in, and if it is in
    /// several, the smallest (a moon's before its planet's). What `carried_by` was carried by keeps carrying it a quarter farther out than its sphere, so that
    /// something at the edge is not taken and let go in turn.
    pub fn planet_carrying(
        &self,
        level: LevelIndex,
        position: WorldPosition,
        carried_by: Option<GridId>,
    ) -> Option<GridId> {
        pick_carrier(&self.carriers(), level, position, carried_by)
    }

    /// The acceleration of gravity at a place of the level of a planet on a rail for what falls with the planet: everything's pull but that of what the planet
    /// goes round (see [`ServerWorld::gravity_in`]).
    pub fn gravity_in_the_free_fall_of(&self, planet: GridId, position: WorldPosition) -> [f32; 3] {
        let level = self
            .data
            .grids()
            .get(planet)
            .map_or(LevelIndex::MAIN, |ship| ship.level);
        self.gravity_at_without(level, position, &self.what_it_goes_round(planet))
    }

    /// Removes a ship for good, as when it is destroyed, and returns it. Clients that watch it are told it is gone. What was aboard it
    /// (every entity whose frame it was, those of players who are away too) is put in the level the ship was in, where it was in the
    /// world and turned as it was, so it does not lose its place with the ship.
    pub fn remove_grid(&mut self, grid: GridId) -> Option<MovingGrid> {
        let ship = self.data.grids_mut().remove(grid)?;
        for id in self.data.entities().in_grid(grid) {
            let Some(aboard) = self.data.entities().get(id).map(|entity| entity.pose) else {
                continue;
            };
            // A place the world cannot hold is replaced by the ship's own, unturned: nothing is left in a frame that is gone.
            let (position, orientation) = ship
                .pose
                .place_in_world(aboard.position, aboard.orientation)
                .unwrap_or((ship.pose.position, ship.pose.orientation));
            let _ = self.data.entities_mut().set_pose(
                id,
                EntityPose::new(GridId::root(ship.level), position, orientation),
            );
        }
        Some(ship)
    }

    /// Cuts a ship into parts. Each part is a new ship (none keeps the id of the ship, which leaves a tombstone naming them all), in the
    /// same place and turned the same, with only its voxels (every channel of them), and it goes on at the speed its centre of mass had in
    /// the ship, which is the ship's speed there plus the turn of the ship. It is held or frozen if the ship was, and says the same of its
    /// pilot's logout. Whatever was aboard goes to the part whose block it is standing on (the first block along the way gravity pulls, within
    /// four voxels), else to the part nearest it, and is where it was in the ship's coordinates, which are the parts' too. The rules hear of
    /// the parts as of ships that came out of a file. Voxels of the ship that are in no part are lost with it. Nothing changes on an error.
    pub fn split_grid(
        &mut self,
        grid: GridId,
        parts: Vec<SplitPart>,
    ) -> Result<Vec<GridId>, SplitError> {
        let old = self
            .data
            .grids()
            .get(grid)
            .ok_or(AccessError::NoSuchGrid(grid))?;
        if old.terrain.is_some() {
            return Err(SplitError::HasTerrain);
        }
        if parts.len() < 2 || parts.iter().any(|part| part.voxels.is_empty()) {
            return Err(SplitError::NotTwoParts);
        }
        let mut owner: BTreeMap<VoxelCoordinate, usize> = BTreeMap::new();
        for (index, part) in parts.iter().enumerate() {
            for &voxel in &part.voxels {
                if owner.insert(voxel, index).is_some() {
                    return Err(SplitError::Overlap);
                }
            }
        }
        let layout = Arc::clone(old.voxels.layout());
        let channels: Vec<ChannelIndex> = layout.channel_indices().collect();
        let made: Vec<MovingGrid> = parts
            .iter()
            .map(|part| {
                let mut voxels = Grid::new(Arc::clone(&layout));
                for &voxel in &part.voxels {
                    for &channel in &channels {
                        voxels.set(channel, voxel, old.voxels.get(channel, voxel));
                    }
                }
                let centre = WorldPosition::new(BrickCoordinate::ORIGIN, part.centre_of_mass);
                let linear_velocity = old
                    .pose
                    .local_to_world(centre)
                    .map_or(old.linear_velocity, |place| old.velocity_at(place));
                MovingGrid {
                    level: old.level,
                    pose: old.pose,
                    linear_velocity,
                    angular_velocity: old.angular_velocity,
                    mass: 0.0,
                    centre_of_mass: part.centre_of_mass,
                    held: old.held,
                    frozen: old.frozen,
                    on_pilot_logout: old.on_pilot_logout,
                    voxels,
                    terrain: None,
                    rail: None,
                    sections: old.sections.clone(),
                }
            })
            .collect();
        // Which part each thing aboard goes to, decided while the ship is still there.
        let aboard: Vec<(EntityId, EntityPose, usize)> = self
            .data
            .entities()
            .in_grid(grid)
            .into_iter()
            .filter_map(|id| {
                let pose = self.data.entities().get(id)?.pose;
                Some((
                    id,
                    pose,
                    self.part_under(grid, pose.position, &owner, &parts),
                ))
            })
            .collect();
        let (_, ids) = self
            .data
            .grids_mut()
            .retire(
                grid,
                made.into_iter()
                    .map(|part| (part, LatticeTransform::IDENTITY))
                    .collect(),
            )
            .ok_or(AccessError::NoSuchGrid(grid))?;
        for (id, pose, part) in aboard {
            let _ = self.data.entities_mut().set_pose(
                id,
                EntityPose::new(ids[part], pose.position, pose.orientation),
            );
        }
        self.woken.extend(ids.iter().copied());
        Ok(ids)
    }

    /// The part of a ship that something at this place in it belongs to: the part of the block below it (along gravity, within four voxels), or
    /// else the part with the voxel nearest to it.
    fn part_under(
        &self,
        grid: GridId,
        place: WorldPosition,
        owner: &BTreeMap<VoxelCoordinate, usize>,
        parts: &[SplitPart],
    ) -> usize {
        let at = {
            let [x, y, z] = [0, 1, 2].map(|axis| {
                let brick = [place.brick().x(), place.brick().y(), place.brick().z()][axis];
                brick as f64 * 32.0 + f64::from(place.offset()[axis])
            });
            [x, y, z]
        };
        if let Ok(gravity) = self.gravity_in(grid, place) {
            let gravity = gravity.map(f64::from);
            let length = gravity.iter().map(|g| g * g).sum::<f64>().sqrt();
            if length > 0.0 {
                for step in 1..=8 {
                    let t = f64::from(step) * 0.5;
                    let voxel = VoxelCoordinate::new(
                        (at[0] + gravity[0] / length * t).floor() as i128,
                        (at[1] + gravity[1] / length * t).floor() as i128,
                        (at[2] + gravity[2] / length * t).floor() as i128,
                    );
                    if let Some(&part) = owner.get(&voxel) {
                        return part;
                    }
                }
            }
        }
        let distance = |voxel: &VoxelCoordinate| {
            let d = [
                voxel.x() as f64 + 0.5 - at[0],
                voxel.y() as f64 + 0.5 - at[1],
                voxel.z() as f64 + 0.5 - at[2],
            ];
            d[0] * d[0] + d[1] * d[1] + d[2] * d[2]
        };
        parts
            .iter()
            .enumerate()
            .filter_map(|(index, part)| {
                part.voxels
                    .iter()
                    .map(distance)
                    .min_by(f64::total_cmp)
                    .map(|nearest| (nearest, index))
            })
            .min_by(|a, b| a.0.total_cmp(&b.0).then(a.1.cmp(&b.1)))
            .map_or(0, |(_, index)| index)
    }

    /// Makes an empty ship in a level.
    pub fn create_grid(
        &mut self,
        level: LevelIndex,
        pose: GridPose,
    ) -> Result<GridId, AccessError> {
        let layout = Arc::clone(
            self.data
                .level(level)
                .ok_or(AccessError::NoSuchLevel(level))?
                .overrides
                .layout(),
        );
        Ok(self.data.grids_mut().create(MovingGrid {
            level,
            pose,
            linear_velocity: [0.0; 3],
            angular_velocity: [0.0; 3],
            mass: 0.0,
            centre_of_mass: [0.0; 3],
            held: false,
            frozen: false,
            on_pilot_logout: PilotLogout::Stay,
            voxels: Grid::new(layout),
            terrain: None,
            rail: None,
            sections: Vec::new(),
        }))
    }

    /// Queues a message from the game for clients, delivered at the end of this tick.
    pub fn send(&mut self, audience: Audience, kind: NamespacedId, payload: Vec<u8>) {
        self.outgoing.push(OutgoingGameMessage {
            audience,
            kind,
            payload,
        });
    }

    /// Queues text for one client as the answer to a command, delivered at the end of this tick.
    /// Text longer than [`MAXIMUM_COMMAND_LENGTH`] bytes is cut short.
    pub fn reply(&mut self, client: ClientId, text: &str) {
        let mut end = text.len().min(MAXIMUM_COMMAND_LENGTH);
        while !text.is_char_boundary(end) {
            end -= 1;
        }
        self.replies.push((client, text[..end].to_owned()));
    }

    /// The generated terrain of a brick, assigning a generator to its region first if it has none.
    /// Recently generated bricks are remembered.
    fn generated_brick(
        &mut self,
        level: LevelIndex,
        coordinate: BrickCoordinate,
    ) -> Result<Arc<Brick>, AccessError> {
        if let Some(remembered) = self
            .generated
            .borrow()
            .get((GridId::root(level), coordinate))
        {
            return Ok(Arc::clone(remembered));
        }
        // (A brick the worker has finished is taken in before the generator is run again.)
        self.take_prefetched();
        if let Some(remembered) = self
            .generated
            .borrow()
            .get((GridId::root(level), coordinate))
        {
            return Ok(Arc::clone(remembered));
        }
        let data = self
            .data
            .level_mut(level)
            .ok_or(AccessError::NoSuchLevel(level))?;
        data.terrain.assign_unassigned(coordinate);
        // (What the generator makes, whether or not the brick has been edited: the edits are not asked about here.)
        match data.terrain.generate(data.overrides.layout(), coordinate) {
            GenerationOutcome::Generated(brick) => {
                self.generations.set(self.generations.get() + 1);
                let brick = Arc::new(brick);
                self.generated
                    .borrow_mut()
                    .insert((GridId::root(level), coordinate), Arc::clone(&brick));
                Ok(brick)
            }
            GenerationOutcome::MissingGenerator(generator) => {
                Err(AccessError::TerrainUnavailable { generator })
            }
            GenerationOutcome::Unassigned => {
                unreachable!("the brick was just assigned a generator")
            }
        }
    }

    /// The brick the terrain of a ship makes at `coordinate`, in the ship's own coordinates: what its generator makes, if the brick is in the ship's extent, and
    /// the default brick if it is not or the ship has no terrain. Recently made bricks are remembered, with those of the terrain of the levels.
    fn generated_ship_brick(
        &self,
        grid: GridId,
        coordinate: BrickCoordinate,
    ) -> Result<Arc<Brick>, AccessError> {
        let ship = self
            .data
            .grids()
            .get(grid)
            .ok_or(AccessError::NoSuchGrid(grid))?;
        let layout = Arc::clone(ship.voxels.layout());
        let Some(terrain) = ship
            .terrain
            .filter(|terrain| terrain.extent.contains(coordinate))
        else {
            return Ok(Arc::new(Brick::new(&layout)));
        };
        if let Some(remembered) = self.generated.borrow().get((grid, coordinate)) {
            return Ok(Arc::clone(remembered));
        }
        // (Only when it is not there: this is the path of every voxel a body reads.)
        self.take_prefetched();
        if let Some(remembered) = self.generated.borrow().get((grid, coordinate)) {
            return Ok(Arc::clone(remembered));
        }
        // (The generators are the world's, one table for all its levels.)
        let entry = self
            .data
            .main()
            .terrain
            .generators()
            .entry(terrain.generator)
            .ok_or_else(|| AccessError::TerrainUnavailable {
                generator: "unknown:generator"
                    .parse()
                    .expect("constant identifier is valid"),
            })?;
        let generator = entry
            .content()
            .ok_or_else(|| AccessError::TerrainUnavailable {
                generator: entry.identifier().clone(),
            })?;
        let brick = Arc::new(generator.generate_brick(&layout, coordinate));
        self.generations.set(self.generations.get() + 1);
        self.generated
            .borrow_mut()
            .insert((grid, coordinate), Arc::clone(&brick));
        Ok(brick)
    }
