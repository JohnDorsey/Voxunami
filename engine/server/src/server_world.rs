use std::collections::{BTreeMap, BTreeSet};
use std::sync::Arc;

use namespaced_id::NamespacedId;
use protocol::{ClientId, Tick, VoxelChange};
use voxel_grid::{Brick, ChannelIndex};
use voxel_space::{BrickCoordinate, VoxelCoordinate};
use world_storage::{BrickSource, WorldData};

use crate::generated_cache::GeneratedBrickCache;

/// Who receives a game message.
#[derive(Clone, Copy, Debug, PartialEq, Eq)]
pub enum Audience {
    /// Every client that has joined.
    Everyone,
    /// One client. Dropped if that client has left.
    Client(ClientId),
    /// Every client whose watched region contains the brick.
    Watching(BrickCoordinate),
}

/// The region has terrain this server cannot reproduce, because the plugin of its generator is not
/// loaded. The world is intact, but this program cannot read or change that terrain.
#[derive(Clone, Debug, PartialEq, Eq, thiserror::Error)]
#[error("the terrain here was generated by {generator}, which is not loaded")]
pub struct TerrainUnavailable {
    pub generator: NamespacedId,
}

/// What happened to one brick during the current tick.
#[derive(Debug)]
pub(crate) struct BrickEdits {
    /// The brick had never been edited before this tick, so clients cannot apply `changes` to what
    /// they generate themselves: they are sent the whole brick instead.
    pub created: bool,
    pub changes: Vec<VoxelChange>,
}

#[derive(Debug)]
pub(crate) struct OutgoingGameMessage {
    pub audience: Audience,
    pub kind: NamespacedId,
    pub payload: Vec<u8>,
}

/// The world as game logic sees it during a tick: the terrain and edits, and the way to change them
/// and to talk to clients. Everything done here is replicated to the clients that watch it.
#[derive(Debug)]
pub struct ServerWorld {
    data: WorldData,
    tick: Tick,
    clients: BTreeSet<ClientId>,
    generated: GeneratedBrickCache,
    pub(crate) edits: BTreeMap<BrickCoordinate, BrickEdits>,
    pub(crate) outgoing: Vec<OutgoingGameMessage>,
}

impl ServerWorld {
    pub(crate) fn new(data: WorldData) -> Self {
        Self {
            data,
            tick: Tick::ZERO,
            clients: BTreeSet::new(),
            generated: GeneratedBrickCache::default(),
            edits: BTreeMap::new(),
            outgoing: Vec::new(),
        }
    }

    pub fn data(&self) -> &WorldData {
        &self.data
    }

    pub(crate) fn data_mut(&mut self) -> &mut WorldData {
        &mut self.data
    }

    pub(crate) fn into_data(self) -> WorldData {
        self.data
    }

    /// The tick being processed, or the last one completed between ticks.
    pub fn tick(&self) -> Tick {
        self.tick
    }

    pub(crate) fn set_tick(&mut self, tick: Tick) {
        self.tick = tick;
    }

    /// The clients that have joined, in the order they did.
    pub fn clients(&self) -> impl Iterator<Item = ClientId> + '_ {
        self.clients.iter().copied()
    }

    pub(crate) fn add_client(&mut self, client: ClientId) {
        self.clients.insert(client);
    }

    pub(crate) fn remove_client(&mut self, client: ClientId) {
        self.clients.remove(&client);
    }

    /// The value of a voxel, from the edited brick if there is one, else from the terrain generator.
    pub fn voxel(
        &mut self,
        channel: ChannelIndex,
        at: VoxelCoordinate,
    ) -> Result<u32, TerrainUnavailable> {
        let (coordinate, local) = at.split();
        if let Some(edited) = self.data.overrides.brick(coordinate) {
            return Ok(edited.get(channel, local));
        }
        Ok(self.generated_brick(coordinate)?.get(channel, local))
    }

    /// Sets a voxel and replicates the change to the clients watching its brick. Returns whether
    /// the voxel changed; setting it to the value it has changes and sends nothing.
    pub fn set_voxel(
        &mut self,
        channel: ChannelIndex,
        at: VoxelCoordinate,
        value: u32,
    ) -> Result<bool, TerrainUnavailable> {
        let (coordinate, local) = at.split();
        let created = self.data.overrides.brick(coordinate).is_none();
        if created {
            let mut generated = Brick::clone(&*self.generated_brick(coordinate)?);
            if !generated.set(channel, local, value) {
                return Ok(false);
            }
            self.data
                .overrides
                .insert_brick(coordinate, Arc::new(generated))
                .expect("the generated brick has the grid's channels");
        } else if !self
            .data
            .overrides
            .brick_mut(coordinate)
            .expect("the brick exists")
            .set(channel, local, value)
        {
            return Ok(false);
        }
        let entry = self.edits.entry(coordinate).or_insert(BrickEdits {
            created,
            changes: Vec::new(),
        });
        entry.changes.push(VoxelChange {
            voxel: local,
            channel: u16::try_from(channel.get()).expect("channel positions fit in 16 bits"),
            value,
        });
        Ok(true)
    }

    /// Queues a message from the game for clients, delivered at the end of this tick.
    pub fn send(&mut self, audience: Audience, kind: NamespacedId, payload: Vec<u8>) {
        self.outgoing.push(OutgoingGameMessage {
            audience,
            kind,
            payload,
        });
    }

    /// The generated terrain of a brick, assigning a generator to its region first if it has none.
    /// Recently generated bricks are remembered.
    fn generated_brick(
        &mut self,
        coordinate: BrickCoordinate,
    ) -> Result<Arc<Brick>, TerrainUnavailable> {
        if let Some(remembered) = self.generated.get(coordinate) {
            return Ok(Arc::clone(remembered));
        }
        self.data.terrain.assign_unassigned(coordinate);
        match self.data.effective_brick(coordinate) {
            BrickSource::Generated(brick) => {
                let brick = Arc::new(brick);
                self.generated.insert(coordinate, Arc::clone(&brick));
                Ok(brick)
            }
            BrickSource::MissingGenerator(generator) => Err(TerrainUnavailable { generator }),
            BrickSource::Edited(_) | BrickSource::Unassigned => {
                unreachable!("the brick has no edits and was just assigned a generator")
            }
        }
    }
}

#[cfg(test)]
mod tests {
    use std::sync::atomic::{AtomicUsize, Ordering};

    use terrain::{TerrainGenerator, WorldTerrain};
    use voxel_grid::{Grid, GridLayout};
    use world_storage::test_support::{Game, Plugin, id};

    use super::*;

    /// A generator that counts how many bricks it is asked for.
    #[derive(Debug)]
    struct Counting {
        inner: Arc<dyn TerrainGenerator>,
        calls: Arc<AtomicUsize>,
    }

    impl TerrainGenerator for Counting {
        fn generate_brick(&self, layout: &GridLayout, coordinate: BrickCoordinate) -> Brick {
            self.calls.fetch_add(1, Ordering::Relaxed);
            self.inner.generate_brick(layout, coordinate)
        }
    }

    fn counting_world() -> (ServerWorld, ChannelIndex, Arc<AtomicUsize>) {
        let game = Game::new(&[Plugin::BaseBlocks]);
        let calls = Arc::new(AtomicUsize::new(0));
        let mut generators = terrain_registry();
        let flat = game.generator_registry();
        let inner = Arc::clone(
            flat.entry(flat.runtime_id(&id("base_terrain:flat_v1")).unwrap())
                .unwrap()
                .content()
                .unwrap(),
        );
        let counting: Arc<dyn TerrainGenerator> = Arc::new(Counting {
            inner,
            calls: Arc::clone(&calls),
        });
        let default = generators
            .register(id("base_terrain:flat_v1"), counting)
            .unwrap();
        let terrain = WorldTerrain::new(generators, default, 3).unwrap();
        let layout = Arc::new(GridLayout::new(game.channel_definitions()).unwrap());
        let channel = layout.channel_index(&id("core:block")).unwrap();
        let data = WorldData::new(1, terrain, Grid::new(layout));
        (ServerWorld::new(data), channel, calls)
    }

    fn terrain_registry() -> content_registry::Registry<Arc<dyn TerrainGenerator>> {
        content_registry::Registry::new()
    }

    #[test]
    fn reading_terrain_nobody_has_edited_generates_each_brick_once() {
        let (mut world, channel, calls) = counting_world();
        for x in 0..32 {
            world.voxel(channel, VoxelCoordinate::new(x, 2, 3)).unwrap();
        }
        assert_eq!(calls.load(Ordering::Relaxed), 1);
        world
            .voxel(channel, VoxelCoordinate::new(40, 2, 3))
            .unwrap();
        assert_eq!(calls.load(Ordering::Relaxed), 2);
    }

    #[test]
    fn editing_after_reading_uses_the_remembered_brick_and_changes_only_what_was_set() {
        let (mut world, channel, calls) = counting_world();
        let at = VoxelCoordinate::new(5, 5, 5);
        let neighbour = VoxelCoordinate::new(6, 5, 5);
        let before = world.voxel(channel, neighbour).unwrap();
        let original = world.voxel(channel, at).unwrap();
        assert!(world.set_voxel(channel, at, original + 1).unwrap());
        assert_eq!(calls.load(Ordering::Relaxed), 1);
        assert_eq!(world.voxel(channel, at).unwrap(), original + 1);
        assert_eq!(world.voxel(channel, neighbour).unwrap(), before);
        // The remembered brick is not changed by the edit: setting the original value back is
        // a change again only if the edit really happened.
        assert!(world.set_voxel(channel, at, original).unwrap());
    }
}
