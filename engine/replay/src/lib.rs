//! Recording the stream a client receives, and playing it back.
//!
//! The client's whole picture of the world comes from the server's message stream, so a recording of
//! that stream is a complete replay of what the client saw. [`RecordingConnection`] wraps a client's
//! connection and writes every frame it receives to a file ([`file`] defines the format);
//! [`ReplayConnection`] reads such a file and plays the part of the server, so the unchanged client
//! code rebuilds the same views tick by tick, to be watched, rendered to video or checked.
//!
//! A recording needs no more of the server than the client had: terrain is regenerated by the client
//! from the world's seed, so a replay stays valid only as long as the terrain generators it names
//! produce what they produced when it was made, which the generator-version rule guarantees.

pub mod file;
mod playback;
mod recording;
mod welcome;

pub use file::{ReplayError, ReplayReader, ReplayWriter};
pub use playback::{ReplayConnection, ReplayEnd};
pub use recording::RecordingConnection;
