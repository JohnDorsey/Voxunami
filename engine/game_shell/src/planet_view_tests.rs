type Player = Session<Box<dyn Connection>, ExampleGame>;

/// The bricks of the planet that the renderer of a player holds, as the updates say.
#[derive(Default, Debug)]
struct Screen {
    planet: HashMap<BrickCoordinate, PackedBrickMesh>,
    /// Every picture of a brick of the planet that was ever put on the screen, in order (a wrong one that was soon replaced would show here).
    history: Vec<(BrickCoordinate, PackedBrickMesh)>,
    /// Anything else the updates said about the planet's grid or other grids.
    other_grids: usize,
}

impl Screen {
    fn apply(&mut self, planet: GridId, updates: Vec<MeshUpdate>) {
        for update in updates {
            match update {
                MeshUpdate::UploadGridBrick {
                    grid,
                    coordinate,
                    mesh,
                } => {
                    assert_eq!(grid, planet);
                    if mesh.is_empty() {
                        self.planet.remove(&coordinate);
                    } else {
                        self.history.push((coordinate, mesh.clone()));
                        self.planet.insert(coordinate, mesh);
                    }
                }
                MeshUpdate::RemoveGridBrick { grid, coordinate } => {
                    assert_eq!(grid, planet);
                    self.planet.remove(&coordinate);
                }
                MeshUpdate::RemoveGrid(grid) => {
                    assert_eq!(grid, planet);
                    self.planet.clear();
                    self.other_grids += 1;
                }
                MeshUpdate::GridPose { .. } => self.other_grids += 1,
                _ => {}
            }
        }
    }
}

/// The planet: a ship that is not moving, 20 bricks over the origin, generated by the ground of the world's terrain over the 17 x 17 x 17 bricks about its origin.
fn planet(world: &world_storage::WorldData, block: ChannelIndex, stone: u32) -> MovingGrid {
    let layout = Arc::clone(world.main().overrides.layout());
    let generator = world.main().terrain.default_generator();
    // A brick the server has stored from the start (brick 2, 0, 0): empty but for a block of stone at its +x edge, where the brick beside it (which the generator makes) is
    // ground, so that the block shows no face on that side if it is meshed with its neighbour and a face if it is meshed alone.
    let mut voxels = Grid::new(layout);
    voxels.set(block, VoxelCoordinate::new(95, 5, 5), stone);
    MovingGrid {
        level: LevelIndex::MAIN,
        pose: GridPose::new(
            WorldPosition::new(BrickCoordinate::new(0, 20, 0), [0.0; 3]),
            Orientation::IDENTITY,
        ),
        linear_velocity: [0.0; 3],
        angular_velocity: [0.0; 3],
        mass: 1.0e20,
        centre_of_mass: [0.0; 3],
        held: true,
        frozen: false,
        on_pilot_logout: PilotLogout::Stay,
        voxels,
        terrain: Some(GridTerrain {
            generator,
            extent: BrickBox::around(BrickCoordinate::ORIGIN, 8),
            mass: 1.0e20,
        }),
        sections: Vec::new(),
    }
}

/// Removes the planet when the test asks, as a rule of the game would.
#[derive(Debug)]
struct Remover {
    grid: GridId,
    asked: Arc<Mutex<bool>>,
}

impl Plugin for Remover {
    fn id(&self) -> NamespacedId {
        "test:remover".parse().unwrap()
    }

    fn register(&self, registrar: &mut Registrar<'_>) {
        let grid = self.grid;
        let asked = Arc::clone(&self.asked);
        registrar.system(
            SystemSpec::new("test:remover", Phase::Rules),
            move |context| {
                if std::mem::take(&mut *asked.lock().unwrap()) {
                    context.world().remove_grid(grid);
                }
            },
        );
    }
}

struct Rig {
    server: Server,
    connector: LoopbackConnector,
    queue: Arc<Mutex<Vec<VoxelCoordinate>>>,
    removal: Arc<Mutex<bool>>,
    planet: GridId,
    block: ChannelIndex,
}

impl Rig {
    fn new() -> Self {
        let content: ExampleContent = ExampleGame::new_content();
        let mut world = content.new_world(7);
        let block = content.view_channels().blocks;
        let air = content.game.raw_block("base_blocks:air");
        assert_eq!(air, AIR);
        let made = planet(&world, block, content.game.raw_block("base_blocks:stone"));
        let planet = world.grids_mut().create(made);
        let queue: Arc<Mutex<Vec<VoxelCoordinate>>> = Arc::default();
        let digger = Digger::new(planet, block, air, Arc::clone(&queue));
        let removal: Arc<Mutex<bool>> = Arc::default();
        let remover = Remover {
            grid: planet,
            asked: Arc::clone(&removal),
        };
        let plugins: Vec<Box<dyn Plugin>> = vec![
            Box::new(PlayersPlugin::new(true)),
            Box::new(digger),
            Box::new(remover),
        ];
        let (server, connector) =
            build_server_with_plugins::<ExampleGame>(&content, world, 3, plugins).unwrap();
        Self {
            server,
            connector,
            queue,
            removal,
            planet,
            block,
        }
    }

    fn connection(&self) -> Box<dyn Connection> {
        Box::new(self.connector.connect().unwrap())
    }

    /// A player at `position` (in the world), looking `pitch` degrees up.
    fn join(
        &mut self,
        connection: Box<dyn Connection>,
        who: u8,
        position: [f64; 3],
        pitch: f32,
    ) -> Player {
        let server = &mut self.server;
        Session::<_, ExampleGame>::connect(
            connection,
            &Identity::from_secret([who; 32]),
            Mode::Playing,
            3,
            camera_at(position, 0.0, pitch),
            || {
                server.step();
            },
        )
        .unwrap()
    }

    fn settle(&mut self, player: &mut Player, screen: &mut Screen) {
        player.send_pose();
        for _ in 0..3 {
            let server = &mut self.server;
            let updates = player
                .settle(|| {
                    server.step();
                })
                .unwrap();
            screen.apply(self.planet, updates);
        }
    }

    /// Asks the server to dig out the voxels of the planet (in the planet's own coordinates).
    fn dig(&self, voxels: &[VoxelCoordinate]) {
        self.queue.lock().unwrap().extend_from_slice(voxels);
    }

    /// The value the server has stored for a voxel of the planet, if it has stored its brick.
    fn stored_value_in_the_planet(&self, at: VoxelCoordinate) -> Option<u32> {
        let (brick, local) = at.split();
        self.server
            .world()
            .grids()
            .get(self.planet)?
            .voxels
            .brick(brick)
            .map(|stored| stored.get(self.block, local))
    }
}

/// The block the dug voxels become: the air of the example game, which is block 0.
const AIR: u32 = 0;

/// 14 voxels over the flat ground of the planet (whose top voxel is at height 9), a little off the middle of a brick; the planet is 20 bricks up.
const OVER_THE_PLANET: [f64; 3] = [5.5, 20.0 * 32.0 + 14.0, 5.5];

#[test]
fn a_player_over_a_planet_sees_the_bricks_its_generator_makes_around_the_camera() {
    let mut rig = Rig::new();
    let connection = rig.connection();
    let mut player = rig.join(connection, 1, OVER_THE_PLANET, 0.0);
    let mut screen = Screen::default();
    rig.settle(&mut player, &mut screen);

    // The ground of the planet within 3 bricks of the camera: one brick (y = 0) of grass on top for each integer point within 3 of the camera's, which is 29, and what the
    // stored brick uncovers.
    let mut shown: Vec<BrickCoordinate> = screen.planet.keys().copied().collect();
    shown.sort();
    let mut expected: Vec<BrickCoordinate> = (-3..=3)
        .flat_map(|x| (-3..=3).map(move |z| (x, z)))
        .filter(|(x, z)| x * x + z * z <= 9)
        .map(|(x, z)| BrickCoordinate::new(x, 0, z))
        .collect();
    // (The brick the server stored has no ground in it, so the top of the stone under it is drawn.)
    expected.push(BrickCoordinate::new(2, -1, 0));
    expected.sort();
    assert_eq!(shown, expected);
    // The renderer was told where the planet is.
    assert!(screen.other_grids >= 1);
    // And nothing was stored for it: it was drawn from the generator.
    let held = player.client().world().grids().get(rig.planet).unwrap();
    assert_eq!(
        held.voxels.brick_count(),
        1,
        "only the brick the server stored"
    );
    assert!(held.terrain.is_some());
    // The stored brick is meshed with the bricks the generator makes beside it, not alone: its block, at the edge of the brick where the ground beside it is, has no face
    // against that ground (and has five faces, the others).
    // (In every picture of it that was ever drawn, not only the last: the brick is told of in the same tick as the planet, before the mesher of the planet exists.)
    let pictures: Vec<&PackedBrickMesh> = screen
        .history
        .iter()
        .filter(|(coordinate, _)| *coordinate == BrickCoordinate::new(2, 0, 0))
        .map(|(_, mesh)| mesh)
        .collect();
    assert!(!pictures.is_empty());
    for mesh in pictures {
        let faces_of_the_block: Vec<FaceDirection> = mesh
            .quads
            .iter()
            .map(|quad| quad.unpack())
            .filter(|quad| quad.origin == [31, 5, 5])
            .map(|quad| quad.face)
            .collect();
        assert!(!faces_of_the_block.is_empty());
        assert!(
            !faces_of_the_block.contains(&FaceDirection::PositiveX),
            "{faces_of_the_block:?}"
        );
    }
}

#[test]
fn the_crosshair_of_a_player_over_a_planet_aims_at_the_ground_it_generates() {
    let mut rig = Rig::new();
    let connection = rig.connection();
    // Looking straight down.
    let mut player = rig.join(connection, 1, OVER_THE_PLANET, -90.0);
    let mut screen = Screen::default();
    rig.settle(&mut player, &mut screen);
    let hit = player.target().expect("the ground is within reach");
    assert_eq!(hit.grid, rig.planet);
    assert_eq!(hit.voxel, VoxelCoordinate::new(5, 9, 5));
    // The client knows what the block is, though it was not sent: it generated it.
    let grass = ExampleGame::new_content()
        .game
        .raw_block("base_blocks:grass");
    assert_eq!(player.target_content_of(&hit), Some((grass, 0)));
}

#[test]
fn an_edit_the_server_makes_to_a_planet_changes_what_the_player_sees_of_that_brick_and_no_other() {
    let mut rig = Rig::new();
    let connection = rig.connection();
    let mut player = rig.join(connection, 1, OVER_THE_PLANET, 0.0);
    let mut screen = Screen::default();
    rig.settle(&mut player, &mut screen);
    let before = screen.planet.clone();

    // Dig out three voxels of grass at the top of the ground in the brick the camera is over.
    let dug = [
        VoxelCoordinate::new(5, 9, 5),
        VoxelCoordinate::new(6, 9, 5),
        VoxelCoordinate::new(5, 9, 6),
    ];
    assert_eq!(
        rig.stored_value_in_the_planet(dug[0]),
        None,
        "nothing is stored before the dig"
    );
    rig.dig(&dug);
    rig.settle(&mut player, &mut screen);

    // The server stored the brick with the grass dug out of it, and the player was sent it.
    assert_eq!(rig.stored_value_in_the_planet(dug[0]), Some(AIR));
    assert_eq!(
        player
            .client()
            .world()
            .grids()
            .get(rig.planet)
            .unwrap()
            .voxels
            .brick_count(),
        2
    );
    let changed: Vec<BrickCoordinate> = before
        .iter()
        .filter(|(coordinate, mesh)| screen.planet.get(*coordinate) != Some(*mesh))
        .map(|(coordinate, _)| *coordinate)
        .collect();
    assert_eq!(changed, [BrickCoordinate::new(0, 0, 0)]);
    assert_eq!(screen.planet.len(), before.len());
    // The stored brick is meshed with its neighbours, which the generator makes, not alone: the only faces but the tops are the sides of the pit.
    let mesh = &screen.planet[&BrickCoordinate::new(0, 0, 0)];
    let elsewhere = mesh
        .quads
        .iter()
        .map(|quad| quad.unpack())
        .filter(|quad| {
            quad.face != FaceDirection::PositiveY
                && !((4..=7).contains(&quad.origin[0]) && (4..=7).contains(&quad.origin[2]))
        })
        .count();
    assert_eq!(elsewhere, 0, "faces against bricks that are not there");
}

#[test]
fn when_the_server_removes_a_planet_the_player_takes_it_down_and_stops_making_its_bricks() {
    let mut rig = Rig::new();
    let connection = rig.connection();
    let mut player = rig.join(connection, 1, OVER_THE_PLANET, 0.0);
    let mut screen = Screen::default();
    rig.settle(&mut player, &mut screen);
    assert_eq!(player.planet_count(), 1);
    assert!(!screen.planet.is_empty());

    *rig.removal.lock().unwrap() = true;
    rig.settle(&mut player, &mut screen);
    assert!(player.client().world().grids().is_empty());
    assert_eq!(player.planet_count(), 0);
    assert!(screen.planet.is_empty());
}

#[test]
fn a_recording_of_a_player_over_a_planet_shows_what_the_player_saw() {
    let directory =
        std::env::temp_dir().join(format!("voxunami_planet_view_{}", std::process::id()));
    std::fs::create_dir_all(&directory).unwrap();
    let path = directory.join("session.voxreplay");
    let mut rig = Rig::new();
    let recorded: Box<dyn Connection> =
        record_connection(rig.connector.connect().unwrap(), &path).unwrap();
    let mut player = rig.join(recorded, 1, OVER_THE_PLANET, 0.0);
    let mut screen = Screen::default();
    rig.settle(&mut player, &mut screen);
    rig.dig(&[VoxelCoordinate::new(5, 9, 5)]);
    rig.settle(&mut player, &mut screen);
    drop(player);

    let connection: Box<dyn Connection> = Box::new(open_recording(&path).unwrap());
    let mut replay = Session::<_, ExampleGame>::connect(
        connection,
        &Identity::generate(),
        Mode::Replaying,
        3,
        camera_at([0.0; 3], 0.0, 0.0),
        || {},
    )
    .unwrap();
    while replay.advance_one_tick().unwrap_or(false) {}
    let mut replay_screen = Screen::default();
    replay_screen.apply(rig.planet, replay.settle(|| {}).unwrap());

    assert!(replay_screen.planet.len() >= 29);
    assert_eq!(replay_screen.planet.len(), screen.planet.len());
    for (coordinate, mesh) in &screen.planet {
        assert_eq!(
            replay_screen.planet.get(coordinate),
            Some(mesh),
            "{coordinate:?}"
        );
    }
    std::fs::remove_dir_all(&directory).unwrap();
}
