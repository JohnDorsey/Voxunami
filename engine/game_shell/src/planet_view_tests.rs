//! A planet (a ship with terrain) in a player's session: the bricks around the camera are made by the client from the planet's generator, under the planet's pose;
//! the server's edits show; the crosshair aims at the generated ground; and a recording shows what the live player saw. The planet here has the flat ground of the example
//! game, 20 bricks above the terrain of the level (which is flat too, and so does not get in the way).

