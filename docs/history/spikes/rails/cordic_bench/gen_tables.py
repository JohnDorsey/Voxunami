"""THROWAWAY. CORDIC tables for 126-bit (as in engine/world_storage/src/exact_circle.rs) and 254-bit fixed point, written as Rust."""
from mpmath import mp, mpf, atan, pi, sqrt

mp.prec = 1000
MASK = (1 << 64) - 1


def limbs(value, count):
    return [(value >> (64 * index)) & MASK for index in range(count)]


def angles(count):
    fractional = 64 * count - 2
    return [int(mp.nint(atan(mpf(2) ** -step) / (2 * pi) * mpf(2) ** (64 * count))) for step in range(fractional + 1)]


def gain(count):
    fractional = 64 * count - 2
    product = mpf(1)
    for step in range(fractional + 1):
        product /= sqrt(1 + mpf(4) ** -step)
    return int(mp.nint(product * mpf(2) ** fractional))


# the repo's own constants, to make sure this generator makes the same numbers
repo_angles = [0x20000000000000000000000000000000, 0x12E4051D9DF308665688F6DAE35195B0, 0x09FB385B5EE39E8DDF43F3CA0921E0D2]
assert angles(2)[:3] == repo_angles, "angles differ from exact_circle.rs"
assert gain(2) == 0x26DD3B6A10D79699FD7E424AF5FF503A, "gain differs from exact_circle.rs"

lines = ["// generated by gen_tables.py", ""]
lines.append(f"pub const GAIN_128: i128 = {gain(2):#x};")
lines.append(f"pub const ANGLES_128: [u128; {len(angles(2))}] = [{', '.join(f'{value:#x}' for value in angles(2))}];")
for count in (2, 3, 4):
    lines.append(f"pub const GAIN_{count}: [u64; {count}] = [{', '.join(f'{limb:#x}' for limb in limbs(gain(count), count))}];")
    table = angles(count)
    rows = ", ".join("[" + ", ".join(f"{limb:#x}" for limb in limbs(value, count)) + "]" for value in table)
    lines.append(f"pub const ANGLES_{count}: [[u64; {count}]; {len(table)}] = [{rows}];")
with open("src/tables.rs", "w", newline="\n") as handle:
    handle.write("\n".join(lines) + "\n")
print("tables ok")
