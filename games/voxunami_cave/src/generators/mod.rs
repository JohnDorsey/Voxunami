//! Cave's ground: the terrain generators of its overworld, its planets and its great rivers, the family of planets a body file can ask for, and what
//! the engine is told so that it can draw them. The engine owns the machinery (density fields, coarse cells, the registry of generators); everything
//! that makes this world Cave's is here, under Cave's own names.
//!
//! A generator's identifier is a file format for as long as a world has used it (a world regenerates unedited ground from it). Until the first release
//! worlds are expendable and these may change; from it, a changed design is a new version.

mod great_river;
mod hills;
mod planet;
mod planet_data;
mod planet_family;
mod planet_node;

use std::sync::Arc;

use base_blocks::BaseBlockIds;
use content_registry::Registry;
use namespaced_id::NamespacedId;
use terrain::{GeneratorFamily, SurfaceLayers, TerrainGenerator, empty};
use voxel_grid::ChannelIndex;

pub use great_river::{
    GreatRivers, GreatRiversGenerator, RiverField, RiverKnot, RiverPath, great_rivers,
};
pub use hills::{RollingHillsSettings, rolling_hills};
pub use planet::{PlanetGenerator, PlanetGround, PlanetSettings, planet};
pub use planet_family::PlanetFamily;

fn identifier(text: &str) -> NamespacedId {
    text.parse().expect("constant identifiers are valid")
}

/// The terrain generator version of the overworld: rolling hills with sheet caves, grass, dirt and stone.
pub fn rolling_hills_generator_identifier() -> NamespacedId {
    identifier("voxunami_cave:rolling_hills_v1")
}

/// The terrain generator version of a planet with one hundredth of the radius of the Earth (63,710 voxels, `PlanetSettings::one_percent_of_earth`): a ball
/// with hills a kilometre wide, grass, dirt and stone, and the caves of the rolling hills. It is for a ship to be generated by (see `docs/planet-spec.md`).
pub fn small_planet_generator_identifier() -> NamespacedId {
    identifier("voxunami_cave:small_planet_v1")
}

/// The family of planets, for a world to make planets from data: its parameters are the bytes of `PlanetSettings` (`PlanetSettings::to_bytes`), and what it
/// makes from the settings of `PlanetSettings::one_percent_of_earth(seed)` is `voxunami_cave:small_planet_v1` (a test pins that). It is a file format like a
/// generator: a changed design is a new family.
pub fn planet_family_identifier() -> NamespacedId {
    identifier("voxunami_cave:planet_v1")
}

/// How the parameters of the planet family are written in a body file of a data pack (the family's data side; [`planet_family_identifier`] names both).
pub fn planet_family_data() -> Arc<dyn data_packs::FamilyData> {
    planet_data::PlanetData::shared()
}

/// The families of terrain generators Cave has, as a body file may name them.
pub fn family_data() -> Vec<(NamespacedId, Arc<dyn data_packs::FamilyData>)> {
    vec![(planet_family_identifier(), planet_family_data())]
}

/// The terrain generator version of space: air everywhere, for a level with nothing in it but what is put there (`terrain::empty`).
pub fn empty_generator_identifier() -> NamespacedId {
    identifier("voxunami_cave:empty_v1")
}

/// The terrain generator version of the great rivers (`great_rivers`, `docs/great-rivers-spec.md`): tubes of great river water across the universe, from a
/// billion light years wide to eighty metres, and air everywhere else. It is the terrain of the level of space of a new world.
pub fn great_rivers_generator_identifier() -> NamespacedId {
    identifier("voxunami_cave:great_rivers_v1")
}

/// What the ground of Cave is made of, by where in the ground it is: grass on top, dirt below it, stone under that.
pub fn surface_layers(ids: &BaseBlockIds) -> SurfaceLayers {
    SurfaceLayers {
        air: ids.air,
        surface: ids.grass,
        subsurface: ids.dirt,
        deep: ids.stone,
    }
}

/// The families of terrain generators Cave provides, writing blocks into `block_channel` of the world's grid layout.
pub fn generator_families(
    ids: &BaseBlockIds,
    block_channel: ChannelIndex,
) -> Vec<(NamespacedId, Arc<dyn GeneratorFamily>)> {
    vec![(
        planet_family_identifier(),
        Arc::new(PlanetFamily::new(block_channel, surface_layers(ids))),
    )]
}

/// The terrain generators Cave provides for a world with this seed, writing blocks into `block_channel` of the world's grid layout.
pub fn terrain_generators(
    ids: &BaseBlockIds,
    seed: u64,
    block_channel: ChannelIndex,
) -> Registry<Arc<dyn TerrainGenerator>> {
    let layers = surface_layers(ids);
    let mut generators: Registry<Arc<dyn TerrainGenerator>> = Registry::new();
    let hills: Arc<dyn TerrainGenerator> = Arc::new(rolling_hills(
        RollingHillsSettings::for_one_metre_voxels(seed),
        block_channel,
        layers,
    ));
    generators
        .register(rolling_hills_generator_identifier(), hills)
        .expect("the registry is empty");
    let small_planet: Arc<dyn TerrainGenerator> = Arc::new(planet(
        PlanetSettings::one_percent_of_earth(seed),
        block_channel,
        layers,
    ));
    generators
        .register(small_planet_generator_identifier(), small_planet)
        .expect("the identifier is new");
    let nothing: Arc<dyn TerrainGenerator> = Arc::new(empty(block_channel, layers.air));
    generators
        .register(empty_generator_identifier(), nothing)
        .expect("the identifier is new");
    let rivers: Arc<dyn TerrainGenerator> = Arc::new(great_rivers(
        seed,
        block_channel,
        ids.air,
        ids.great_river_water,
    ));
    generators
        .register(great_rivers_generator_identifier(), rivers)
        .expect("the identifier is new");
    generators
}
